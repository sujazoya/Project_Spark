#!/usr/bin/env python3
"""Offline integrity/geometry/material validation only. Does not test Unity compilation or Play Mode."""
import csv, json, glob, os, sys, re
from pathlib import Path
import trimesh
from PIL import Image
ROOT=Path(__file__).resolve().parent.parent
models=sorted((ROOT/'Models').glob('[0-9][0-9]_*.fbx'))
glbs=sorted((ROOT/'GLB').glob('[0-9][0-9]_*.glb'))
rows=list(csv.DictReader(open(ROOT/'Docs'/'Model_Manifest.csv', newline='')))
materials=list(csv.DictReader(open(ROOT/'Docs'/'Materials_Manifest.csv', newline='')))
placements=list(csv.DictReader(open(ROOT/'Docs'/'Scene_Placement.csv', newline='')))
pivots=list(csv.DictReader(open(ROOT/'Docs'/'Animation_Pivots.csv', newline='')))
errors=[]; checks=[]
def check(n,ok,reason=''):
 checks.append((n,bool(ok),reason))
 if not ok: errors.append(n+': '+reason)
check('37 modular FBX files',len(models)==37,str(len(models)))
check('37 modular GLB files',len(glbs)==37,str(len(glbs)))
check('Model manifest complete',len(rows)==37,str(len(rows)))
check('17 material families',len(materials)==17,str(len(materials)))
check('3 chairs and 1 wastebin',sum('Chair' in p['Instance'] for p in placements)==3 and sum(p['Instance']=='WasteBin' for p in placements)==1,'')
check('4 named animation pivots',len(pivots)==4,'')
check('85 texture maps',len(list((ROOT/'Textures').glob('*.png')))==85,'')
check('2 hologram shader source files',len(list((ROOT/'Shaders').glob('*.shader')))==2,'')
check('4 Unity C# source files',len(list((ROOT/'Unity').rglob('*.cs')))==4,'')
check('Assembled FBX showcase', (ROOT/'Models'/'ProjectSpark_ProGameRoom_COMPLETE_Showcase.fbx').exists(),'')
check('Assembled GLB showcase', (ROOT/'GLB'/'ProjectSpark_ProGameRoom_COMPLETE_Showcase.glb').exists(),'')
check('All source FBXs are binary 7400',all(p.read_bytes()[:27]==b'Kaydara FBX Binary  \x00\x1a\x00'+(7400).to_bytes(4,'little') for p in models),'')
check('FBX UV and normal layer names',all(b'LayerElementUV' in p.read_bytes() and b'LayerElementNormal' in p.read_bytes() for p in models),'')
tri=0; node_count=0;uv_ok=0; material_ok=0; checked=[]
for p in glbs:
 try:
  s=trimesh.load(p,force='scene',process=False)
  for mesh in s.geometry.values():
   tri+=len(mesh.faces)
   node_count+=1
   uv=getattr(mesh.visual,'uv',None)
   if uv is not None and len(uv)==len(mesh.vertices): uv_ok+=1
   if getattr(getattr(mesh.visual,'material',None),'name','').startswith('PS_'): material_ok+=1
  checked.append(p)
 except Exception as ex: errors.append(f'GLB load failed {p}: {ex}')
check('37 standalone GLBs parse',len(checked)==37,str(len(checked)))
check('All GLB submeshes have UVs',uv_ok==node_count,str(uv_ok)+'/'+str(node_count))
check('All GLB submeshes have PBR material slot names',material_ok==node_count,str(material_ok)+'/'+str(node_count))
expected_tri=sum(int(m['Triangles']) for m in rows)
check('Triangle totals match source manifest',tri==expected_tri,str(tri)+'/'+str(expected_tri))
for r in materials:
 n=r['MaterialID']
 paths=[ROOT/'Textures'/f'{n}_{s}.png' for s in ['BaseColor','Normal','UnityMaskMap','MetalRoughAO','Emission']]
 check('Texture family '+n,all(p.is_file() and Image.open(p).width>=512 for p in paths),'')
check('Unity shader literal names',all('Shader "ProjectSpark/RoomStudio/' in x.read_text() for x in (ROOT/'Shaders').glob('*.shader')),'')
check('Table preview avoids gameplay components',all(x not in (ROOT/'Unity/Runtime/PSRoomPreviewHost.cs').read_text() for x in ['AddComponent<SparkTerminal>', 'AddComponent<LevelGamePlayManager>', 'Instantiate(source)']),'')
# Check scene unscaled GLB dimensions against art plan.
s=trimesh.load(ROOT/'GLB'/'00_PS_Studio_FloorSlab.glb',force='scene')
b=s.bounds
check('18.2 x 14.4 meter floor footprint',abs((b[1,0]-b[0,0])-18.2)<.05 and abs((b[1,2]-b[0,2])-14.4)<.05,str(b.tolist()))
report={
 'project':'Project Spark Pro Futuristic Game Room',
 'model_count':len(models),'glb_count':len(glbs),'material_count':len(materials),
 'texture_count':len(list((ROOT/'Textures').glob('*.png'))),
 'triangles':tri,'mesh_pieces':node_count, 'uv_mesh_pieces':uv_ok, 'pbr_named_mesh_pieces':material_ok,
 'scene_instances':len(placements), 'chair_instances':3,'wastebin_instances':1, 'plant_instances':1,
 'unit_policy':'GLB meter geometry; FBX centimeters with scale metadata',
 'checks_passed':sum(x[1] for x in checks),'checks_total':len(checks),
 'errors':errors,'limitations':['No Unity compilation or Play Mode verification','No guaranteed performance on all hardware or all historical level meshes','Materials generated by included Unity Editor installer, not precompiled Unity binary assets']
}
(ROOT/'Docs'/'Offline_Validation_Report.json').write_text(json.dumps(report,indent=2))
(ROOT/'Docs'/'Offline_Validation_Report.txt').write_text('\n'.join(('PASS' if b else 'FAIL')+': '+n+((' — '+rs) if rs else '') for n,b,rs in checks)+'\n\n'+json.dumps(report,indent=2))
print(json.dumps(report,indent=2));sys.exit(1 if errors else 0)
