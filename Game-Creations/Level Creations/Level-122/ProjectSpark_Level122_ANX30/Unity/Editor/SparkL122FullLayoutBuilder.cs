                "Redundant inertial measurement and disagreement detection",
                "Bounded deterministic localization and uncertainty propagation",
                "Independent geofence / emergency-motion-inhibit safety control",
                "F1 radar PLL / F2 GNSS RF via / F3 inertial redundancy contact",
                "W385 trusted localization-ready open and supervised fresh reset",
                "Reproducible input traces, fault seeds, save and evidence generations"
