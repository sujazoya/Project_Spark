                return;
            }
            Renderer tableRenderer = selected.GetComponent<Renderer>();
            if (tableRenderer == null) tableRenderer = selected.GetComponentInChildren<Renderer>();
            if (tableRenderer == null)
            {
                Debug.LogError("[L122] Table_top has no measurable Renderer; cannot place or size the preview.");
                return;
            }
            GameObject imported = AssetDatabase.LoadAssetAtPath<GameObject>(source + "/Models_OBJ/353_L122_AssembledReference.obj");
            if (imported == null)
            {
                Debug.LogError("[L122] Assembled showcase OBJ unavailable.");
                return;
            }
            GameObject preview = new GameObject("L122_ANX30_VisualPreview_ONLY");
            Undo.RegisterCreatedObjectUndo(preview, "Create Level122 Visual Preview");
            preview.AddComponent<SparkL122VisualOnly>();
            GameObject visual = (GameObject)PrefabUtility.InstantiatePrefab(imported);
            visual.transform.SetParent(preview.transform, false);
            visual.name = "VisualShowcase_NotElectrical";
            SparkL122URPPBRMaterialBuilder.Bind(visual);
            float scale = Mathf.Min(PreviewWidth / PhysicalWidth, PreviewMaxDepth / PhysicalDepth);
