            string[] zoneNames = {
                "GNSS_A_RF_UNBOUND", "GNSS_B_RF_UNBOUND",
                "Radar_A_PhaseQuality_UNBOUND", "Radar_B_PhaseQuality_UNBOUND",
                "IMU_RedundantPair_UNBOUND", "SLAM_Confidence_UNBOUND", "Independent_MotionSafety_UNBOUND"
            };
            Vector3[] zonePositions = {
                new Vector3(.075f,.0014f,.108f),new Vector3(.138f,.0014f,.106f),
                new Vector3(.065f,.0014f,.015f),new Vector3(.147f,.0014f,.015f),
                new Vector3(-.124f,.0014f,.133f),new Vector3(-.133f,.0014f,.035f),
                new Vector3(-.030f,.0014f,-.108f)
