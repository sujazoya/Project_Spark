#!/usr/bin/env python3
"""Generate shared, tileable reference PBR material library with Unity masks.
UVs are autogenerated projections; these are not final production-authored bakes.
"""
from pathlib import Path
import json,csv
import numpy as np
from PIL import Image
ROOT=Path(__file__).resolve().parents[1];out=ROOT/'Textures';out.mkdir(exist_ok=True)
SETS={
'BrushedTitanium':((164,181,192),.87,.31,'brushed'),
'WhiteCeramicLab':((226,234,236),.10,.36,'ceramic'),
'HighVacuumStainlessSteel':((156,169,182),.91,.25,'brushed'),
'AnalyticalGraphite':((47,56,67),.26,.57,'carbon'),
'IndustrialLabFloor':((62,77,89),.47,.55,'floor'),
'OpticalGoldTerminal':((238,186,86),.92,.24,'brushed'),
'CopperVacuumTube':((179,109,61),.85,.42,'brushed'),
'SampleVaultGlass':((82,173,198),.06,.12,'glass'),
'SCADADeepBlue':((10,33,62),.08,.31,'holo'),
'CyanScientificHologram':((16,196,237),.03,.16,'holo'),
'PurpleSpectralHologram':((146,76,217),.03,.25,'holo'),
'ThermalWarningAmber':((236,129,43),.10,.24,'holo'),
'StatusGreen':((58,204,115),.10,.28,'holo'),
'StatusRed':((227,58,50),.12,.29,'holo'),
'CarbonaceousCoreRock':((72,69,72),.02,.86,'rock'),
'AsteroidMineralInclusions':((168,110,72),.29,.64,'rock'),
'HighReflectiveOre':((178,187,195),.72,.37,'rock'),
'QuartzSpectralOptics':((179,182,217),.08,.14,'glass')}
MAP={
'white':'WhiteCeramicLab','ceramic':'WhiteCeramicLab','titanium':'BrushedTitanium','silver':'HighVacuumStainlessSteel','structural':'BrushedTitanium',
'graphite':'AnalyticalGraphite','dark':'AnalyticalGraphite','black':'AnalyticalGraphite','panel':'SCADADeepBlue','floor':'IndustrialLabFloor',
'gold':'OpticalGoldTerminal','copper':'CopperVacuumTube','glass':'SampleVaultGlass','glassgold':'SampleVaultGlass','inert':'SampleVaultGlass',
'cyan':'CyanScientificHologram','holo':'CyanScientificHologram','blue':'CyanScientificHologram',
'purple':'PurpleSpectralHologram','laser':'PurpleSpectralHologram','spectrum':'PurpleSpectralHologram',
'amber':'ThermalWarningAmber','green':'StatusGreen','red':'StatusRed','core':'CarbonaceousCoreRock','regolith':'CarbonaceousCoreRock',
'mineral':'AsteroidMineralInclusions','ore':'HighReflectiveOre','vacuum':'QuartzSpectralOptics'}
assert all(k in MAP for k in __import__('build_level93').c.COLORS)
S=1024;A=np.arange(S,dtype=np.float32);X=A[None,:];Y=A[:,None]
rows=[]
for j,(name,(color,metal,rough,kind)) in enumerate(SETS.items()):
 rng=np.random.default_rng(93093+j)
 noise=rng.normal(0,1,(S,S)).astype('float32')
 crng=rng.integers(0,255,(64,64),dtype=np.uint8)
 coarse=np.asarray(Image.fromarray(crng).resize((S,S),Image.Resampling.BICUBIC),dtype=np.float32)/255-.5
 if kind=='brushed':h=.45*np.sin(X*.20)+.20*np.sin(X*1.05)+.2*noise+.3*coarse
 elif kind=='rock':h=.55*np.sin(X*.087)*np.sin(Y*.116)+.3*noise+.55*coarse
 elif kind=='floor':h=.25*np.sin(X*.03)*np.cos(Y*.04)+.22*noise+.18*coarse-.8*(((X%128)<2).astype('float32')+((Y%128)<2).astype('float32'))
 elif kind=='holo':h=.22*np.cos(X*.06)+.15*np.sin(Y*.21)+.11*noise+.15*coarse
 elif kind=='glass':h=.05*noise+.10*coarse
 else:h=.20*noise+.25*coarse
 albedo=np.clip(np.asarray(color)[None,None,:]*(1+.065*h[:,:,None]),0,255).astype('uint8')
 gx=np.gradient(h,axis=1);gy=np.gradient(h,axis=0)
 n=np.dstack((-gx*.13,-gy*.13,np.ones_like(h)));n=n/np.maximum(np.linalg.norm(n,axis=2,keepdims=True),.00001)
 normal=np.clip((n*.5+.5)*255,0,255).astype('uint8')
 r=np.clip(rough+.032*noise+.030*coarse,0,1);ao=np.clip(.91-.036*np.abs(noise)-.045*np.abs(coarse),0,1)
 metalImg=np.full((S,S),int(metal*255),dtype='uint8')
 mr=np.dstack((metalImg,(r*255).astype('uint8'),(ao*255).astype('uint8')))
 mask=np.dstack((metalImg,(ao*255).astype('uint8'),np.zeros_like(metalImg),(np.clip(1-r,0,1)*255).astype('uint8')))
 occ=np.dstack(((ao*255).astype('uint8'),)*3)
 emissionScale=1 if kind=='holo' else 0.0
 emi=np.clip(albedo.astype('float32')*(emissionScale*.45),0,255).astype('uint8')
 for suffix,arr,mode in [('Albedo',albedo,'RGB'),('Normal',normal,'RGB'),('MetalRoughAO',mr,'RGB'),('UnityMetallicSmoothness',mask,'RGBA'),('Occlusion',occ,'RGB'),('Emission',emi,'RGB')]:
  path=out/f'{name}_{suffix}.png';Image.fromarray(arr,mode).save(path,optimize=False,compress_level=5)
 rows.append(dict(Name=name,Metallic=metal,Roughness=rough,Pattern=kind,Size=S,TexturePrefix='Textures/'+name,UsedBy=';'.join(key for key,val in MAP.items() if val==name)))
 print('TEXTURE_SET',j+1,'/',len(SETS),name,flush=True)
(ROOT/'Texture_Manifest.json').write_text(json.dumps({'texture_sets':len(SETS),'map_count':len(SETS)*6,
 'resolution':[S,S],'uv':'generated planar UVs per mesh chunk, not manually authored atlas','material_to_texture_set':MAP,
 'sets':rows},indent=2))
with (ROOT/'Materials'/'Material_Assignment.csv').open('w',newline='') as f:
 w=csv.writer(f);w.writerow(['FBXMaterial','PBRTextureSet','Metallic','Roughness','TransparencyOrEmission']);
 for mat,pack in MAP.items():
  base=SETS[pack];w.writerow(['PS_'+mat,pack,base[1],base[2],base[3]])
print('DONE',len(SETS),'sets',len(SETS)*6,'images')
