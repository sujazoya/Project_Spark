#!/usr/bin/env python3
"""Offline structural verification only. Never claims Unity compilation or playable objective success."""
from pathlib import Path
import csv,json,math,hashlib,re
import numpy as np,trimesh
ROOT=Path('/mnt/data/ProjectSpark_Level92_HD_AAA')
m=json.loads((ROOT/'Model_Manifest.json').read_text())
checks=[]
def chk(name,pass_,detail=''):
 checks.append(dict(name=name,status='PASS' if pass_ else 'FAIL',detail=str(detail)))
 if not pass_:print('FAIL',name,detail,flush=True)
def csvread(name):
 with (ROOT/name).open(encoding='utf-8') as f:return list(csv.DictReader(f))
models=list((ROOT/'Models').glob('[0-9][0-9]_*.fbx'))
glbs=list((ROOT/'GLB').glob('[0-9][0-9]_*.glb'))
chk('98 modular FBX files',len(models)==98,len(models))
chk('98 modular GLB files',len(glbs)==98,len(glbs))
chk('manifest 98 models',len(m['models'])==98)
chk('model names unique',len(set(q['name'] for q in m['models']))==98)
chk('complete FBX alternative',(ROOT/'Models'/m['assembled_fbx']).exists())
chk('complete GLB alternative',(ROOT/'GLB'/m['assembled_glb']).exists())
chk('binary FBX 7400 signatures',all(p.open('rb').read(27).startswith(b'Kaydara FBX Binary') and int.from_bytes(p.open('rb').read(27)[23:27],'little')==7400 for p in models))
chk('GLB binary magic and version',all(p.open('rb').read(8)==b'glTF\x02\x00\x00\x00' for p in glbs))
chk('all model file sizes nonempty',all(p.stat().st_size>1000 for p in models+glbs))
chk('FBX and GLB names paired',all((ROOT/'Models'/q['fbx']).exists() and (ROOT/'GLB'/q['glb']).exists() for q in m['models']))
chk('mesh triangle count > 150k',m['triangle_count']>150000,m['triangle_count'])
chk('pivot groups 88',m['animation_pivots']==88)
chk('visual sockets 266',m['decorative_sockets']==266)
chk('planned wires 188',m['planned_player_wires']==188)
chk('independent contacts 376',m['proposed_independent_logical_endpoints']==376)
chk('manifest real player wires are NOT included',m['actual_player_wires_included'] is False)
chk('manifest functional terminals NOT included',m['functional_sparkterminals_included'] is False)
chk('Unity compilation NOT claimed',m['unity_compilation_tested'] is False)
chk('Unity Play Mode NOT claimed',m['unity_playmode_tested'] is False)
chk('objective completion NOT claimed',m['objective_certifications_implemented'] is False)
node_names=[];bad=[];total_faces=0;total_pieces=0
for idx,q in enumerate(m['models']):
 try:
  sc=trimesh.load(str(ROOT/'GLB'/q['glb']),force='scene')
  nodes=list(sc.graph.nodes);node_names.extend(nodes)
  tris=sum(len(g.faces) for g in sc.geometry.values());total_faces+=tris
  total_pieces+=len(sc.geometry)
  if tris!=q['triangles']:bad.append(f"{q['name']}: {tris} versus {q['triangles']}")
  if q['name'] not in nodes:bad.append('missing root '+q['name'])
  if not sc.geometry or any(not np.isfinite(geo.vertices).all() for geo in sc.geometry.values()):bad.append('bad geometry '+q['name'])
  if any(n.startswith('L91_') for n in nodes):bad.append('stale old prefix '+q['name'])
 except Exception as e:bad.append(f"{q['glb']}: {e}")
chk('all 98 GLBs independently load as actual 3D scenes',not bad,'; '.join(bad[:3]))
chk('GLB imported mesh triangles match manifest',total_faces==m['triangle_count'],total_faces)
chk('GLB imported mesh chunks match manifest',total_pieces==m['mesh_chunk_count'],total_pieces)
pv=csvread('Animation_Rigs.csv');anc=csvread('Terminal_Anchor_Plan_266.csv');vis=csvread('Visual_Terminal_Sockets_266.csv')
w=csvread('Gameplay_Wiring_Concept_W001_W188.csv');logical=csvread('Terminal_Logical_Port_Reconciliation_376.csv')
conf=csvread('Terminal_Anchor_Signal_Conflict_Report.csv');obj=csvread('Objective_Certification_Plan_6.csv')
chk('88 unique pivot plan records',len(pv)==len(set(x['Pivot'] for x in pv))==88)
chk('every pivot has one imported node',all(node_names.count(x['Pivot'])==1 for x in pv))
chk('pivot coordinates finite',all(all(math.isfinite(float(x[f'World{ax}_m'])) for ax in 'XYZ') for x in pv))
chk('266 unique socket anchor records',len(anc)==len({x['AnchorID'] for x in anc})==266)
chk('visual socket list exactly matches anchors',anc==vis)
chk('every socket has one imported node',all(node_names.count('SOCKET_'+a['AnchorID'])==1 for a in anc))
chk('188 sequential wiring IDs',len(w)==188 and [x['WireID'] for x in w]==[f'W{i:03d}' for i in range(1,189)])
chk('376 logical contacts',len(logical)==376)
chk('logical contact port IDs unique',len({x['FunctionalPortID'] for x in logical})==376)
sm={x['AnchorID']:x['OwnerModel'] for x in anc}
chk('all source socket ownership correct',all(sm.get(x['SourceVisualAnchor'])==x['SourceModel'] for x in w))
chk('all target socket ownership correct',all(sm.get(x['TargetVisualAnchor'])==x['TargetModel'] for x in w))
chk('each logical endpoint linked to actual wire id',all(x['WireID'] in {r['WireID'] for r in w} for x in logical))
chk('exact conflict records',len(conf)==m['reused_socket_locations'],len(conf))
chk('mixed-signal conflict number',sum(x['MixedSignalKinds']=='True' for x in conf)==m['mixed_signal_socket_locations'])
chk('only W171 marked critical',[x['WireID'] for x in w if x['Critical']=='YES']==['W171'])
critical=w[170]
chk('W171 source',critical['SourceModel']=='L92_AnchorLoadCellArray',critical['SourceModel'])
chk('W171 destination',critical['TargetModel']=='L92_SamplingSafetyPLC',critical['TargetModel'])
chk('W171 exact endpoints',critical['SourceVisualAnchor']=='P072' and critical['TargetVisualAnchor']=='P219',critical)
chk('W171 analog safety feedback',critical['SignalKind']=='ANALOG_SAFETY_FEEDBACK')
chk('W171 independent logical ports',all(s in {x['FunctionalPortID'] for x in logical} for s in ['TRUSTED_ANCHOR_LOAD_OUT','TRUSTED_ANCHOR_LOAD_IN']))
chk('six objectives conceptual only',len(obj)==6 and all(x['Implemented']=='NO' for x in obj))
chk('36 procedural reference maps',len(list((ROOT/'Textures').glob('*.png')))==36)
chk('12 reference material groups',len(json.loads((ROOT/'Texture_Manifest.json').read_text())['materials'])==12)
chk('four Unity helper scripts',len(list((ROOT/'Unity_Optional').glob('*.cs')))==4)
chk('Unity art helper scripts use Level92',all('Level92' in p.name for p in (ROOT/'Unity_Optional').glob('*.cs')))
chk('Unity menu 92, not earlier levels',all('Tools/Project Spark/Levels/90/' not in p.read_text() and 'Tools/Project Spark/Levels/91/' not in p.read_text() for p in (ROOT/'Unity_Optional').glob('*.cs')))
chk('Unity art placement menu exact', 'Tools/Project Spark/Levels/92/Place HD Art Under Selected Layout' in (ROOT/'Unity_Optional'/'SparkLevel92ArtPlacementEditor.cs').read_text())
chk('Unity art validator menu exact', 'Tools/Project Spark/Levels/92/Validate Imported HD Art' in (ROOT/'Unity_Optional'/'SparkLevel92AssetValidatorEditor.cs').read_text())
chk('Unity visual rig names match animation pivots', all(x in {p['Pivot'] for p in pv} for x in ['ANIM_DRILL_SPINDLE','ANIM_CORE_BIT','ANIM_TETHER_WINCH_SPOOL','ANIM_CARTRIDGE_CAROUSEL','ANIM_ANCHOR_A_MICROSPINE_LATCH']))
chk('production collision LOD plan',(ROOT/'Collision_LOD_Production_Plan.csv').exists())
chk('W171 detailed recovery plan',(ROOT/'W171_Critical_Anchor_Load_Recovery.md').exists())
chk('reproducible generation scripts',(ROOT/'Source'/'build_level92.py').exists() and (ROOT/'Source'/'geometry_export_core.py').exists())
chk('all source models lack prebuilt success flags',not m['objective_certifications_implemented'])
report=dict(level=92,validation_scope='Offline FBX header GLB import meshes manifest and related file structure only',
 passed=sum(c['status']=='PASS' for c in checks),failed=sum(c['status']=='FAIL' for c in checks),total=len(checks),checks=checks,
 disclaimer='Does not test Unity FBX import, C# compilation, Play Mode, solver, physical simulation or playable 6/6 objective completion.')
(ROOT/'Reports'/'Verification_Report.json').write_text(json.dumps(report,indent=2),encoding='utf8')
print('LEVEL 92 OFFLINE VERIFICATION:',report['passed'],'/',report['total'],'passed;',report['failed'],'failed',flush=True)
if report['failed']:raise SystemExit(1)
