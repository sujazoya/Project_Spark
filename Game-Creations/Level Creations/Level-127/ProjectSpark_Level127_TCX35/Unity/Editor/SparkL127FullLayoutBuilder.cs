                    Debug.LogError("[L127] Missing importable component mesh " + model[5]);
                    UnityEngine.Object.DestroyImmediate(root);
                    return;
                }
                // Object models are local to their origin: placement is through the slot only.
                visual.transform.localPosition = Vector3.zero;
                visual.transform.localRotation = Quaternion.identity;
                Bounds visualBounds;
                if (!TryBounds(visual, out visualBounds))
                {
                    Debug.LogError("[L127] Component has no measurable Renderer: " + record[0]);
                    UnityEngine.Object.DestroyImmediate(root);
                    return;
                }
                trigger.size = visualBounds.size;
                trigger.center = visual.transform.InverseTransformPoint(visualBounds.center);
                visual.AddComponent<SparkL127VisualOnly>();
                PrefabUtility.SaveAsPrefabAsset(visual, prefabAsset);
                UnityEngine.Object.DestroyImmediate(visual);
            }
            List<SparkL127RouteEntry> routeData = new List<SparkL127RouteEntry>(464);
            for (int i = 0; i < routeRows.Count; i++)
            {
                string[] r = routeRows[i];
                Child(routes.transform, r[0] + "_" + SafeName(r[1]))
                    .AddComponent<SparkL127BlockedTask>()
                    .Configure(SparkL127TaskType.CopperRoute, r[0], r[1]);
                routeData.Add(new SparkL127RouteEntry
