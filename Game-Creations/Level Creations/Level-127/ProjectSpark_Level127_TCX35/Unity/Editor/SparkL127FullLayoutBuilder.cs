                Child(adapters.transform, SafeName(requiredServices[i]))
                    .AddComponent<SparkL127IntegrationAnchor>().Configure(requiredServices[i]);
            GameObject demo = Child(root.transform, "OPTIONAL_ThermalTransient_Teaching_DEMO_NONCERTIFIABLE");
            demo.AddComponent<SparkL127ThermalTeachingDemo>();

            GameObject disabledReference = Child(root.transform, "Assembled_ART_REFERENCE_DISABLED_NEVER_GAMEPLAY");
            GameObject reference = ImportModel(source, "435_L127_AssembledReference.obj", disabledReference.transform, "Showcase_FullAssembly_ONLY");
            if (reference != null) reference.AddComponent<SparkL127VisualOnly>();
            disabledReference.AddComponent<SparkL127VisualOnly>();
            disabledReference.SetActive(false);

            PrefabUtility.SaveAsPrefabAsset(root, Output + "/Level_127_Layout.prefab");
            EditorSceneManager.SaveScene(scene, Output + "/Level_127_Layout.unity");
