                    .AddComponent<SparkL127BlockedTask>()
                    .Configure(SparkL127TaskType.Via, v[0], "Layer span TBD");
                viaData.Add(new SparkL127ViaEntry
                {
                    id = v[0], netId = v[1], fromLayer = v[2], toLayer = v[3], verified = false
                });
            }
            SparkL127SourceBlueprint blueprint = AssetDatabase.LoadAssetAtPath<SparkL127SourceBlueprint>(Output + "/L127_SourceBlueprint.asset");
            if (blueprint == null)
            {
                blueprint = ScriptableObject.CreateInstance<SparkL127SourceBlueprint>();
                AssetDatabase.CreateAsset(blueprint, Output + "/L127_SourceBlueprint.asset");
            }
            blueprint.SetSourceData(componentData, routeData, viaData);
            EditorUtility.SetDirty(blueprint);

            GameObject adapters = Child(root.transform, "ProjectSparkSystemBindings_REQUIRED_UNBOUND");
            string[] requiredServices = {
                "SparkCircuitSystem: approved protected thermal power and return netlist",
                "SparkTerminal: approved 46-layer contacts and pin mapping",
                "LevelGamePlayManager: six independent objectives, 0/6 initially",
                "Existing virtual multimeter, oscilloscope, thermal diagnostics and repair UI",
                "Existing placement, shop, selection, rotate and wire tools; no global replacements",
                "U1/U2 redundant thermal supervisors; U3 independent actuator inhibit",
                "M1/M2 coolant pump control and independently verified flow feedback",
                "M3/M4 radiator actuators, position and current limits",
                "M5/M6 heater banks, M7 sensor excitation, M8 independent inhibit",
                "F1 Q1 pump driver open / F2 R1 sensor reference drift / F3 TH1 sensor intermittency",
                "W465 U6.TRUSTED_THERMAL_READY_OUT to U3.TRUSTED_THERMAL_READY_IN; physical pins unassigned",
                "Versioned evidence, deterministic replay, save/load and prior-level regressions"
            };
