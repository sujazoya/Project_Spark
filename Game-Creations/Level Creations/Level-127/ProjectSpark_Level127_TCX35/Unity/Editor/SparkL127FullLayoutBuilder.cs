        private static bool TryBounds(GameObject go, out Bounds result)
        {
            result = new Bounds(Vector3.zero, Vector3.zero);
            if (go == null) return false;
            Renderer[] renderers = go.GetComponentsInChildren<Renderer>(true);
            if (renderers.Length == 0) return false;
            bool found = false;
            for (int i = 0; i < renderers.Length; i++)
            {
                if (renderers[i] == null) continue;
                if (!found) { result = renderers[i].bounds; found = true; }
                else result.Encapsulate(renderers[i].bounds);
            }
            return found;
        }

        private static string SafeName(string raw)
        {
            char[] chars = raw.ToCharArray();
            for (int i = 0; i < chars.Length; i++)
                if (!char.IsLetterOrDigit(chars[i]) && chars[i] != '_') chars[i] = '_';
            return new string(chars);
        }

