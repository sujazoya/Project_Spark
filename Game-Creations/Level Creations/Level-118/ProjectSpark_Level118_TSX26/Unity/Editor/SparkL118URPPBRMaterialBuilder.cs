#if UNITY_EDITOR
using System;
using System.Collections.Generic;
using System.IO;
using UnityEditor;
using UnityEngine;

namespace ProjectSpark.Level118.Editor
{
    public static class SparkL118URPPBRMaterialBuilder
    {
        public const string Output = "Assets/ProjectSpark/AutoGeneratedLevels/Level118/URP_PBR_Materials";
        private static readonly Dictionary<string, Material> Cache =
            new Dictionary<string, Material>(StringComparer.OrdinalIgnoreCase);

        [MenuItem("Tools/Project Spark/Automatic Level Generator/118/4. Rebuild URP PBR Materials")]
        public static void Rebuild()
        {
            string root = SparkL118FullLayoutBuilder.FindSourceRoot();
            if (string.IsNullOrEmpty(root)) return;
            if (Build(root)) Debug.Log("[L118] Generated or updated 34 URP Lit PBR materials.");
        }

        public static bool Build(string source)
        {
            Shader shader = Shader.Find("Universal Render Pipeline/Lit");
            if (shader == null)
            {
                Debug.LogError("[L118] URP/Lit shader not found; activate the URP asset first.");
                return false;
            }
            string textures = source + "/Textures";
            string[] maps = Directory.GetFiles(Absolute(textures), "*_BaseColor.png", SearchOption.TopDirectoryOnly);
            if (maps.Length != 34)
            {
                Debug.LogError("[L118] Expected 34 source BaseColor maps, found " + maps.Length);
                return false;
            }
            Array.Sort(maps, StringComparer.OrdinalIgnoreCase);
            Directory.CreateDirectory(Absolute(Output));
            AssetDatabase.Refresh();
            Cache.Clear();
            foreach (string absoluteMap in maps)
            {
                string file = Path.GetFileName(absoluteMap);
                string family = file.Substring(0, file.Length - "_BaseColor.png".Length);
                string diffuse = textures + "/" + family + "_BaseColor.png";
                string normal = textures + "/" + family + "_Normal.png";
                string ao = textures + "/" + family + "_AO.png";
                string packed = source + "/URP_Packed/" + family + "_URP_MetallicSmoothness.png";
                if (!File.Exists(Absolute(normal)) || !File.Exists(Absolute(ao)) || !File.Exists(Absolute(packed)))
                {
                    Debug.LogError("[L118] Missing PBR family maps: " + family);
                    return false;
                }
                Configure(diffuse, false, true);
                Configure(normal, true, false);
                Configure(ao, false, false);
                Configure(packed, false, false);
                Texture2D baseMap = AssetDatabase.LoadAssetAtPath<Texture2D>(diffuse);
                Texture2D normalMap = AssetDatabase.LoadAssetAtPath<Texture2D>(normal);
                Texture2D occlusionMap = AssetDatabase.LoadAssetAtPath<Texture2D>(ao);
                Texture2D metalMap = AssetDatabase.LoadAssetAtPath<Texture2D>(packed);
                if (baseMap == null || normalMap == null || occlusionMap == null || metalMap == null)
                {
                    Debug.LogError("[L118] Texture import unresolved for " + family);
                    return false;
                }
                string destination = Output + "/L118_" + family + ".mat";
                Material mat = AssetDatabase.LoadAssetAtPath<Material>(destination);
                if (mat == null)
                {
                    mat = new Material(shader);
                    mat.name = "L118_" + family;
                    AssetDatabase.CreateAsset(mat, destination);
                }
                else if (mat.shader != shader) mat.shader = shader;
                mat.SetTexture("_BaseMap", baseMap);
                mat.SetColor("_BaseColor", Color.white);
                mat.SetTexture("_MetallicGlossMap", metalMap);
                mat.SetFloat("_Metallic", 1f);
                mat.SetFloat("_Smoothness", 1f);
                if (mat.HasProperty("_SmoothnessTextureChannel")) mat.SetFloat("_SmoothnessTextureChannel", 0f);
                mat.EnableKeyword("_METALLICSPECGLOSSMAP");
                mat.SetTexture("_BumpMap", normalMap);
                mat.SetFloat("_BumpScale", 1f);
                mat.EnableKeyword("_NORMALMAP");
                mat.SetTexture("_OcclusionMap", occlusionMap);
                mat.SetFloat("_OcclusionStrength", 1f);
                mat.SetFloat("_Surface", 0f);
                mat.enableInstancing = true;
                EditorUtility.SetDirty(mat);
                Cache.Add(family, mat);
            }
            AssetDatabase.SaveAssets();
            return Cache.Count == 34;
        }

        private static void Configure(string path, bool normal, bool srgb)
        {
            TextureImporter importer = AssetImporter.GetAtPath(path) as TextureImporter;
            if (importer == null) return;
            TextureImporterType importerType = normal ? TextureImporterType.NormalMap : TextureImporterType.Default;
            if (importer.textureType == importerType && importer.sRGBTexture == srgb) return;
            importer.textureType = importerType;
            importer.sRGBTexture = srgb;
            importer.SaveAndReimport();
        }

        private static void EnsureCached()
        {
            if (Cache.Count != 0) return;
            string[] ids = AssetDatabase.FindAssets("t:Material", new[] { Output });
            foreach (string guid in ids)
            {
                string assetPath = AssetDatabase.GUIDToAssetPath(guid);
                string fileName = Path.GetFileNameWithoutExtension(assetPath);
                if (!fileName.StartsWith("L118_", StringComparison.OrdinalIgnoreCase)) continue;
                Material material = AssetDatabase.LoadAssetAtPath<Material>(assetPath);
                string family = fileName.Substring(5);
                if (material != null && !Cache.ContainsKey(family)) Cache.Add(family, material);
            }
        }

        public static int Bind(GameObject visual)
        {
            if (visual == null) return 0;
            EnsureCached();
            int bound = 0;
            Renderer[] renderers = visual.GetComponentsInChildren<Renderer>(true);
            for (int r = 0; r < renderers.Length; r++)
            {
                Renderer targetRenderer = renderers[r];
                Material[] assignedMaterials = targetRenderer.sharedMaterials;
                bool changed = false;
                for (int materialIndex = 0; materialIndex < assignedMaterials.Length; materialIndex++)
                {
                    Material original = assignedMaterials[materialIndex];
                    string matchedFamily = original == null ? null : FindFamily(original.name);
                    if (matchedFamily == null)
                        matchedFamily = FindHierarchyFamily(targetRenderer.transform);
                    Material urpMaterial;
                    if (matchedFamily != null && Cache.TryGetValue(matchedFamily, out urpMaterial))
                    {
                        assignedMaterials[materialIndex] = urpMaterial;
                        changed = true;
                        bound++;
                    }
                }
                if (changed) targetRenderer.sharedMaterials = assignedMaterials;
            }
            return bound;
        }

        private static string FindHierarchyFamily(Transform start)
        {
            const string tag = "__PSMAT__";
            for (Transform currentNode = start; currentNode != null; currentNode = currentNode.parent)
            {
                string nodeName = currentNode.name;
                int position = nodeName.IndexOf(tag, StringComparison.OrdinalIgnoreCase);
                if (position < 0) continue;
                string taggedMaterialName = nodeName.Substring(position + tag.Length);
                string matchingFamily = FindFamily(taggedMaterialName);
                if (matchingFamily != null) return matchingFamily;
                foreach (string candidateFamily in Cache.Keys)
                {
                    if (taggedMaterialName.StartsWith(candidateFamily + "_", StringComparison.OrdinalIgnoreCase) ||
                        taggedMaterialName.StartsWith(candidateFamily + " (", StringComparison.OrdinalIgnoreCase))
                        return candidateFamily;
                }
            }
            return null;
        }

        private static string FindFamily(string rawName)
        {
            if (string.IsNullOrEmpty(rawName)) return null;
            string best = null;
            foreach (string family in Cache.Keys)
            {
                string prefixed = "L118_" + family;
                bool match = rawName.Equals(prefixed, StringComparison.OrdinalIgnoreCase) ||
                    rawName.Equals(family, StringComparison.OrdinalIgnoreCase) ||
                    rawName.StartsWith(prefixed + " ", StringComparison.OrdinalIgnoreCase) ||
                    rawName.StartsWith(prefixed + "_", StringComparison.OrdinalIgnoreCase) ||
                    rawName.EndsWith("_" + prefixed, StringComparison.OrdinalIgnoreCase);
                if (match && (best == null || family.Length > best.Length)) best = family;
            }
            return best;
        }

        private static string Absolute(string path)
        {
            return Path.Combine(Directory.GetParent(Application.dataPath).FullName,
                path.Replace('/', Path.DirectorySeparatorChar));
        }
    }
}
