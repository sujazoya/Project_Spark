#if UNITY_EDITOR
using System;
using System.Collections.Generic;
using System.IO;
using UnityEditor;
using UnityEngine;

namespace ProjectSpark.Level102.Editor
{
    /// <summary>Level-owned URP PBR materials. Original FBX, GLB and reference textures stay unchanged.</summary>
    public static class SparkL102MaterialBuilder
    {
        internal const string OutputBase = "Assets/ProjectSpark/AutoGeneratedLevels/Level102";
        internal const string OutputMaterials = OutputBase + "/URP_PBR_Materials";
        private static readonly Dictionary<string, Material> Cache = new Dictionary<string, Material>(StringComparer.OrdinalIgnoreCase);
        private static readonly string[] Families =
        {
            "Ceramic_Black", "Ceramic_Cream", "Connector_Gold", "Copper_Gold", "Copper_Red",
            "Dark_Metal", "Dielectric", "Fault_Red", "IC_Epoxy", "Indicator_Amber",
            "Indicator_Green", "Lead_Tin", "PCB_Core", "PCB_Navy", "Polymer_Grey",
            "Rubber_Black", "Silkscreen", "Solder"
        };

        [MenuItem("Tools/Project Spark/Levels/102/3. Create Native PBR Materials")]
        public static void Build()
        {
            string sourceRoot = SparkL102FullLayoutBuilder.FindSourceRoot();
            if (string.IsNullOrEmpty(sourceRoot))
            {
                Debug.LogError("[L102] Unique source manifest not found. Install Level102_HSX10/Data/ModelManifest.csv.");
                return;
            }
            BuildForRoot(sourceRoot);
        }

        internal static bool BuildForRoot(string root)
        {
            Shader shader = Shader.Find("Universal Render Pipeline/Lit");
            if (shader == null)
            {
                Debug.LogError("[L102] URP Lit shader missing. Activate URP before generating native Level 102 materials.");
                return false;
            }
            Directory.CreateDirectory(OutputMaterials);
            AssetDatabase.Refresh();
            Cache.Clear();
            int generated = 0;
            foreach (string family in Families)
            {
                string basePath = root + "/Textures/" + family;
                string albedoPath = basePath + "_Albedo.png";
                string normalPath = basePath + "_Normal.png";
                string maskPath = root + "/URP_Packed/" + family + "_URP_MetallicSmoothness.png";
                string aoPath = root + "/URP_Packed/" + family + "_URP_Occlusion.png";
                if (AssetDatabase.LoadAssetAtPath<Texture2D>(albedoPath) == null ||
                    AssetDatabase.LoadAssetAtPath<Texture2D>(maskPath) == null)
                {
                    Debug.LogError("[L102] Missing texture family: " + family + " at " + root);
                    continue;
                }
                EnsureTextureSettings(albedoPath, false, true);
                EnsureTextureSettings(normalPath, true, false);
                EnsureTextureSettings(maskPath, false, false);
                EnsureTextureSettings(aoPath, false, false);

                string matPath = OutputMaterials + "/L102_" + family + ".mat";
                Material mat = AssetDatabase.LoadAssetAtPath<Material>(matPath);
                if (mat == null)
                {
                    mat = new Material(shader) { name = "L102_" + family };
                    AssetDatabase.CreateAsset(mat, matPath);
                }
                else if (mat.shader != shader) mat.shader = shader;
                Texture2D albedo = AssetDatabase.LoadAssetAtPath<Texture2D>(albedoPath);
                Texture2D normal = AssetDatabase.LoadAssetAtPath<Texture2D>(normalPath);
                Texture2D metallic = AssetDatabase.LoadAssetAtPath<Texture2D>(maskPath);
                Texture2D ao = AssetDatabase.LoadAssetAtPath<Texture2D>(aoPath);
                SetTexture(mat, "_BaseMap", albedo);
                SetTexture(mat, "_BumpMap", normal);
                SetTexture(mat, "_MetallicGlossMap", metallic);
                SetTexture(mat, "_OcclusionMap", ao);
                if (mat.HasProperty("_BaseColor")) mat.SetColor("_BaseColor", Color.white);
                if (mat.HasProperty("_Metallic")) mat.SetFloat("_Metallic", 1f);
                if (mat.HasProperty("_Smoothness")) mat.SetFloat("_Smoothness", 1f);
                if (mat.HasProperty("_BumpScale")) mat.SetFloat("_BumpScale", 0.7f);
                if (mat.HasProperty("_OcclusionStrength")) mat.SetFloat("_OcclusionStrength", 1f);
                if (normal != null) mat.EnableKeyword("_NORMALMAP"); else mat.DisableKeyword("_NORMALMAP");
                if (metallic != null) mat.EnableKeyword("_METALLICSPECGLOSSMAP");
                else mat.DisableKeyword("_METALLICSPECGLOSSMAP");
                EditorUtility.SetDirty(mat);
                Cache[family] = mat;
                generated++;
            }
            AssetDatabase.SaveAssets();
            Debug.Log("[L102] Created/updated " + generated + "/" + Families.Length +
                      " URP Lit material families with packed metallic/smoothness and AO. Keep source textures unchanged.");
            return generated == Families.Length;
        }

        private static void SetTexture(Material mat, string property, Texture texture)
        {
            if (mat.HasProperty(property)) mat.SetTexture(property, texture);
        }

        private static void EnsureTextureSettings(string path, bool isNormal, bool srgb)
        {
            TextureImporter importer = AssetImporter.GetAtPath(path) as TextureImporter;
            if (importer == null) return;
            bool dirty = false;
            TextureImporterType type = isNormal ? TextureImporterType.NormalMap : TextureImporterType.Default;
            if (importer.textureType != type) { importer.textureType = type; dirty = true; }
            if (!isNormal && importer.sRGBTexture != srgb)
            {
                importer.sRGBTexture = srgb;
                dirty = true;
            }
            if (dirty) importer.SaveAndReimport();
        }

        internal static void BindAllMaterials(GameObject artObject)
        {
            Renderer[] renderers = artObject.GetComponentsInChildren<Renderer>(true);
            for (int i = 0; i < renderers.Length; i++)
            {
                Renderer renderer = renderers[i];
                Material[] original = renderer.sharedMaterials;
                if (original.Length == 0) continue;
                Material[] updated = (Material[])original.Clone();
                bool changed = false;
                for (int slot = 0; slot < updated.Length; slot++)
                {
                    string family = IdentifyFamily(original[slot] != null ? original[slot].name : string.Empty);
                    if (string.IsNullOrEmpty(family)) family = IdentifyFamily(renderer.gameObject.name);
                    Material replacement;
                    if (!string.IsNullOrEmpty(family) && Cache.TryGetValue(family, out replacement) && replacement != updated[slot])
                    {
                        updated[slot] = replacement;
                        changed = true;
                    }
                }
                if (changed) renderer.sharedMaterials = updated;
            }
        }

        private static string IdentifyFamily(string candidate)
        {
            if (string.IsNullOrEmpty(candidate)) return null;
            string normalized = candidate.Replace(" (Instance)", "").Replace("L102_", "");
            for (int i = 0; i < Families.Length; i++)
            {
                if (normalized.Equals(Families[i], StringComparison.OrdinalIgnoreCase) ||
                    normalized.IndexOf("_" + Families[i], StringComparison.OrdinalIgnoreCase) >= 0)
                    return Families[i];
            }
            return null;
        }
    }
}
#endif
