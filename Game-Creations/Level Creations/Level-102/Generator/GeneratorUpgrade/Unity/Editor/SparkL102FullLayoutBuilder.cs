        [MenuItem(MenuRoot + "1. Build FULL Level_102_Layout")]
        public static void BuildFullLayout()
        {
            string source = FindSourceRoot();
            if (string.IsNullOrEmpty(source))
            {
                Debug.LogError("[L102] Cannot uniquely identify Level102_HSX10/Data/ModelManifest.csv. Install full source first; remove duplicate copies.");
                return;
            }
            List<Dictionary<string, string>> models = ReadCsv(source + "/Data/ModelManifest.csv");
            List<Dictionary<string, string>> placements = ReadCsv(source + "/Data/ComponentPlacements.csv");
            List<Dictionary<string, string>> routes = ReadCsv(source + "/Data/RouteTasks_108_REQUIRES_NETLIST.csv");
            List<Dictionary<string, string>> vias = ReadCsv(source + "/Data/ViaTasks_28_REQUIRES_NETLIST.csv");
            List<Dictionary<string, string>> bom = ReadCsv(source + "/Data/ComponentBOM.csv");
            if (!ValidateTables(models, placements, routes, vias, bom)) return;
            Dictionary<string, string> componentModels = new Dictionary<string, string>(StringComparer.Ordinal);
            for (int i = 0; i < models.Count; i++)
            {
                if (Get(models[i], "category") != "installable_component") continue;
                componentModels[Get(models[i], "model")] = Get(models[i], "fbx");
            }
            if (componentModels.Count != ExpectedParts)
            {
                Debug.LogError("[L102] Expected 82 unique installable source models, found " + componentModels.Count);
                return;
            }
            GameObject boardModel = ResolveModel(source, "083_L102_PCB_Base.fbx");
            GameObject assembled = ResolveModel(source, "L102_Assembled_Reference.fbx");
            if (boardModel == null || assembled == null)
            {
                Debug.LogError("[L102] Empty PCB or reference model imported without valid meshes. Check Models_OBJ_Fallback and FBX import.");
                return;
            }
            foreach (KeyValuePair<string, string> pair in componentModels)
            {
                if (ResolveModel(source, pair.Value) == null)
                {
                    Debug.LogError("[L102] Renderable component art missing: " + pair.Value);
                    return;
                }
            }
            if (AssetDatabase.LoadAssetAtPath<GameObject>(PrefabPath) != null &&
                !EditorUtility.DisplayDialog("Level 102 rebuild", "The Level_102_Layout prefab already exists. Rebuild Level 102 generated assets? Existing gameplay scenes and other levels are not modified.", "Rebuild", "Cancel")) return;
            if (!SparkL102MaterialBuilder.BuildForRoot(source))
            {
                Debug.LogError("[L102] Full layout aborted; native URP PBR materials are incomplete.");
                return;
            }
            Directory.CreateDirectory(Generated);
            Directory.CreateDirectory(Generated + "/ComponentVisualPrefabs");
            AssetDatabase.Refresh();
            SparkL102SourceBlueprint blueprint = CreateOrUpdateBlueprint(placements, routes, vias, componentModels);
            string report = WriteValidationReport(source, models.Count, componentModels.Count, routes.Count, vias.Count);
            Scene tempScene = EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Additive);
            bool saved = false;
            try
            {
                GameObject root = CreateInScene("L102_SignalPhantom", tempScene, null);
                GameObject gameplay = CreateChild("GameplayAuthority_INTEGRATION_REQUIRED", root.transform);
                CreateChild("BoardElectricalGraph_AWAIT_REAL_PROJECT_API", gameplay.transform);
                CreateChild("SixLayerNetlist_BLOCKED", gameplay.transform);
                GameObject componentRoot = CreateChild("ComponentFootprints_SOURCE_ONLY", gameplay.transform);
                GameObject routeRoot = CreateChild("RouteTasks_108_UNVERIFIED", gameplay.transform);
                GameObject viaRoot = CreateChild("ViaTasks_28_UNVERIFIED", gameplay.transform);
                GameObject safetyRoot = CreateChild("Safety_W109_CONCEPTUAL_PORTS", gameplay.transform);
                CreateChild("L102_LinkQualityMonitor_U9.TRUSTED_LINK_QUALITY_OUT", safetyRoot.transform);
                CreateChild("L102_HighSpeedSafetySupervisor_U11.TRUSTED_LINK_QUALITY_IN", safetyRoot.transform);
                GameObject objectives = CreateChild("Objectives_0_of_6_AUTHORITY_PENDING", gameplay.transform);
                string[] names = { "01_Assembly", "02_Routing", "03_Commissioning", "04_SignalIntegrity", "05_ThreeFaultRecovery", "06_W109SafetyRecovery" };
                for (int i = 0; i < names.Length; i++)
                    CreateChild(names[i] + "_UNCERTIFIED", objectives.transform);
                GameObject faults = CreateChild("SourceFaults_NOT_INJECTED", gameplay.transform);
                CreateChild("F1_R1_150_Ohm_InsteadOf_100_Ohm", faults.transform);
                CreateChild("F2_DiffPairA_ExcessCoupling", faults.transform);
                CreateChild("F3_ViaBarrels_UnterminatedStub", faults.transform);

                GameObject visuals = CreateChild("Visuals", root.transform);
                GameObject pcb = CreateChild("PCB_Base", visuals.transform);
                SpawnModel(boardModel, "HSX10_Empty_Board", pcb.transform, tempScene);
                CreateChild("InstalledComponentVisuals_EMPTY", visuals.transform);
                GameObject layers = CreateChild("LayerInspection_ArtOnly_Disabled", visuals.transform);
                for (int n = 84; n <= 89; n++)
                {
                    string prefix = n.ToString("000", CultureInfo.InvariantCulture) + "_L102_";
                    string fbx = FindModelFileForPrefix(models, prefix);
                    if (string.IsNullOrEmpty(fbx)) continue;
                    GameObject model = ResolveModel(source, fbx);
                    if (model == null) continue;
                    GameObject layer = SpawnModel(model, Path.GetFileNameWithoutExtension(fbx) + "_VISUAL", layers.transform, tempScene);
                    if (layer != null) layer.SetActive(false);
                }
                layers.SetActive(false);
                GameObject showcaseRoot = CreateChild("Reference_Assembly_NonPlayable_Disabled", visuals.transform);
                GameObject showcase = SpawnModel(assembled, "Complete_Board_SHOWCASE_ONLY", showcaseRoot.transform, tempScene);
                if (showcase != null)
                {
                    Collider[] colliders = showcase.GetComponentsInChildren<Collider>(true);
                    for (int i = 0; i < colliders.Length; i++) UnityEngine.Object.DestroyImmediate(colliders[i]);
                }
                showcaseRoot.SetActive(false);

                GameObject interaction = CreateChild("Interaction_PendingRealVirtualToolBridge", root.transform);
                CreateChild("WorldSpaceCanvas_ExistingUI_NotDuplicated", interaction.transform);
                CreateChild("BoardPickTargets_PendingApprovedPads", interaction.transform);
                for (int i = 0; i < placements.Count; i++)
                {
                    Dictionary<string, string> item = placements[i];
                    string id = Get(item, "ref");
                    string fbx;
                    if (!componentModels.TryGetValue(id, out fbx)) throw new InvalidOperationException("No source model for " + id);
                    GameObject model = ResolveModel(source, fbx);
                    GameObject previewPrefab = EnsureVisualPrefab(model, id, tempScene);
                    GameObject slot = CreateChild("Slot_" + id + "_UNINSTALLED", componentRoot.transform);
                    float x = FloatValue(Get(item, "x_m"));
                    float y = FloatValue(Get(item, "y_m"));
                    // Source XY board plane, Z up. Unity fallback is XZ plane, Y up: (x,y)->(x,-y).
                    slot.transform.localPosition = new Vector3(x, 0.0008f, -y);
                    SparkL102PlacementTarget target = slot.AddComponent<SparkL102PlacementTarget>();
                    target.referenceDesignator = id;
                    target.footprint = Get(item, "footprint");
                    target.sourceFbx = fbx;
                    target.physicalLocationMeters = slot.transform.localPosition;
                    target.visualPrefab = previewPrefab;
                    target.startsInstalled = false;
                }
                for (int i = 0; i < routes.Count; i++)
                {
                    string id = Get(routes[i], "route_id");
                    GameObject record = CreateChild(id + "_UNVERIFIED", routeRoot.transform);
                    SparkL102UnverifiedTask task = record.AddComponent<SparkL102UnverifiedTask>();
                    task.taskId = id;
                    task.taskKind = "ROUTE";
                    task.sourceGroup = Get(routes[i], "subsystem");
                    task.certifiable = false;
                }
                for (int i = 0; i < vias.Count; i++)
                {
                    string id = Get(vias[i], "via_id");
                    GameObject record = CreateChild(id + "_UNVERIFIED", viaRoot.transform);
                    SparkL102UnverifiedTask task = record.AddComponent<SparkL102UnverifiedTask>();
                    task.taskId = id;
                    task.taskKind = "VIA";
                    task.sourceGroup = Get(vias[i], "manufacturing_type");
                    task.certifiable = false;
                }
                PrefabUtility.SaveAsPrefabAsset(root, PrefabPath);
                if (!EditorSceneManager.SaveScene(tempScene, ScenePath)) throw new IOException("Scene save unsuccessful: " + ScenePath);
                saved = true;
            }
            catch (Exception exception) { Debug.LogException(exception); }
            finally { EditorSceneManager.CloseScene(tempScene, true); }
            AssetDatabase.SaveAssets();
            AssetDatabase.Refresh();
            if (saved)
            {
                Selection.activeObject = AssetDatabase.LoadAssetAtPath<GameObject>(PrefabPath);
                Debug.Log("[L102] FULL visual layout created. " + PrefabPath + " | " + ScenePath +
                    " | " + AssetPath + " | status=" + blueprint.validationStatus +
                    " | 82 UNINSTALLED; 108 ROUTES MISSING; 28 VIAS MISSING; W109 DISCONNECTED; 0/6. Report: " + report);
            }
        }

        [MenuItem(MenuRoot + "2. Place Level 102 on SELECTED tabletop")]
        public static void PlaceOnTabletop()
        {
            Transform table = Selection.activeTransform;
            if (table == null)
            {
                Debug.LogError("[L102] Select the Table_top Transform in Hierarchy. A MeshRenderer or Collider is not required.");
                return;
            }
            GameObject prefab = AssetDatabase.LoadAssetAtPath<GameObject>(PrefabPath);
            if (prefab == null) { Debug.LogError("[L102] Build FULL Level_102_Layout first."); return; }
            GameObject existing = GameObject.Find(PreviewName);
            if (existing != null)
            {
                if (!EditorUtility.DisplayDialog("Replace Level 102 preview", "The tabletop already has a Level 102 preview. Replace this visual-only preview?", "Replace", "Cancel")) return;
                Undo.DestroyObjectImmediate(existing);
            }
            GameObject display = (GameObject)PrefabUtility.InstantiatePrefab(prefab);
            if (display == null) { Debug.LogError("[L102] Could not instantiate generated prefab."); return; }
            Transform art = display.transform.Find("Visuals");
            if (art == null) { UnityEngine.Object.DestroyImmediate(display); Debug.LogError("[L102] Missing Visuals node in generated prefab."); return; }
            Undo.RegisterCreatedObjectUndo(display, "Level 102 Visual Preview");
            display.name = PreviewName;
            // Never detach children from an imported prefab instance: Unity disallows restructuring it.
            // Turn off non-visual source planning nodes and retain only the art for this oversized preview.
            for (int i = 0; i < display.transform.childCount; i++)
            {
                Transform child = display.transform.GetChild(i);
                if (child != art) child.gameObject.SetActive(false);
            }
            display.transform.SetPositionAndRotation(table.position, table.rotation);
            float uniform = TargetBoardWidth / PhysicalWidthMeters;
            art.localScale = Vector3.one * uniform;
            SparkL102TabletopPreview marker = display.AddComponent<SparkL102TabletopPreview>();
            marker.displayUniformScale = uniform;
            Collider[] accidentalColliders = display.GetComponentsInChildren<Collider>(true);
            for (int i = 0; i < accidentalColliders.Length; i++) UnityEngine.Object.DestroyImmediate(accidentalColliders[i]);
            Transform pcb = art.Find("PCB_Base");
            if (pcb != null)
            {
                Bounds bounds;
                if (TryGetBounds(pcb.gameObject, out bounds))
                    display.transform.position += Vector3.up * (table.position.y + 0.012f - bounds.min.y);
            }
            Selection.activeGameObject = display;
            Debug.Log("[L102] Created 10.13 x 7.091-unit tabletop art preview, uniformly scaled 40.52x. " +
                "NOT the physical solver board; no gameplay, objectives, or power are enabled.");
        }

        [MenuItem(MenuRoot + "3. Validate Imported Art and Source")]
        public static void ValidateImported()
        {
            string source = FindSourceRoot();
            if (string.IsNullOrEmpty(source)) { Debug.LogError("[L102] Source ambiguous/missing"); return; }
            var models = ReadCsv(source + "/Data/ModelManifest.csv");
            var placement = ReadCsv(source + "/Data/ComponentPlacements.csv");
            var routes = ReadCsv(source + "/Data/RouteTasks_108_REQUIRES_NETLIST.csv");
            var vias = ReadCsv(source + "/Data/ViaTasks_28_REQUIRES_NETLIST.csv");
            int imported = 0;
            foreach (var entry in models) if (ResolveModel(source, Get(entry, "fbx")) != null) imported++;
            bool valid = imported == 104 && placement.Count == 82 && routes.Count == 108 && vias.Count == 28;
            GameObject board = ResolveModel(source, "083_L102_PCB_Base.fbx");
            Debug.Log("[L102] " + (valid ? "Art sources located" : "MISSING SOURCE MODELS") + ": " + imported + "/104" +
                ", placements=" + placement.Count + ", routes=" + routes.Count + ", vias=" + vias.Count +
                ", PCB mesh=" + (board != null) + ", electrical status=BLOCKED_UNVERIFIED_NETLIST.");
        }

        public static string FindSourceRoot()
        {
            string found = null;
            foreach (string guid in AssetDatabase.FindAssets("ModelManifest"))
            {
                string path = AssetDatabase.GUIDToAssetPath(guid).Replace('\\', '/');
                if (!path.EndsWith("/Data/ModelManifest.csv", StringComparison.OrdinalIgnoreCase)) continue;
                if (path.IndexOf("L102", StringComparison.OrdinalIgnoreCase) < 0 &&
                    path.IndexOf("Level102", StringComparison.OrdinalIgnoreCase) < 0) continue;
                string candidate = path.Substring(0, path.Length - "/Data/ModelManifest.csv".Length);
                if (found != null && !found.Equals(candidate, StringComparison.OrdinalIgnoreCase)) return null;
                found = candidate;
            }
            return found;
        }

        private static SparkL102SourceBlueprint CreateOrUpdateBlueprint(
            List<Dictionary<string,string>> placements, List<Dictionary<string,string>> routes,
            List<Dictionary<string,string>> vias, Dictionary<string,string> names)
        {
            SparkL102SourceBlueprint asset = AssetDatabase.LoadAssetAtPath<SparkL102SourceBlueprint>(AssetPath);
            if (asset == null)
            {
                asset = ScriptableObject.CreateInstance<SparkL102SourceBlueprint>();
                AssetDatabase.CreateAsset(asset, AssetPath);
            }
            asset.parts.Clear(); asset.routes.Clear(); asset.vias.Clear();
            asset.validationStatus = SparkL102SourceBlueprint.UnverifiedStatus;
            foreach (Dictionary<string,string> row in placements)
            {
                string id = Get(row,"ref");
                asset.parts.Add(new SparkL102PartDefinition
                {
                    id = id, footprint = Get(row,"footprint"), visualModelName = names[id],
                    physicalPositionMeters = new Vector3(FloatValue(Get(row,"x_m")), 0.0008f, -FloatValue(Get(row,"y_m"))),
                    startsInstalled = false
                });
            }
            foreach (Dictionary<string,string> row in routes)
            {
                asset.routes.Add(new SparkL102CopperDefinition
                {
                    routeId = Get(row,"route_id"), subsystem = Get(row,"subsystem"), sourcePad = Get(row,"source_pad"),
                    destinationPad = Get(row,"destination_pad"), netId = Get(row,"net_id"), layer = Get(row,"layer"), certifiable = false
                });
            }
            foreach (Dictionary<string,string> row in vias)
            {
                asset.vias.Add(new SparkL102ViaDefinition
                {
                    viaId = Get(row,"via_id"), netId = Get(row,"net_id"), sourceLayer = Get(row,"start_layer"),
                    destinationLayer = Get(row,"end_layer"), manufacturingType = Get(row,"manufacturing_type"), certifiable = false
                });
            }
            EditorUtility.SetDirty(asset);
            return asset;
        }

