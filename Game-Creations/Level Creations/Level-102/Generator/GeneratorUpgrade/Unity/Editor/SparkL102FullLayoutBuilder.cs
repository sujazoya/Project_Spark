        }

        private static GameObject EnsureVisualPrefab(GameObject imported, string id, Scene scene)
        {
            string path = Generated + "/ComponentVisualPrefabs/L102_" + id + "_Visual.prefab";
            GameObject root = CreateInScene("L102_" + id + "_VisualOnly", scene, null);
            SpawnModel(imported, id + "_Art", root.transform, scene);
            GameObject result = PrefabUtility.SaveAsPrefabAsset(root, path);
            UnityEngine.Object.DestroyImmediate(root);
            return result;
        }

        private static string FindModelFileForPrefix(List<Dictionary<string,string>> rows, string prefix)
        {
            foreach (var row in rows)
            {
                string fbx = Get(row,"fbx");
                if (fbx.StartsWith(prefix, StringComparison.OrdinalIgnoreCase)) return fbx;
            }
            return null;
        }

        private static GameObject SpawnModel(GameObject source, string name, Transform parent, Scene scene)
        {
            GameObject go = PrefabUtility.InstantiatePrefab(source, scene) as GameObject;
            if (go == null) return null;
            go.name = name;
            go.transform.SetParent(parent, false);
            go.transform.localPosition = Vector3.zero;
            go.transform.localRotation = Quaternion.identity;
            go.transform.localScale = Vector3.one;
            SparkL102MaterialBuilder.BindAllMaterials(go);
            return go;
        }

        private static GameObject CreateInScene(string name, Scene scene, Transform parent)
        {
            GameObject go = new GameObject(name);
            SceneManager.MoveGameObjectToScene(go, scene);
            if (parent != null) go.transform.SetParent(parent, false);
            return go;
        }
        private static GameObject CreateChild(string name, Transform parent)
        {
            GameObject go = new GameObject(name);
            go.transform.SetParent(parent, false);
            return go;
        }

        private static GameObject ResolveModel(string root, string originalFbxName)
        {
            string stem = Path.GetFileNameWithoutExtension(originalFbxName);
            string fbxPath = root + "/Models_FBX/" + stem + ".fbx";
            string objPath = root + "/Models_OBJ_Fallback/" + stem + ".obj";
            GameObject native = AssetDatabase.LoadAssetAtPath<GameObject>(fbxPath);
            // Original FBX retains the best original UVs, if the Unity importer actually generated meshes.
            if (HasRealGeometry(native)) return native;
            GameObject fallback = AssetDatabase.LoadAssetAtPath<GameObject>(objPath);
            if (HasRealGeometry(fallback)) return fallback;
            return null;
        }

        private static bool HasRealGeometry(GameObject prefab)
        {
            if (prefab == null) return false;
            MeshFilter[] filters = prefab.GetComponentsInChildren<MeshFilter>(true);
            for (int i = 0; i < filters.Length; i++)
                if (filters[i].sharedMesh != null && filters[i].sharedMesh.vertexCount >= 3) return true;
            SkinnedMeshRenderer[] skin = prefab.GetComponentsInChildren<SkinnedMeshRenderer>(true);
            for (int i = 0; i < skin.Length; i++)
                if (skin[i].sharedMesh != null && skin[i].sharedMesh.vertexCount >= 3) return true;
            return false;
        }

        private static bool TryGetBounds(GameObject go, out Bounds bounds)
        {
            Renderer[] renderers = go.GetComponentsInChildren<Renderer>(true);
            bounds = new Bounds(go.transform.position, Vector3.zero);
            bool found = false;
            for (int i = 0; i < renderers.Length; i++)
            {
                if (!renderers[i].gameObject.activeInHierarchy) continue;
                if (!found) { bounds = renderers[i].bounds; found = true; }
                else bounds.Encapsulate(renderers[i].bounds);
            }
            return found;
        }

        private static bool ValidateTables(List<Dictionary<string,string>> models,
            List<Dictionary<string,string>> placements, List<Dictionary<string,string>> routes,
            List<Dictionary<string,string>> vias, List<Dictionary<string,string>> bom)
        {
            if (models.Count != 104 || placements.Count != ExpectedParts || bom.Count != ExpectedParts ||
                routes.Count != ExpectedRoutes || vias.Count != ExpectedVias)
            {
                Debug.LogError("[L102] Source manifest mismatch: models=" + models.Count + ", placements=" + placements.Count +
                    ", BOM=" + bom.Count + ", routes=" + routes.Count + ", vias=" + vias.Count);
                return false;
            }
            HashSet<string> parts = new HashSet<string>(StringComparer.Ordinal);
            foreach (var p in placements) if (!parts.Add(Get(p,"ref")) || Get(p,"initial_installed").Equals("true",StringComparison.OrdinalIgnoreCase))
            { Debug.LogError("[L102] Duplicate or pre-installed part: " + Get(p,"ref")); return false; }
            foreach (var p in bom) if (!parts.Contains(Get(p,"ref"))) { Debug.LogError("[L102] BOM mismatch: " + Get(p,"ref")); return false; }
            HashSet<string> ids = new HashSet<string>(StringComparer.Ordinal);
            for (int i = 0; i < routes.Count; i++)
            {
                var r=routes[i]; string id="W"+(i+1).ToString("000",CultureInfo.InvariantCulture);
                if (Get(r,"route_id")!=id || !ids.Add(id) ||
                    !Get(r,"certifiable").Equals("false",StringComparison.OrdinalIgnoreCase) ||
                    Get(r,"source_pad")!="UNASSIGNED" || Get(r,"destination_pad")!="UNASSIGNED")
                { Debug.LogError("[L102] Unexpected route authority/source record " + id); return false; }
            }
            for (int i = 0; i < vias.Count; i++)
            {
                var v=vias[i]; string id="V"+(i+1).ToString("00",CultureInfo.InvariantCulture);
                if (Get(v,"via_id")!=id || !Get(v,"certifiable").Equals("false",StringComparison.OrdinalIgnoreCase) ||
                    Get(v,"net_id")!="UNVERIFIED")
                { Debug.LogError("[L102] Unexpected via authority/source record " + id); return false; }
            }
            return true;
        }

        private static List<Dictionary<string,string>> ReadCsv(string path)
        {
            List<Dictionary<string,string>> rows = new List<Dictionary<string,string>>();
            string absolute = ToAbsolute(path);
            if (!File.Exists(absolute)) return rows;
            string[] lines = File.ReadAllLines(absolute);
            if (lines.Length < 2) return rows;
            List<string> headers = ParseCsvLine(lines[0].TrimStart('\ufeff'));
            for (int i = 1; i < lines.Length; i++)
            {
                if (string.IsNullOrWhiteSpace(lines[i])) continue;
                List<string> vals = ParseCsvLine(lines[i]);
                if (vals.Count != headers.Count) { Debug.LogError("[L102] Broken CSV line " + i + " in " + path); return new List<Dictionary<string,string>>(); }
                var row = new Dictionary<string,string>(StringComparer.Ordinal);
                for (int j = 0; j < headers.Count; j++) row[headers[j]] = vals[j];
                rows.Add(row);
            }
            return rows;
        }
        private static List<string> ParseCsvLine(string line)
        {
            var cols = new List<string>(); var text = new StringBuilder(); bool quoted = false;
            for (int i = 0; i < line.Length; i++)
            {
                char c = line[i];
                if (c == '"')
                {
                    if (quoted && i + 1 < line.Length && line[i+1] == '"') { text.Append('"'); i++; }
                    else quoted = !quoted;
                }
                else if (c == ',' && !quoted) { cols.Add(text.ToString().Trim()); text.Length = 0; }
                else text.Append(c);
            }
            cols.Add(text.ToString().Trim());
            return cols;
        }
        private static string ToAbsolute(string unityAssetPath)
        {
            return Path.Combine(Directory.GetParent(Application.dataPath).FullName, unityAssetPath.Replace('/',Path.DirectorySeparatorChar));
        }
        private static string Get(Dictionary<string,string> row, string col)
        {
            string s; return row.TryGetValue(col, out s) ? s : string.Empty;
        }
        private static float FloatValue(string value)
        {
            float f;
            if (!float.TryParse(value,NumberStyles.Float,CultureInfo.InvariantCulture,out f)) throw new FormatException("Invalid coordinate: "+value);
            return f;
        }
