                "Status: BLOCKED_UNVERIFIED_NETLIST\n" +
                "Source: " + root + "\n" +
                "Model assets: " + modelCount + "/104 | Components: " + partCount + "/82\n" +
                "Route tasks: " + routeCount + "/108 UNVERIFIED | Via tasks: " + viaCount + "/28 UNVERIFIED\n" +
                "Initial installation state: 0/82, 0/108, 0/28, W109 disconnected, objectives 0/6\n" +
                "W109: U9 trusted link-quality output -> detachable W109 -> U11 independent safety input; physical pin contacts NOT VERIFIED.\n" +
