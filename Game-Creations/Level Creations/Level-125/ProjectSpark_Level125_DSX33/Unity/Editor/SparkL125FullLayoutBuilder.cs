        [MenuItem(Menu + "1. Build FULL Level_125_Layout")]
        [MenuItem("Tools/Project Spark/Levels/Create Level 125")]
        public static void BuildFull()
        {
            string source = FindSourceRoot();
            if (string.IsNullOrEmpty(source)) return;
            if (!ValidateSource(source, true)) return;
            if (!SparkL125URPPBRMaterialBuilder.Build(source)) return;
            EnsureDirectory(Output);
            EnsureDirectory(Output + "/ComponentVisualPrefabs");
            AssetDatabase.Refresh();
            // The complete visual board is a separate prefab; it never enters gameplay inventory.
            if (!CreateCompleteMotherboardPrefab(source)) return;

            List<string[]> modelRows = ReadCsv(source + "/Data/ModelManifest.csv");
            List<string[]> bomRows = ReadCsv(source + "/Data/ComponentBOM.csv");
            List<string[]> placementRows = ReadCsv(source + "/Data/ComponentPlacements.csv");
            List<string[]> routeRows = ReadCsv(source + "/Data/CopperRoutes_432_REQUIRES_SCHEMATIC.csv");
            List<string[]> viaRows = ReadCsv(source + "/Data/ViaTasks_172_REQUIRES_SCHEMATIC.csv");
            Dictionary<string, string[]> models = new Dictionary<string, string[]>(StringComparer.OrdinalIgnoreCase);
            Dictionary<string, string[]> parts = new Dictionary<string, string[]>(StringComparer.OrdinalIgnoreCase);
            for (int i = 0; i < modelRows.Count; i++) models.Add(modelRows[i][1], modelRows[i]);
            for (int i = 0; i < bomRows.Count; i++) parts.Add(bomRows[i][0], bomRows[i]);

            // Avoid silently destroying the user's open and modified Project Spark scenes.
            if (!EditorSceneManager.SaveCurrentModifiedScenesIfUserWantsTo())
            {
                Debug.LogWarning("[L125] Build cancelled so open unsaved scenes are preserved.");
                return;
            }
            Scene scene = EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Single);
            GameObject root = new GameObject(RootName);
            root.AddComponent<SparkL125LayoutMarker>();
            GameObject art = Child(root.transform, "VisualArtRoot_Metres");
            GameObject actualBoard = Child(art.transform, "EmptyPCB_Physical_620x480mm");
            string[] boardRecord;
            if (!models.TryGetValue("L125_PCB_Main", out boardRecord))
            {
                Debug.LogError("[L125] Missing PCB_Main manifest record.");
                UnityEngine.Object.DestroyImmediate(root);
                return;
            }
            GameObject board = ImportModel(source, boardRecord[5], actualBoard.transform, "PCB_Main_RealScale");
            Bounds boardBounds;
            if (board == null || !TryBounds(board, out boardBounds) ||
                Mathf.Abs(boardBounds.size.x - PhysicalWidth) > .002f ||
                Mathf.Abs(boardBounds.size.z - PhysicalDepth) > .002f)
            {
                Debug.LogError("[L125] Board mesh import/scale mismatch. Expected 0.620 x 0.480 m. " +
                               "Do not generate primitive fallback geometry.");
                UnityEngine.Object.DestroyImmediate(root);
                return;
            }
            actualBoard.AddComponent<SparkL125VisualOnly>();
            BoxCollider boardClickArea = actualBoard.AddComponent<BoxCollider>();
            boardClickArea.size = new Vector3(PhysicalWidth, .0030f, PhysicalDepth);
            boardClickArea.center = Vector3.zero;
            GameObject layerArtwork = Child(art.transform, "42_InspectionLayerReferences_DISABLED");
            GameObject otherArtwork = Child(art.transform, "OtherUnverifiedFactoryArtwork_DISABLED");
            for (int i = 0; i < modelRows.Count; i++)
            {
                string[] item = modelRows[i];
                if (item[10] == "TRUE" || item[1] == "L125_PCB_Main") continue;
                Transform owner = item[2] == "layer" ? layerArtwork.transform : otherArtwork.transform;
                GameObject decoration = ImportModel(source, item[5], owner, "NONCONDUCTIVE_" + item[1]);
                if (decoration != null)
                {
                    decoration.transform.localPosition = new Vector3(F(item[7]), F(item[8]), F(item[9]));
                    decoration.AddComponent<SparkL125VisualOnly>();
                }
            }
            layerArtwork.SetActive(false);
            otherArtwork.SetActive(false);

            GameObject authoring = Child(root.transform, "GameplayAuthoringRoot_NONCERTIFIABLE");
            GameObject targets = Child(authoring.transform, "344_UninstalledComponentTargets");
            GameObject routes = Child(authoring.transform, "432_Routes_UNASSIGNED_BLOCKED");
            GameObject vias = Child(authoring.transform, "172_Vias_UNASSIGNED_BLOCKED");
            // Visual integration anchors only: positions are planning hints, not certified pads.
            GameObject zones = Child(authoring.transform, "DeepSpaceTelemetryZones_UNBOUND");
            string[] zoneNames = { "Telemetry_A", "Telemetry_B", "Independent_TX_Supervisor", "Receiver_B", "ReferenceClock_Y1", "Transmitter_A_Q1", "FEC_FPGA_U4", "W433_TX_READY_OPEN" };
            Vector3[] zonePositions = {
                new Vector3(-.269f,.0015f,-.207f), new Vector3(-.223f,.0015f,-.207f),
                new Vector3(-.177f,.0015f,-.207f), new Vector3(-.223f,.0015f,-.164f),
                new Vector3(-.286f,.0015f,-.123f), new Vector3(.227f,.0015f,-.123f),
                new Vector3(-.131f,.0015f,-.207f), new Vector3(.227f,.0015f,.222f)
            };
            for (int zoneIndex = 0; zoneIndex < zoneNames.Length; zoneIndex++)
            {
                GameObject zone = Child(zones.transform, zoneNames[zoneIndex]);
                zone.transform.localPosition = zonePositions[zoneIndex];
                zone.AddComponent<SparkL125IntegrationAnchor>()
                    .Configure("Approved RF and telemetry electrical schematic and physical contact authority required");
            }
            GameObject inventory = Child(authoring.transform, "InventoryPrefabs_AsAssets_NotYetInstalled");
            inventory.AddComponent<SparkL125VisualOnly>();
            List<SparkL125ComponentEntry> componentData = new List<SparkL125ComponentEntry>(344);
            for (int i = 0; i < placementRows.Count; i++)
            {
                string[] record = placementRows[i];
                string[] bomItem;
                string[] model;
                if (!parts.TryGetValue(record[0], out bomItem) || !models.TryGetValue(record[1], out model))
                {
                    Debug.LogError("[L125] Missing component/BOM/asset join: " + record[0]);
                    UnityEngine.Object.DestroyImmediate(root);
                    return;
