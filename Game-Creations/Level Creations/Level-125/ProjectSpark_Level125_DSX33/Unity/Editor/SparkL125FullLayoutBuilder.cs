            {
                string[] r = routeRows[i];
                Child(routes.transform, r[0] + "_" + SafeName(r[1]))
                    .AddComponent<SparkL125BlockedTask>()
                    .Configure(SparkL125TaskType.CopperRoute, r[0], r[1]);
