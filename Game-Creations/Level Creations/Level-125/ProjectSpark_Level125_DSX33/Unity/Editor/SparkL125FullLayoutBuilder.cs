            }
            SparkL125SourceBlueprint blueprint = AssetDatabase.LoadAssetAtPath<SparkL125SourceBlueprint>(Output + "/L125_SourceBlueprint.asset");
            if (blueprint == null)
            {
                blueprint = ScriptableObject.CreateInstance<SparkL125SourceBlueprint>();
                AssetDatabase.CreateAsset(blueprint, Output + "/L125_SourceBlueprint.asset");
            }
            blueprint.SetSourceData(componentData, routeData, viaData);
            EditorUtility.SetDirty(blueprint);

            GameObject adapters = Child(root.transform, "ProjectSparkSystemBindings_REQUIRED_UNBOUND");
            string[] requiredServices = {
                "SparkCircuitSystem: approved protected power, RF and return netlist",
                "SparkTerminal: approved 42-layer contacts and pin mapping",
                "LevelGamePlayManager: six independent objectives, 0/6 initially",
                "Existing virtual oscilloscope, spectrum, continuity, RF diagnostics and repair UI",
                "Existing placement, shop, selection, rotate and wire tools; no global replacements",
                "Redundant telemetry processors U1/U2; watchdog, stale evidence and fault latches",
                "Receiver A/B front ends, reference Y1 and qualified clock evidence",
                "Transmitter A/B, Q1 current sensing, RF power detector and independent inhibit",
                "Frame CRC, FEC decoder, sequence and replay checks; bounded link model",
                "F1 Y1 reference drift / F2 C1 receiver filter ESR / F3 Q1 output-stage overcurrent",
