        public static string FindSourceRoot()
        {
            const string suffix = "/Data/ModelManifest.csv";
            string[] assets = AssetDatabase.GetAllAssetPaths();
            string matched = null;
            for (int i = 0; i < assets.Length; i++)
            {
                if (!assets[i].EndsWith(suffix, StringComparison.OrdinalIgnoreCase)) continue;
                if (assets[i].IndexOf("Level125", StringComparison.OrdinalIgnoreCase) < 0 &&
                    assets[i].IndexOf("DSX33", StringComparison.OrdinalIgnoreCase) < 0) continue;
                string sourceRoot = assets[i].Substring(0, assets[i].Length - "/Data/ModelManifest.csv".Length);
                if (matched != null && !matched.Equals(sourceRoot, StringComparison.OrdinalIgnoreCase))
                {
                    Debug.LogError("[L125] Duplicated Level125_DSX33 source root: " + matched + " and " + sourceRoot);
                    return null;
                }
                matched = sourceRoot;
            }
            if (matched == null) Debug.LogError("[L125] Level125_DSX33 source not installed under Unity Assets.");
            return matched;
        }

        public static bool ValidateSource(string root, bool writeLog)
        {
            try
            {
                List<string[]> models = ReadCsv(root + "/Data/ModelManifest.csv");
                List<string[]> parts = ReadCsv(root + "/Data/ComponentBOM.csv");
                List<string[]> placements = ReadCsv(root + "/Data/ComponentPlacements.csv");
                List<string[]> routes = ReadCsv(root + "/Data/CopperRoutes_432_REQUIRES_SCHEMATIC.csv");
                List<string[]> viaRows = ReadCsv(root + "/Data/ViaTasks_172_REQUIRES_SCHEMATIC.csv");
                if (models.Count != 400 || parts.Count != 344 || placements.Count != 344 ||
                    routes.Count != 432 || viaRows.Count != 172)
                {
                    Debug.LogError("[L125] Wrong row counts: models=" + models.Count +
                        " BOM=" + parts.Count + " placements=" + placements.Count +
                        " routes=" + routes.Count + " vias=" + viaRows.Count);
                    return false;
                }
                HashSet<string> ids = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
                for (int i = 0; i < models.Count; i++)
                {
                    string[] m = models[i];
                    if (m.Length < 12 || !m[5].EndsWith(".obj", StringComparison.OrdinalIgnoreCase) ||
                        !m[6].EndsWith(".glb", StringComparison.OrdinalIgnoreCase) ||
                        m[5].Equals("NOT_INCLUDED", StringComparison.OrdinalIgnoreCase) ||
                        Path.GetFileName(m[5]) != m[5] || Path.GetFileName(m[6]) != m[6] ||
                        !ids.Add(m[1]) ||
                        !File.Exists(Absolute(root + "/Models_OBJ/" + m[5])) ||
                        !File.Exists(Absolute(root + "/Models_GLB/" + m[6])))
                    {
                        Debug.LogError("[L125] Missing / repeated / invalid model row at index " + i);
                        return false;
                    }
                }
                HashSet<string> componentIds = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
                for (int i = 0; i < placements.Count; i++)
                {
                    string[] record = placements[i];
                    if (record.Length < 8 || !componentIds.Add(record[0]) ||
                        !ids.Contains(record[1]) || record[2] != "DSX-33" || record[6] != "FALSE" || record[7] != "FALSE")
                    {
                        Debug.LogError("[L125] Invalid component placement row: " + record[0]);
                        return false;
                    }
                }
                HashSet<string> bomIds = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
                for (int i = 0; i < parts.Count; i++)
                {
                    string[] b = parts[i];
                    if (b.Length < 4 || b[3] != "DSX-33" || !bomIds.Add(b[0]) ||
                        !componentIds.Contains(b[0]) || !ids.Contains("L125_" + b[0]))
                    {
                        Debug.LogError("[L125] Invalid BOM model/placement join: " + b[0]);
                        return false;
                    }
                }
                for (int i = 0; i < models.Count; i++)
                {
                    string[] m = models[i];
                    if (m[4] != "DSX-33" || (m[10] == "TRUE" && !componentIds.Contains(m[1].Substring(5))))
                    {
                        Debug.LogError("[L125] Invalid model ownership/installable flag: " + m[1]);
                        return false;
                    }
                }
                HashSet<string> taskIds = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
                for (int i = 0; i < routes.Count; i++)
                {
                    string[] r = routes[i];
                    if (r.Length < 8 || !taskIds.Add(r[0]) || r[2] != "UNASSIGNED" || r[3] != "UNASSIGNED" ||
                        r[4] != "UNASSIGNED" || r[7] != "FALSE")
                    {
                        Debug.LogError("[L125] Route data unexpectedly changed; require schematic review: " + r[0]);
                        return false;
                    }
                }
                taskIds.Clear();
                for (int i = 0; i < viaRows.Count; i++)
                {
                    string[] v = viaRows[i];
                    if (v.Length < 7 || !taskIds.Add(v[0]) || v[1] != "UNASSIGNED" || v[2] != "TBD" ||
                        v[3] != "TBD" || v[6] != "FALSE")
                    {
                        Debug.LogError("[L125] Via data unexpectedly changed; require schematic review: " + v[0]);
                        return false;
                    }
                }
                if (!File.Exists(Absolute(root + "/Models_OBJ/401_L125_AssembledReference.obj")))
                {
                    Debug.LogError("[L125] Assembled reference missing.");
                    return false;
                }
                Debug.Log("[L125] Source validation PASS (file/manifest consistency ONLY): " +
                    "400 model pairs; 344 BOM; 432 routes/172 vias UNASSIGNED; W433 pins UNVERIFIED. " +
                    "Unity Play Mode and electrical qualification NOT_RUN.");
                if (writeLog)
                {
                    EnsureDirectory(Output);
                    WriteValidationReport(root, models.Count, parts.Count, routes.Count, viaRows.Count);
                    AssetDatabase.Refresh();
                }
                return true;
            }
            catch (Exception error)
            {
                Debug.LogError("[L125] Source validation failed: " + error);
                return false;
            }
        }

        private static List<string[]> ReadCsv(string path)
        {
            string file = Absolute(path);
            if (!File.Exists(file)) throw new FileNotFoundException(path);
            string[] lines = File.ReadAllLines(file);
            if (lines.Length == 0) throw new FormatException("Empty CSV: " + path);
            string header = lines[0].TrimStart('\uFEFF');
            string expected = null;
            switch (Path.GetFileName(path))
            {
                case "ModelManifest.csv": expected = "index,asset_id,kind,role,board,obj,glb,x_m,y_m,z_m,installable,certifiable"; break;
                case "ComponentBOM.csv": expected = "ref,kind,description,board"; break;
                case "ComponentPlacements.csv": expected = "ref,asset_id,board,x_m,y_m,z_m,installed_at_start,footprint_verified"; break;
                case "CopperRoutes_432_REQUIRES_SCHEMATIC.csv": expected = "id,domain,source_pad,dest_pad,net_id,layer,factory_copper,certifiable"; break;
                case "ViaTasks_172_REQUIRES_SCHEMATIC.csv": expected = "id,net_id,start_layer,end_layer,via_type,position_verified,verified"; break;
            }
            if (expected == null || !string.Equals(header, expected, StringComparison.Ordinal))
                throw new FormatException("Unexpected CSV schema: " + path);
            List<string[]> rows = new List<string[]>(lines.Length);
            for (int i = 1; i < lines.Length; i++)
            {
                if (string.IsNullOrWhiteSpace(lines[i])) continue;
                // Properly parse quoted commas in component descriptions.
                rows.Add(ParseCsvLine(lines[i]));
            }
            return rows;
        }

        private static string[] ParseCsvLine(string line)
        {
            List<string> values = new List<string>();
            StringBuilder value = new StringBuilder();
            bool quoted = false;
            for (int i = 0; i < line.Length; i++)
            {
                char c = line[i];
                if (c == '"')
                {
                    if (quoted && i + 1 < line.Length && line[i + 1] == '"')
                    {
                        value.Append('"');
                        i++;
                    }
                    else quoted = !quoted;
                }
                else if (c == ',' && !quoted)
                {
                    values.Add(value.ToString());
                    value.Length = 0;
                }
                else value.Append(c);
            }
            if (quoted) throw new FormatException("Unterminated quoted CSV cell");
            values.Add(value.ToString());
            return values.ToArray();
        }

