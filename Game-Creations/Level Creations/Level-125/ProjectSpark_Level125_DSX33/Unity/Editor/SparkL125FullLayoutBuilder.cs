                // Object models are local to their origin: placement is through the slot only.
                visual.transform.localPosition = Vector3.zero;
                visual.transform.localRotation = Quaternion.identity;
                Bounds visualBounds;
                if (!TryBounds(visual, out visualBounds))
                {
                    Debug.LogError("[L125] Component has no measurable Renderer: " + record[0]);
                    UnityEngine.Object.DestroyImmediate(root);
                    return;
                }
                trigger.size = visualBounds.size;
                trigger.center = visual.transform.InverseTransformPoint(visualBounds.center);
                visual.AddComponent<SparkL125VisualOnly>();
                PrefabUtility.SaveAsPrefabAsset(visual, prefabAsset);
                UnityEngine.Object.DestroyImmediate(visual);
            }
            List<SparkL125RouteEntry> routeData = new List<SparkL125RouteEntry>(432);
