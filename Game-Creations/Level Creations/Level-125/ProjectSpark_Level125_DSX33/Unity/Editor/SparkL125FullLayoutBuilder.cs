                Child(adapters.transform, SafeName(requiredServices[i]))
                    .AddComponent<SparkL125IntegrationAnchor>().Configure(requiredServices[i]);
            GameObject demo = Child(root.transform, "OPTIONAL_LinkBudget_Teaching_DEMO_NONCERTIFIABLE");
            demo.AddComponent<SparkL125LinkTeachingDemo>();

