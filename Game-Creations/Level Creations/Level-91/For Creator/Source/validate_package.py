from pathlib import Path
import csv,json,collections,math
import numpy as np,trimesh
ROOT=Path('/mnt/data/ProjectSpark_Level91_HD_AAA')
checks=[]
def check(name,test,detail=''):
 checks.append(dict(check=name,status='PASS' if test else 'FAIL',detail=detail))
 if not test:print('FAIL',name,detail,flush=True)
def table(name):
 with (ROOT/name).open() as f:return list(csv.DictReader(f))
m=json.loads((ROOT/'Model_Manifest.json').read_text())
models=list((ROOT/'Models').glob('[0-9][0-9]_*.fbx'))
glbs=list((ROOT/'GLB').glob('[0-9][0-9]_*.glb'))
check('96 numbered FBXs',len(models)==96,len(models))
check('96 numbered GLBs',len(glbs)==96,len(glbs))
check('model manifest 96',len(m['models'])==96)
check('assembled FBX', (ROOT/'Models'/m['assembled_fbx']).exists())
check('assembled GLB', (ROOT/'GLB'/m['assembled_glb']).exists())
check('distinct model names',len(set(r['name'] for r in m['models']))==96)
check('valid FBX binary signature',all(p.read_bytes()[:18]==b'Kaydara FBX Binary' for p in models))
check('FBX version 7400',all(int.from_bytes(p.read_bytes()[23:27],'little')==7400 for p in models))
check('GLB magic and version',all((p.open('rb').read(8)==b'glTF\x02\x00\x00\x00') for p in glbs))
check('all individual model bytes nonempty',all(p.stat().st_size>400 for p in models+glbs))
check('96 GLBs match named models',all((ROOT/'GLB'/q['glb']).exists() for q in m['models']))
check('96 FBXs match named models',all((ROOT/'Models'/q['fbx']).exists() for q in m['models']))
check('mesh triangles >200k',m['triangle_count']>200000,m['triangle_count'])
check('mesh count > 900',m['mesh_chunk_count']>900,m['mesh_chunk_count'])
check('84 pivot metadata',m['animation_pivots']==84)
check('260 socket metadata',m['decorative_sockets']==260)
check('182 wire metadata',m['planned_player_wires']==182)
check('364 endpoints metadata',m['proposed_independent_logical_endpoints']==364)
check('source has no gameplay wired claim',m['actual_player_wires_included'] is False)
check('source has no SparkTerminals claim',m['functional_sparkterminals_included'] is False)
check('Unity compile not claimed',m['unity_compilation_tested'] is False)
check('Unity Play Mode not claimed',m['unity_playmode_tested'] is False)
scene_nodes=[];mesh_total=0;bad_scene=[]
for q in m['models']:
 p=ROOT/'GLB'/q['glb']
 try:
  scene=trimesh.load(str(p),force='scene')
  nn=list(scene.graph.nodes)
  if not scene.geometry or len(scene.geometry)<1 or any(not np.isfinite(g.vertices).all() for g in scene.geometry.values()):bad_scene.append(q['glb'])
  tris=sum(len(g.faces) for g in scene.geometry.values())
  if tris!=q['triangles']:bad_scene.append(f"{q['name']} tri mismatch {tris} vs {q['triangles']}")
  if not any(node==q['name'] for node in nn):bad_scene.append(f"{q['name']} missing root node")
  if any('L90_' in node for node in nn):bad_scene.append(f"{q['name']} incorrectly names L90")
  mesh_total+=tris;scene_nodes.extend(nn)
 except Exception as e:bad_scene.append(f"{q['glb']} error: {e}")
check('every GLB imports as actual scene mesh',not bad_scene,';'.join(bad_scene[:4]))
check('total imported GLB triangles equals manifest',mesh_total==m['triangle_count'],mesh_total)
pivots=table('Animation_Rigs.csv');sockets=table('Visual_Terminal_Sockets_260.csv')
wires=table('Gameplay_Wiring_Concept_W001_W182.csv');logical=table('Terminal_Logical_Port_Reconciliation_364.csv')
conflict=table('Terminal_Anchor_Signal_Conflict_Report.csv');objectives=table('Objective_Certification_Plan_6.csv')
check('84 distinct pivot names',len(pivots)==len(set(x['Pivot'] for x in pivots))==84)
check('84 pivot nodes imported',all(sum(node==p['Pivot'] for node in scene_nodes)==1 for p in pivots))
check('pivots with declared XYZ',all(all(math.isfinite(float(p[f'World{ax}_m'])) for ax in 'XYZ') for p in pivots))
check('260 distinct visual IDs',len(sockets)==len(set(s['AnchorID'] for s in sockets))==260)
check('260 visual nodes imported',all(sum(node=='SOCKET_'+a['AnchorID'] for node in scene_nodes)==1 for a in sockets))
check('182 distinct planned IDs',len(wires)==len(set(q['WireID'] for q in wires))==182)
check('wire numbering contiguous',sorted(q['WireID'] for q in wires)==[f'W{i:03d}' for i in range(1,183)])
check('364 independent logical contacts',len(logical)==364)
check('all wire endpoints map to source models',all(q['SourceModel'] in [x['name'] for x in m['models']] and q['TargetModel'] in [x['name'] for x in m['models']] for q in wires))
sm={q['AnchorID']:q['OwnerModel'] for q in sockets}
check('all source visual anchor ownerships valid',all(sm[q['SourceVisualAnchor']]==q['SourceModel'] for q in wires))
check('all target visual anchor ownerships valid',all(sm[q['TargetVisualAnchor']]==q['TargetModel'] for q in wires))
check('logical contacts all unique',len(set(q['FunctionalPortID'] for q in logical))==364)
check('all signal conflicts explicitly documented',len(conflict)==m['reused_socket_locations'])
check('mixed-signal conflict count matches manifest',sum(q['MixedSignalKinds']=='True' for q in conflict)==m['mixed_signal_socket_locations'])
check('only W163 is marked critical',[q['WireID'] for q in wires if q['Critical']=='YES']==['W163'])
w163=next(q for q in wires if q['WireID']=='W163')
check('W163 source exact model',w163['SourceModel']=='L91_PrimaryAtomicClockReference')
check('W163 destination exact model',w163['TargetModel']=='L91_NavigationIntegritySafetyPLC')
check('W163 endpoint IDs exact',w163['SourceVisualAnchor']=='P104' and w163['TargetVisualAnchor']=='P221')
check('W163 feedback kind exact',w163['SignalKind']=='TIME_REFERENCE_FEEDBACK')
check('W163 functional outputs appear',any(q['FunctionalPortID']=='TRUSTED_TIME_REFERENCE_OUT' for q in logical) and any(q['FunctionalPortID']=='TRUSTED_TIME_REFERENCE_IN' for q in logical))
check('six objective design records',len(objectives)==6)
check('all objectives are NOT implemented',all(q['Implemented']=='NO' for q in objectives))
check('36 texture maps',len(list((ROOT/'Textures').glob('*.png')))==36)
check('12 texture manifest sets',len(json.loads((ROOT/'Texture_Manifest.json').read_text())['materials'])==12)
check('four Unity art scripts',len(list((ROOT/'Unity_Optional').glob('*.cs')))==4)
check('all Unity scripts named Level91',all('Level91' in q.name for q in (ROOT/'Unity_Optional').glob('*.cs')))
check('source exporters included',all((ROOT/'Source'/x).exists() for x in ('build_level91.py','geometry_export_core.py','make_textures.py')))
check('W163 recovery document included',(ROOT/'W163_Critical_Atomic_Clock_Recovery.md').exists())
check('collision and LOD plan included',(ROOT/'Collision_LOD_Production_Plan.csv').exists())
check('no precomputed gameplay pass flags in manifest',not m['objective_certifications_implemented'])
report={'level':'91','check_total':len(checks),'passed':sum(q['status']=='PASS' for q in checks),'failed':sum(q['status']=='FAIL' for q in checks),'checks':checks,'disclaimer':'Structural file and metadata checks only. Unity compilation, Play Mode, sensor simulation and playable electrical topology were NOT tested.'}
(ROOT/'Reports'/'Verification_Report.json').write_text(json.dumps(report,indent=2))
print('VERIFICATION',report['passed'],'/',report['check_total'],'checks',flush=True)
if report['failed']:raise SystemExit(1)
