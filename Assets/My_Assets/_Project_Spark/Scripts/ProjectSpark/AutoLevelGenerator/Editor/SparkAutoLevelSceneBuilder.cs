#if UNITY_EDITOR
using System;
using System.Collections.Generic;
using System.IO;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using UnityEngine.SceneManagement;

namespace ProjectSpark.AutoLevelGenerator.Editor
{
    public static class SparkAutoLevelSceneBuilder
    {
        private const string GeneratedSuffix = "_AUTO_GENERATED";

        public static void Generate(SparkAutoLevelRecipe recipe, SparkAutoLevelBlueprint importedBlueprint,
            SparkAutoLevelBuildReport report, bool buildGameScene, bool buildReferenceScene)
        {
            string output = recipe.generatedAssetsFolder.TrimEnd('/');
            if (!output.StartsWith("Assets/", StringComparison.Ordinal))
                throw new InvalidOperationException("Generated folder must live beneath Assets/");
            EnsureFolder(output);
            string blueprintPath = output + "/L" + recipe.levelId + "_Blueprint.asset";
            var existing = AssetDatabase.LoadAssetAtPath<SparkAutoLevelBlueprint>(blueprintPath);
            SparkAutoLevelBlueprint blueprint;
            if (existing == null) { AssetDatabase.CreateAsset(importedBlueprint, blueprintPath); blueprint = importedBlueprint; }
            else { EditorUtility.CopySerialized(importedBlueprint, existing); EditorUtility.SetDirty(existing); blueprint = existing;
                UnityEngine.Object.DestroyImmediate(importedBlueprint); }
            AssetDatabase.SaveAssets();

            // Exact, filename-based lookup. Never silently substitute a different component mesh.
            var models = BuildModelLookup(recipe, report);
            for (int i = 0; i < blueprint.Parts.Count; i++)
            {
                SparkAutoPart part = blueprint.Parts[i];
                string discovered;
                if (models.TryGetValue(part.Id, out discovered)) part.AssetPath = discovered;
            }
            EditorUtility.SetDirty(blueprint);
            var materials = SparkAutoURPMaterialBuilder.Build(recipe, report);
            if (buildGameScene) BuildScene(recipe, blueprint, output, models, materials, false, report);
            if (buildReferenceScene) BuildScene(recipe, blueprint, output, models, materials, true, report);
            AssetDatabase.SaveAssets();
            AssetDatabase.Refresh();
        }

        private static void BuildScene(SparkAutoLevelRecipe recipe, SparkAutoLevelBlueprint blueprint, string output,
            Dictionary<string, string> models, Dictionary<string, Material> materials, bool referenceOnly, SparkAutoLevelBuildReport report)
        {
            Scene priorScene = SceneManager.GetActiveScene();
            Scene newScene = EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Additive);
            try
            {
                SceneManager.SetActiveScene(newScene);
                string phase = referenceOnly ? "REFERENCE" : "EMPTY_GAMEPLAY";
                string rootName = "L" + recipe.levelId + "_" + recipe.boardId + "_" + phase + GeneratedSuffix;
                var root = new GameObject(rootName);
                var marker = root.AddComponent<SparkAutoGeneratedMarker>();
                marker.Configure(recipe.levelId, referenceOnly);
                var runtime = root.AddComponent<SparkAutoLevelRuntime>();
                runtime.Configure(blueprint, referenceOnly);
                var board = NewChild("PCB_And_PermanentArt", root.transform);
                var targets = NewChild("AuthorizedPlacementTargets_UNBOUND", root.transform);
                var service = NewChild("ServiceableCooling_Staging", root.transform);
                var reference = NewChild("CompletedShowcase_ReferenceOnly", root.transform);
                var nonVisual = NewChild("ElectricalTopology_RequiresProjectAdapter", root.transform);
                NewChild("ObjectiveAuthority_RequiresLevelGamePlayManager", root.transform);
                NewChild("VirtualInstruments_BindExistingWorldSpaceUI", root.transform);
                NewChild("Faults_RequiresRealSimulation", root.transform);
                NewChild("WiringAndVias_NotApprovedUntilSchematic", nonVisual.transform);

                float posFactor = blueprint.MillimetersToUnityUnits;
                int actualPartAssets = 0;
                for (int i = 0; i < blueprint.Parts.Count; i++)
                {
                    var part = blueprint.Parts[i];
                    string assetPath;
                    GameObject prefab = ResolveModel(part.Id, models, out assetPath);
                    if (part.Installable)
                    {
                        if (!referenceOnly)
                        {
                            GameObject target = NewChild("FOOTPRINT_" + part.Id, targets.transform);
                            target.transform.localPosition = MillimeterToScene(part, posFactor);
                            target.transform.localRotation = Quaternion.Euler(0, -part.OrientationDegrees, 0);
                            var box = target.AddComponent<BoxCollider>();
                            box.size = new Vector3(0.005f, 0.002f, 0.005f);
                            box.isTrigger = false;
                            var interaction = target.AddComponent<SparkAutoPlacementTarget>();
                            interaction.Configure(part.Id, part.Type, runtime, false, prefab);
                            // Target collider is not an actual pin/pad map; integration must replace with verified contacts.
                        }
                        if (prefab != null) actualPartAssets++;
                        continue;
                    }
                    if (IsLayerReference(part)) continue; // Internal copper visualization is not physical installed routing.
                    if (IsServiceHardware(part))
                    {
                        if (!referenceOnly && prefab != null) InstantiateModel(prefab, service.transform, part, recipe, materials);
                        continue;
                    }
                    if (prefab != null)
                    {
                        InstantiateModel(prefab, board.transform, part, recipe, materials);
                        if (string.Equals(part.Id, recipe.bareBoardId, StringComparison.Ordinal))
                            CheckBoardBounds(board.transform, blueprint, report);
                    }
                    else report.Warn("Supporting model not imported: " + part.Id);
                }
                report.Info("L" + recipe.levelId + " component meshes resolved for placement preview: " + actualPartAssets + "/" + blueprint.InstallableCount);

                bool hasAssembledFBX = false;
                if (!string.IsNullOrWhiteSpace(recipe.assembledBoardModelName))
                {
                    string assembledPath;
                    var assembled = ResolveModel(recipe.assembledBoardModelName, models, out assembledPath);
                    if (assembled != null)
                    {
                        GameObject view = (GameObject)PrefabUtility.InstantiatePrefab(assembled);
                        view.name = "ASSEMBLED_REFERENCE_NO_PROGRESS";
                        view.transform.SetParent(reference.transform, false);
                        view.transform.localScale = Vector3.one * recipe.visualScaleMultiplier;
                        SparkAutoURPMaterialBuilder.Apply(view, materials);
                        hasAssembledFBX = true;
                    }
                    else report.Warn("Assembled FBX not found: " + recipe.assembledBoardModelName +
                        "; optional composite visual preview can be generated from modular assets");
                }
                if (referenceOnly && !hasAssembledFBX)
                {
                    int composed = 0;
                    for (int i = 0; i < blueprint.Parts.Count; i++)
                    {
                        SparkAutoPart piece = blueprint.Parts[i];
                        if (IsLayerReference(piece) || string.Equals(piece.Type, "FAULT_OVERLAY", StringComparison.OrdinalIgnoreCase)) continue;
                        string subPath;
                        var source = ResolveModel(piece.Id, models, out subPath);
                        if (source == null) continue;
                        InstantiateModel(source, reference.transform, piece, recipe, materials);
                        composed++;
                    }
                    report.Warn("ASSEMBLED_FBX_MISSING: generated a " + composed + "-mesh composite reference " +
                        "from the source manifest. This is art only; inspect alignment and materials.");
                }
                reference.SetActive(referenceOnly);
                service.SetActive(false); // Serviceable covers/heatsinks must be installed by gameplay, not preplaced.
                if (referenceOnly) { board.SetActive(false); targets.SetActive(false); }

                CreatePreviewLight(root.transform);
                CreateInspectionCamera(root.transform, blueprint);
                string prefabPath = output + "/" + rootName + ".prefab";
                bool success;
                PrefabUtility.SaveAsPrefabAsset(root, prefabPath, out success);
                if (!success) report.Error("Prefab save failed: " + prefabPath);
                string scenePath = output + "/" + rootName + ".unity";
                if (!EditorSceneManager.SaveScene(newScene, scenePath)) report.Error("Scene save failed: " + scenePath);
                else report.Info("Generated scene + prefab: " + scenePath);
            }
            finally
            {
                EditorSceneManager.CloseScene(newScene, true);
                if (priorScene.IsValid() && priorScene.isLoaded) SceneManager.SetActiveScene(priorScene);
            }
        }

        private static void CreateInspectionCamera(Transform parent, SparkAutoLevelBlueprint blueprint)
        {
            GameObject go = NewChild("BoardInspectionCamera", parent);
            Camera cam = go.AddComponent<Camera>();
            cam.orthographic = true;
            cam.orthographicSize = Mathf.Max(blueprint.BoardWidthMm, blueprint.BoardHeightMm) *
                                   blueprint.MillimetersToUnityUnits * 0.68f;
            cam.nearClipPlane = 0.01f;
            cam.farClipPlane = 5f;
            cam.clearFlags = CameraClearFlags.SolidColor;
            cam.backgroundColor = new Color(0.025f, 0.044f, 0.072f, 1f);
            go.transform.localPosition = new Vector3(0f, 0.55f, 0f);
            go.transform.localRotation = Quaternion.Euler(90f, 0f, 0f);
            go.tag = "MainCamera";
        }

        private static void CreatePreviewLight(Transform parent)
        {
            GameObject g = NewChild("EditorPreview_DirectionalLight", parent);
            Light light = g.AddComponent<Light>();
            light.type = LightType.Directional;
            light.intensity = 1.35f;
            light.shadows = LightShadows.Soft;
            g.transform.localRotation = Quaternion.Euler(52, -25, 0);
        }

        private static void CheckBoardBounds(Transform artRoot, SparkAutoLevelBlueprint blueprint, SparkAutoLevelBuildReport report)
        {
            var renderers = artRoot.GetComponentsInChildren<Renderer>(true);
            for (int i = 0; i < renderers.Length; i++)
            {
                if (!renderers[i].name.Contains("EmptyPCB")) continue;
                Vector3 size = renderers[i].bounds.size;
                float expectedX = blueprint.BoardWidthMm * blueprint.MillimetersToUnityUnits;
                float expectedZ = blueprint.BoardHeightMm * blueprint.MillimetersToUnityUnits;
                float largest = Mathf.Max(size.x, Mathf.Max(size.y, size.z));
                if (largest < expectedX * 0.8f || largest > expectedX * 1.25f)
                    report.Warn("BOARD_SCALE_REVIEW_REQUIRED: imported PCB max dimension " + largest.ToString("F4") +
                                " Unity units vs expected " + expectedX.ToString("F4") + ". Check FBX importer scale; do not double convert.");
                break;
            }
        }

        private static bool IsLayerReference(SparkAutoPart part)
        {
            return part.Type != null && (part.Type.IndexOf("PLANE", StringComparison.OrdinalIgnoreCase) >= 0 ||
                part.Type.IndexOf("LAYER", StringComparison.OrdinalIgnoreCase) >= 0);
        }
        private static bool IsServiceHardware(SparkAutoPart part)
        {
            if (part.Type == null) return false;
            return part.Type.IndexOf("HEATSINK", StringComparison.OrdinalIgnoreCase) >= 0 ||
                   part.Type.IndexOf("THERMAL_PAD", StringComparison.OrdinalIgnoreCase) >= 0 ||
                   part.Type.IndexOf("SPREADER", StringComparison.OrdinalIgnoreCase) >= 0;
        }

        private static Vector3 MillimeterToScene(SparkAutoPart part, float scale)
        {
            // Assets author XY as board plane with Z normal; Unity commonly imports FBX as XZ with Y normal.
            return new Vector3(part.Xmm * scale, part.Zmm * scale, part.Ymm * scale);
        }
        private static GameObject NewChild(string name, Transform parent)
        {
            var go = new GameObject(name);
            go.transform.SetParent(parent, false);
            return go;
        }
        private static void InstantiateModel(GameObject prefab, Transform parent, SparkAutoPart part, SparkAutoLevelRecipe r, Dictionary<string, Material> materials)
        {
            var go = (GameObject)PrefabUtility.InstantiatePrefab(prefab);
            go.name = part.Id;
            go.transform.SetParent(parent, false);
            go.transform.localPosition = MillimeterToScene(part, r.millimetersToUnityUnits);
            go.transform.localRotation = Quaternion.Euler(0, -part.OrientationDegrees, 0);
            go.transform.localScale = Vector3.one * r.visualScaleMultiplier;
            SparkAutoURPMaterialBuilder.Apply(go, materials);
        }

        private static Dictionary<string, string> BuildModelLookup(SparkAutoLevelRecipe recipe, SparkAutoLevelBuildReport report)
        {
            var map = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
            string root = recipe.sourceAssetsFolder.TrimEnd('/') + "/Models_FBX";
            if (!AssetDatabase.IsValidFolder(root)) { report.Error("Models_FBX missing: " + root); return map; }
            string[] guids = AssetDatabase.FindAssets("t:Model", new[] { root });
            for (int i = 0; i < guids.Length; i++)
            {
                string path = AssetDatabase.GUIDToAssetPath(guids[i]);
                if (!path.EndsWith(".fbx", StringComparison.OrdinalIgnoreCase)) continue;
                string basename = Path.GetFileNameWithoutExtension(path);
                string id = basename;
                int u = basename.IndexOf('_');
                if (u > 0)
                {
                    int prefixNumber;
                    if (int.TryParse(basename.Substring(0, u), out prefixNumber)) id = basename.Substring(u + 1);
                }
                if (map.ContainsKey(id)) report.Warn("Duplicate FBX model ID: " + id);
                else map.Add(id, path);
            }
            if (!string.IsNullOrEmpty(recipe.bareBoardId) && !map.ContainsKey(recipe.bareBoardId))
                report.Error("Bare PCB model missing/failed to import: " + recipe.bareBoardId);
            if (recipe.expectedModels > 0 && map.Count < recipe.expectedModels)
                report.Warn("Unity loaded " + map.Count + " FBX models; expected at least " + recipe.expectedModels + ". ASCII FBX support may require conversion.");
            return map;
        }

        private static GameObject ResolveModel(string id, Dictionary<string, string> models, out string assetPath)
        {
            // Always initialize out parameters: || short-circuits when id is null or empty.
            assetPath = null;
            if (string.IsNullOrEmpty(id) || models == null || !models.TryGetValue(id, out assetPath))
                return null;

            return AssetDatabase.LoadAssetAtPath<GameObject>(assetPath);
        }

        public static void EnsureFolder(string path)
        {
            string[] segments = path.Split('/');
            if (segments.Length < 2 || segments[0] != "Assets")
                throw new ArgumentException("Folder must be under Assets/");
            string current = "Assets";
            for (int i = 1; i < segments.Length; i++)
            {
                string next = current + "/" + segments[i];
                if (!AssetDatabase.IsValidFolder(next)) AssetDatabase.CreateFolder(current, segments[i]);
                current = next;
            }
        }
    }
}
