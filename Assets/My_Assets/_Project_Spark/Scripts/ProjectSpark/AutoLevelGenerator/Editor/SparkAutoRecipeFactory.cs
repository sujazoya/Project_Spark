#if UNITY_EDITOR
using System;
using System.IO;
using System.IO.Compression;
using System.Collections.Generic;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace ProjectSpark.AutoLevelGenerator.Editor
{
    /// <summary>
    /// Creates an art-scaffolding recipe by inspecting a ZIP's real manifests.
    /// Does not create an electrical schematic or assume board dimensions.
    /// </summary>
    public static class SparkAutoRecipeFactory
    {
        public static string CreateFromZip(string zipPath, int levelId, string boardId, string title,
            float verifiedWidthMm, float verifiedHeightMm, int verifiedCopperLayers, SparkAutoLevelBuildReport report)
        {
            if (!File.Exists(zipPath)) throw new FileNotFoundException("ZIP does not exist", zipPath);
            if (levelId <= 0 || string.IsNullOrWhiteSpace(boardId)) throw new ArgumentException("Level ID and board ID required");
            if (verifiedWidthMm <= 0 || verifiedHeightMm <= 0)
                throw new ArgumentException("Measured/approved board width and height in mm are required; do not guess dimensions");
            if (verifiedCopperLayers < 1 || verifiedCopperLayers > 40) throw new ArgumentException("Enter a verified copper-layer count (1–40)");
            var recipe = new SparkAutoLevelRecipe {
                levelId = levelId, boardId = boardId.Trim(), title = title ?? "Level " + levelId,
                widthMm = verifiedWidthMm, heightMm = verifiedHeightMm, copperLayers = verifiedCopperLayers,
                millimetersToUnityUnits = 0.001f,
                sourceAssetsFolder = "Assets/ProjectSpark/Level" + levelId,
                generatedAssetsFolder = "Assets/ProjectSpark/AutoGeneratedLevels/Level" + levelId
            };
            var names = new List<string>();
            using (ZipArchive archive = ZipFile.OpenRead(zipPath))
            {
                for (int i = 0; i < archive.Entries.Count; i++) names.Add(archive.Entries[i].FullName.Replace('\\','/'));
                names.Sort(StringComparer.OrdinalIgnoreCase);
                string root = FindArchiveRoot(names);
                recipe.archiveRoot = root;
                recipe.modelsCsv = SelectName(names, root, "/Data/", "Models_", ".csv");
                recipe.componentsCsv = SelectName(names, root, "/Data/", "Components_", ".csv");
                recipe.routesCsv = SelectName(names, root, "/Data/", "Routes_", ".csv");
                recipe.viasCsv = SelectName(names, root, "/Data/", "Vias_", ".csv");
                recipe.objectivesJson = SelectName(names, root, "/Data/", "Objectives_", ".json");
                recipe.faultsJson = SelectName(names, root, "/Data/", "Faults_", ".json");
                if (string.IsNullOrEmpty(recipe.faultsJson))
                    recipe.faultsJson = SelectName(names, root, "/Data/", "Faults_", ".csv");
                recipe.safetyJson = SelectName(names, root, "/Data/", "_W", "Safety.json");
                recipe.expectedModels = CountCsv(archive, root, recipe.modelsCsv, report);
                recipe.expectedInstallable = CountCsv(archive, root, recipe.componentsCsv, report);
                recipe.expectedRoutes = CountCsv(archive, root, recipe.routesCsv, report);
                recipe.expectedVias = CountCsv(archive, root, recipe.viasCsv, report);
                // Do not infer objective count until the JSON has been parsed and reviewed.
                recipe.expectedObjectives = 0;
                for (int i = 0; i < names.Count; i++)
                {
                    string n = names[i];
                    if (!n.EndsWith(".fbx", StringComparison.OrdinalIgnoreCase)) continue;
                    string stem = Path.GetFileNameWithoutExtension(n);
                    string id = StripNumericPrefix(stem);
                    if (id.IndexOf("EmptyPCB", StringComparison.OrdinalIgnoreCase) >= 0 ||
                        id.IndexOf("BarePCB", StringComparison.OrdinalIgnoreCase) >= 0) recipe.bareBoardId = id;
                    if (id.IndexOf("Complete_Assembled_Board", StringComparison.OrdinalIgnoreCase) >= 0)
                        recipe.assembledBoardModelName = id;
                }
            }
            if (string.IsNullOrEmpty(recipe.modelsCsv) || string.IsNullOrEmpty(recipe.componentsCsv))
                throw new InvalidDataException("ZIP must include Data/*Models*.csv and Data/*Components*.csv");
            if (string.IsNullOrEmpty(recipe.bareBoardId)) report.Warn("Bare board FBX not found; recipe requires manual correction");
            if (string.IsNullOrEmpty(recipe.safetyJson)) report.Warn("Safety definition not found; functionality will remain blocked");
            report.Warn("REVIEW REQUIRED: Set the correct copperLayers, objective source, route/via mappings, and approval status before generation");
            string folder = SparkAutoRecipeRegistry.PreferredRecipesFolder();
            string path = folder + "/Level" + levelId + "_" + recipe.boardId + ".recipe.json";
            string absolute = SparkAutoLevelSourceImporter.ToAbsolute(path);
            if (File.Exists(absolute)) throw new IOException("Recipe already exists; will not overwrite: " + path);
            Directory.CreateDirectory(Path.GetDirectoryName(absolute));
            File.WriteAllText(absolute, JsonUtility.ToJson(recipe, true), Encoding.UTF8);
            AssetDatabase.Refresh();
            report.Info("Recipe created: " + path);
            return path;
        }

        private static string StripNumericPrefix(string value)
        {
            int index = value.IndexOf('_');
            int number;
            if (index > 0 && int.TryParse(value.Substring(0,index),out number)) return value.Substring(index+1);
            return value;
        }
        private static string FindArchiveRoot(List<string> names)
        {
            if (names.Count == 0) throw new InvalidDataException("ZIP is empty");
            string first = null;
            for (int i = 0; i < names.Count; i++)
            {
                string n = names[i].TrimStart('/');
                if (string.IsNullOrEmpty(n)) continue;
                int slash = n.IndexOf('/');
                if (slash <= 0) return string.Empty;
                string root = n.Substring(0,slash);
                if (first == null) first = root;
                if (!string.Equals(first,root,StringComparison.Ordinal)) return string.Empty;
            }
            return first ?? string.Empty;
        }
        private static string SelectName(List<string> names, string root, string folder, string marker, string suffix)
        {
            for (int i = 0; i < names.Count; i++)
            {
                string n = names[i];
                if ((n.IndexOf(folder, StringComparison.OrdinalIgnoreCase) < 0 &&
                     !n.StartsWith(folder.Trim('/'), StringComparison.OrdinalIgnoreCase)) ||
                    n.IndexOf(marker, StringComparison.OrdinalIgnoreCase) < 0 ||
                    !n.EndsWith(suffix, StringComparison.OrdinalIgnoreCase)) continue;
                string prefix = string.IsNullOrEmpty(root) ? "" : root.TrimEnd('/') + "/";
                if (prefix.Length > 0 && !n.StartsWith(prefix, StringComparison.Ordinal)) continue;
                return n.Substring(prefix.Length);
            }
            return string.Empty;
        }
        private static int CountCsv(ZipArchive archive, string root, string relative, SparkAutoLevelBuildReport report)
        {
            if (string.IsNullOrEmpty(relative)) return 0;
            string path = string.IsNullOrEmpty(root) ? relative : root + "/" + relative;
            var entry = archive.GetEntry(path);
            if (entry == null) { report.Error("ZIP manifest missing: " + path); return 0; }
            using (var stream = entry.Open())
            using (var reader = new StreamReader(stream))
                return SparkAutoCsvTable.Parse(reader.ReadToEnd()).RowCount;
        }
    }
}
