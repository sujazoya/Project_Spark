        [MenuItem(Menu + "1. Build FULL Level_120_Layout")]
        public static void BuildFull()
        {
            string source = FindSourceRoot();
            if (string.IsNullOrEmpty(source)) return;
            if (!ValidateSource(source, true)) return;
            if (!SparkL120URPPBRMaterialBuilder.Build(source)) return;
            EnsureDirectory(Output);
            EnsureDirectory(Output + "/ComponentVisualPrefabs");
            AssetDatabase.Refresh();
            // The complete visual board is a separate prefab; it never enters gameplay inventory.
            if (!CreateCompleteMotherboardPrefab(source)) return;

            List<string[]> modelRows = ReadCsv(source + "/Data/ModelManifest.csv");
            List<string[]> bomRows = ReadCsv(source + "/Data/ComponentBOM.csv");
            List<string[]> placementRows = ReadCsv(source + "/Data/ComponentPlacements.csv");
            List<string[]> routeRows = ReadCsv(source + "/Data/CopperRoutes_352_REQUIRES_SCHEMATIC.csv");
            List<string[]> viaRows = ReadCsv(source + "/Data/ViaTasks_132_REQUIRES_SCHEMATIC.csv");
            Dictionary<string, string[]> models = new Dictionary<string, string[]>(StringComparer.OrdinalIgnoreCase);
            Dictionary<string, string[]> parts = new Dictionary<string, string[]>(StringComparer.OrdinalIgnoreCase);
            for (int i = 0; i < modelRows.Count; i++) models.Add(modelRows[i][1], modelRows[i]);
            for (int i = 0; i < bomRows.Count; i++) parts.Add(bomRows[i][0], bomRows[i]);

            // Avoid silently destroying the user's open and modified Project Spark scenes.
            if (!EditorSceneManager.SaveCurrentModifiedScenesIfUserWantsTo())
            {
                Debug.LogWarning("[L120] Build cancelled so open unsaved scenes are preserved.");
                return;
            }
            Scene scene = EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Single);
            GameObject root = new GameObject(RootName);
            root.AddComponent<SparkL120LayoutMarker>();
            GameObject art = Child(root.transform, "VisualArtRoot_Metres");
            GameObject actualBoard = Child(art.transform, "EmptyPCB_Physical_520x380mm");
            string[] boardRecord;
            if (!models.TryGetValue("L120_PCB_Main", out boardRecord))
            {
                Debug.LogError("[L120] Missing PCB_Main manifest record.");
                UnityEngine.Object.DestroyImmediate(root);
                return;
            }
            GameObject board = ImportModel(source, boardRecord[5], actualBoard.transform, "PCB_Main_RealScale");
            Bounds boardBounds;
            if (board == null || !TryBounds(board, out boardBounds) ||
                Mathf.Abs(boardBounds.size.x - PhysicalWidth) > .002f ||
                Mathf.Abs(boardBounds.size.z - PhysicalDepth) > .002f)
            {
                Debug.LogError("[L120] Board mesh import/scale mismatch. Expected 0.520 x 0.380 m. " +
                               "Do not generate primitive fallback geometry.");
                UnityEngine.Object.DestroyImmediate(root);
                return;
            }
            actualBoard.AddComponent<SparkL120VisualOnly>();
            BoxCollider boardClickArea = actualBoard.AddComponent<BoxCollider>();
            boardClickArea.size = new Vector3(PhysicalWidth, .0022f, PhysicalDepth);
            boardClickArea.center = Vector3.zero;
            GameObject layerArtwork = Child(art.transform, "32_InspectionLayerReferences_DISABLED");
            GameObject otherArtwork = Child(art.transform, "OtherUnverifiedFactoryArtwork_DISABLED");
            for (int i = 0; i < modelRows.Count; i++)
            {
                string[] item = modelRows[i];
                if (item[10] == "TRUE" || item[1] == "L120_PCB_Main") continue;
                Transform owner = item[2] == "layer" ? layerArtwork.transform : otherArtwork.transform;
                GameObject decoration = ImportModel(source, item[5], owner, "NONCONDUCTIVE_" + item[1]);
                if (decoration != null) decoration.AddComponent<SparkL120VisualOnly>();
            }
            layerArtwork.SetActive(false);
            otherArtwork.SetActive(false);

            GameObject authoring = Child(root.transform, "GameplayAuthoringRoot_NONCERTIFIABLE");
            GameObject targets = Child(authoring.transform, "264_UninstalledComponentTargets");
            GameObject routes = Child(authoring.transform, "352_Routes_UNASSIGNED_BLOCKED");
            GameObject vias = Child(authoring.transform, "132_Vias_UNASSIGNED_BLOCKED");
            // Six visible authoring axes correspond to six modelled power-stage zones.
            // These are geometry grouping aids only; no motor, terminal or STO is bound.
            GameObject axes = Child(authoring.transform, "SixAxisDriveAuthoringZones_UNBOUND");
            for (int axis = 0; axis < 6; axis++)
            {
                GameObject zone = Child(axes.transform, "Axis_" + (char)('A' + axis) + "_PowerStage_UNBOUND");
                zone.transform.localPosition = new Vector3(.101f, .0011f, .15f - axis * .060f);
                zone.AddComponent<SparkL120IntegrationAnchor>()
                    .Configure("Schematic-approved six-axis motor stage and encoder binding required");
            }
            GameObject inventory = Child(authoring.transform, "InventoryPrefabs_AsAssets_NotYetInstalled");
            inventory.AddComponent<SparkL120VisualOnly>();
            List<SparkL120ComponentEntry> componentData = new List<SparkL120ComponentEntry>(264);
            for (int i = 0; i < placementRows.Count; i++)
            {
                string[] record = placementRows[i];
                string[] bomItem;
                string[] model;
                if (!parts.TryGetValue(record[0], out bomItem) || !models.TryGetValue(record[1], out model))
                {
                    Debug.LogError("[L120] Missing component/BOM/asset join: " + record[0]);
                    UnityEngine.Object.DestroyImmediate(root);
                    return;
                }
                float x = F(record[3]);
                float y = F(record[4]);
                float z = F(record[5]);
                GameObject slot = Child(targets.transform, "SLOT_" + record[0]);
                slot.transform.localPosition = new Vector3(x, y, z);
                slot.AddComponent<SparkL120PlacementSlot>().Configure(record[0], record[1], bomItem[1]);
                BoxCollider trigger = slot.AddComponent<BoxCollider>();
                trigger.isTrigger = true;
                bool substantial = bomItem[1] == "ic" || bomItem[1] == "connector" || bomItem[1] == "shield";
                trigger.size = substantial ? new Vector3(.012f, .004f, .010f) : new Vector3(.005f, .002f, .004f);
                trigger.center = new Vector3(0f, .0007f, 0f);
                componentData.Add(new SparkL120ComponentEntry
                {
                    referenceId = record[0], assetId = record[1], kind = bomItem[1],
                    physicalLocationMetres = new Vector3(x, y, z),
                    footprintVerified = false, installedAtStart = false
                });
                string prefabAsset = Output + "/ComponentVisualPrefabs/L120_" + record[0] + ".prefab";
                GameObject visual = ImportModel(source, model[5], inventory.transform, "L120_" + record[0] + "_SourceVisual");
                if (visual == null)
                {
                    Debug.LogError("[L120] Missing importable component mesh " + model[5]);
                    UnityEngine.Object.DestroyImmediate(root);
                    return;
                }
                // Object models are local to their origin: placement is through the slot only.
                visual.transform.localPosition = Vector3.zero;
                visual.transform.localRotation = Quaternion.identity;
                visual.AddComponent<SparkL120VisualOnly>();
                PrefabUtility.SaveAsPrefabAsset(visual, prefabAsset);
                UnityEngine.Object.DestroyImmediate(visual);
            }
            List<SparkL120RouteEntry> routeData = new List<SparkL120RouteEntry>(352);
            for (int i = 0; i < routeRows.Count; i++)
            {
                string[] r = routeRows[i];
                Child(routes.transform, r[0] + "_" + SafeName(r[1]))
                    .AddComponent<SparkL120BlockedTask>()
                    .Configure(SparkL120TaskType.CopperRoute, r[0], r[1]);
                routeData.Add(new SparkL120RouteEntry
                {
                    id = r[0], domain = r[1], sourcePad = r[2], destinationPad = r[3],
                    netId = r[4], layer = r[5], certifiable = false
                });
            }
            List<SparkL120ViaEntry> viaData = new List<SparkL120ViaEntry>(132);
            for (int i = 0; i < viaRows.Count; i++)
            {
                string[] v = viaRows[i];
                Child(vias.transform, v[0] + "_BLOCKED")
                    .AddComponent<SparkL120BlockedTask>()
                    .Configure(SparkL120TaskType.Via, v[0], "Layer span TBD");
                viaData.Add(new SparkL120ViaEntry
                {
                    id = v[0], netId = v[1], fromLayer = v[2], toLayer = v[3], verified = false
                });
            }
            SparkL120SourceBlueprint blueprint = AssetDatabase.LoadAssetAtPath<SparkL120SourceBlueprint>(Output + "/L120_SourceBlueprint.asset");
            if (blueprint == null)
            {
                blueprint = ScriptableObject.CreateInstance<SparkL120SourceBlueprint>();
                AssetDatabase.CreateAsset(blueprint, Output + "/L120_SourceBlueprint.asset");
            }
            blueprint.SetSourceData(componentData, routeData, viaData);
            EditorUtility.SetDirty(blueprint);

            GameObject adapters = Child(root.transform, "ProjectSparkSystemBindings_REQUIRED_UNBOUND");
            string[] requiredServices = {
                "SparkCircuitSystem authoritative DC-link, six-axis bridge and ground topology",
                "SparkTerminal approved pin-level RAX-28 power, current and safety contacts",
                "LevelGamePlayManager six objective verification events",
                "Existing world-space virtual PCB test and repair UI",
                "Existing shop, shelf, inventory and component placement lifecycle",
                "Six independent six-axis motor power stages and DC-link precharge qualification",
                "Six absolute encoders and synchronized trajectory feedback qualification",
                "Bounded educational six-joint trajectories, homing, pose constraints and coordinated safe stop",
                "F1 axis C gate drive / F2 axis D encoder via / F3 axis F thermal authority",
                "W353 six-axis motion-ready and independent dual-STO supervisor",
                "Save/load evidence freshness and topology revision"
            };
            for (int i = 0; i < requiredServices.Length; i++)
                Child(adapters.transform, SafeName(requiredServices[i]))
                    .AddComponent<SparkL120IntegrationAnchor>().Configure(requiredServices[i]);
            GameObject demo = Child(root.transform, "OPTIONAL_SixAxisRobotMotion_Teaching_DEMO_NONCERTIFIABLE");
            demo.AddComponent<SparkL120RobotMotionTeachingDemo>();

            GameObject disabledReference = Child(root.transform, "Assembled_ART_REFERENCE_DISABLED_NEVER_GAMEPLAY");
            GameObject reference = ImportModel(source, "321_L120_AssembledReference.obj", disabledReference.transform, "Showcase_FullAssembly_ONLY");
            if (reference != null) reference.AddComponent<SparkL120VisualOnly>();
            disabledReference.AddComponent<SparkL120VisualOnly>();
            disabledReference.SetActive(false);

            PrefabUtility.SaveAsPrefabAsset(root, Output + "/Level_120_Layout.prefab");
            EditorSceneManager.SaveScene(scene, Output + "/Level_120_Layout.unity");
            AssetDatabase.SaveAssets();
            WriteValidationReport(source, modelRows.Count, componentData.Count, routeData.Count, viaData.Count);
            AssetDatabase.Refresh();
            Selection.activeGameObject = root;
            Debug.Log("[L120] Visual layout generated. COMPONENTS 0/264, ROUTES 0/352, VIAS 0/132, " +
                      "W353 OPEN, ALL AXES TORQUE DISABLED, STO A/B UNVERIFIED, OBJECTIVES 0/6; NOT CERTIFIABLE.");
        }


