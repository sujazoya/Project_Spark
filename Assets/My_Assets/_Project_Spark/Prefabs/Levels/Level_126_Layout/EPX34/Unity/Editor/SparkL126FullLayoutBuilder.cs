            inventory.AddComponent<SparkL126VisualOnly>();
            List<SparkL126ComponentEntry> componentData = new List<SparkL126ComponentEntry>(360);
            for (int i = 0; i < placementRows.Count; i++)
            {
                string[] record = placementRows[i];
                string[] bomItem;
                string[] model;
                if (!parts.TryGetValue(record[0], out bomItem) || !models.TryGetValue(record[1], out model))
                {
                    Debug.LogError("[L126] Missing component/BOM/asset join: " + record[0]);
