            Dictionary<string, string[]> parts = new Dictionary<string, string[]>(StringComparer.OrdinalIgnoreCase);
            for (int i = 0; i < modelRows.Count; i++) models.Add(modelRows[i][1], modelRows[i]);
            for (int i = 0; i < bomRows.Count; i++) parts.Add(bomRows[i][0], bomRows[i]);

            // Avoid silently destroying the user's open and modified Project Spark scenes.
            if (!EditorSceneManager.SaveCurrentModifiedScenesIfUserWantsTo())
            {
                Debug.LogWarning("[L126] Build cancelled so open unsaved scenes are preserved.");
                return;
            }
            Scene scene = EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Single);
            GameObject root = new GameObject(RootName);
            root.AddComponent<SparkL126LayoutMarker>();
            GameObject art = Child(root.transform, "VisualArtRoot_Metres");
            GameObject actualBoard = Child(art.transform, "EmptyPCB_Physical_640x500mm");
            string[] boardRecord;
            if (!models.TryGetValue("L126_PCB_Main", out boardRecord))
            {
                Debug.LogError("[L126] Missing PCB_Main manifest record.");
                UnityEngine.Object.DestroyImmediate(root);
                return;
            }
            GameObject board = ImportModel(source, boardRecord[5], actualBoard.transform, "PCB_Main_RealScale");
            Bounds boardBounds;
            if (board == null || !TryBounds(board, out boardBounds) ||
                Mathf.Abs(boardBounds.size.x - PhysicalWidth) > .002f ||
                Mathf.Abs(boardBounds.size.z - PhysicalDepth) > .002f)
            {
                Debug.LogError("[L126] Board mesh import/scale mismatch. Expected 0.640 x 0.500 m. " +
                               "Do not generate primitive fallback geometry.");
                UnityEngine.Object.DestroyImmediate(root);
                return;
            }
            actualBoard.AddComponent<SparkL126VisualOnly>();
            BoxCollider boardClickArea = actualBoard.AddComponent<BoxCollider>();
            boardClickArea.size = new Vector3(PhysicalWidth, .0032f, PhysicalDepth);
            boardClickArea.center = Vector3.zero;
            GameObject layerArtwork = Child(art.transform, "44_InspectionLayerReferences_DISABLED");
            GameObject otherArtwork = Child(art.transform, "OtherUnverifiedFactoryArtwork_DISABLED");
            for (int i = 0; i < modelRows.Count; i++)
            {
                string[] item = modelRows[i];
                if (item[10] == "TRUE" || item[1] == "L126_PCB_Main") continue;
                Transform owner = item[2] == "layer" ? layerArtwork.transform : otherArtwork.transform;
                GameObject decoration = ImportModel(source, item[5], owner, "NONCONDUCTIVE_" + item[1]);
                if (decoration != null)
                {
                    decoration.transform.localPosition = new Vector3(F(item[7]), F(item[8]), F(item[9]));
                    decoration.AddComponent<SparkL126VisualOnly>();
                }
            }
            layerArtwork.SetActive(false);
            otherArtwork.SetActive(false);

            GameObject authoring = Child(root.transform, "GameplayAuthoringRoot_NONCERTIFIABLE");
            GameObject targets = Child(authoring.transform, "360_UninstalledComponentTargets");
            GameObject routes = Child(authoring.transform, "448_Routes_UNASSIGNED_BLOCKED");
            GameObject vias = Child(authoring.transform, "180_Vias_UNASSIGNED_BLOCKED");
            // Visual integration anchors only: positions are planning hints, not certified pads.
            GameObject zones = Child(authoring.transform, "EclipsePowerZones_UNBOUND");
            string[] zoneNames = { "Energy_A", "Energy_B", "Independent_Load_Supervisor", "Solar_A_M1", "Solar_A_Q1", "Battery_B_R1", "Essential_Filter_C1", "W449_ENERGY_READY_OPEN" };
            Vector3[] zonePositions = {
                new Vector3(-.276f,.0016f,-.219f), new Vector3(-.229f,.0016f,-.219f),
                new Vector3(-.182f,.0016f,-.219f), new Vector3(-.276f,.0016f,-.174f),
                new Vector3(-.297f,.0016f,-.128f), new Vector3(.223f,.0016f,-.128f),
                new Vector3(-.297f,.0016f,-.104f), new Vector3(.223f,.0016f,.232f)
            };
            for (int zoneIndex = 0; zoneIndex < zoneNames.Length; zoneIndex++)
            {
                GameObject zone = Child(zones.transform, zoneNames[zoneIndex]);
                zone.transform.localPosition = zonePositions[zoneIndex];
                zone.AddComponent<SparkL126IntegrationAnchor>()
                    .Configure("Approved power distribution electrical schematic and physical contact authority required");
            }
