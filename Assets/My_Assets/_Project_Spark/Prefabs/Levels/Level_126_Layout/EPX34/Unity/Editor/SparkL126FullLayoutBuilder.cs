            string[] requiredServices = {
                "SparkCircuitSystem: approved protected power and return netlist",
                "SparkTerminal: approved 44-layer contacts and pin mapping",
                "LevelGamePlayManager: six independent objectives, 0/6 initially",
                "Existing virtual multimeter, oscilloscope, thermal diagnostics and repair UI",
                "Existing placement, shop, selection, rotate and wire tools; no global replacements",
                "U1/U2 redundant supervisors; U3 independent load inhibit",
                "M1/M2 solar regulators and bounded MPPT; qualified input current evidence",
