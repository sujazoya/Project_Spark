        private static bool CreateCompleteMotherboardPrefab(string source)
        {
            string file = source + "/Models_OBJ/417_L126_AssembledReference.obj";
            GameObject model = AssetDatabase.LoadAssetAtPath<GameObject>(file);
            if (model == null)
            {
                Debug.LogError("[L126] Missing complete assembled motherboard OBJ: " + file);
                return false;
            }
            GameObject root = new GameObject("L126_EPX34_CompleteMainboard_VISUAL_ONLY");
            try
            {
                root.AddComponent<SparkL126VisualOnly>();
                GameObject view = (GameObject)PrefabUtility.InstantiatePrefab(model);
                view.name = "CompleteMotherboard_All360Components_Showcase";
                view.transform.SetParent(root.transform, false);
                view.transform.localPosition = Vector3.zero;
                view.transform.localRotation = Quaternion.identity;
                SparkL126URPPBRMaterialBuilder.Bind(view);
                Bounds bound;
                if (!TryBounds(view, out bound) ||
                    Mathf.Abs(bound.size.x - PhysicalWidth) > .002f ||
                    Mathf.Abs(bound.size.z - PhysicalDepth) > .002f)
                {
                    Debug.LogError("[L126] Complete board model has incorrect dimensions; prefab not saved.");
                    return false;
                }
                Collider[] colliders = root.GetComponentsInChildren<Collider>(true);
                for (int i = 0; i < colliders.Length; i++)
                    UnityEngine.Object.DestroyImmediate(colliders[i]);
                PrefabUtility.SaveAsPrefabAsset(root,
                    Output + "/L126_CompleteMotherboard_VISUAL_ONLY.prefab");
                return true;
            }
            finally { UnityEngine.Object.DestroyImmediate(root); }
        }

        [MenuItem(Menu + "2. Place assembled VISUAL preview on SELECTED tabletop")]
        public static void PlacePreview()
        {
            GameObject selected = Selection.activeGameObject;
            if (selected == null)
            {
                Debug.LogError("[L126] Select existing Table_top (or tabletop Renderer) in Hierarchy first.");
                return;
            }
            if (selected.GetComponentInParent<SparkL126LayoutMarker>() != null)
            {
                Debug.LogError("[L126] Select the existing workshop tabletop, not a Level 126 object.");
                return;
            }
            string source = FindSourceRoot();
            if (string.IsNullOrEmpty(source)) return;
            if (GameObject.Find("L126_EPX34_VisualPreview_ONLY") != null)
            {
                Debug.LogWarning("[L126] Visual-only tabletop preview already exists. Not duplicating it.");
                return;
            }
            Renderer tableRenderer = selected.GetComponent<Renderer>();
            if (tableRenderer == null) tableRenderer = selected.GetComponentInChildren<Renderer>();
            if (tableRenderer == null)
            {
                Debug.LogError("[L126] Table_top has no measurable Renderer; cannot place or size the preview.");
                return;
            }
            GameObject imported = AssetDatabase.LoadAssetAtPath<GameObject>(source + "/Models_OBJ/417_L126_AssembledReference.obj");
            if (imported == null)
            {
                Debug.LogError("[L126] Assembled showcase OBJ unavailable.");
                return;
            }
            GameObject preview = new GameObject("L126_EPX34_VisualPreview_ONLY");
            Undo.RegisterCreatedObjectUndo(preview, "Create Level126 Visual Preview");
            preview.AddComponent<SparkL126VisualOnly>();
            GameObject visual = (GameObject)PrefabUtility.InstantiatePrefab(imported);
            visual.transform.SetParent(preview.transform, false);
            visual.name = "VisualShowcase_NotElectrical";
            SparkL126URPPBRMaterialBuilder.Bind(visual);
            float scale = Mathf.Min(PreviewWidth / PhysicalWidth, PreviewMaxDepth / PhysicalDepth);
            preview.transform.position = tableRenderer.bounds.center + Vector3.up *
                                        (tableRenderer.bounds.extents.y + 0.0016f * scale + .001f);
            preview.transform.rotation = selected.transform.rotation;
            preview.transform.localScale = Vector3.one * scale;
            Collider[] colliders = preview.GetComponentsInChildren<Collider>(true);
            for (int i = 0; i < colliders.Length; i++) UnityEngine.Object.DestroyImmediate(colliders[i]);
            Selection.activeGameObject = preview;
            Debug.Log("[L126] Placed visual-only assembled board preview. Physical model remains 0.640 x 0.500 m; " +
                      "presentation scale=" + scale.ToString("F3", Invariant) + ". No gameplay state modified.");
        }

