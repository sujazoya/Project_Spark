        private const string Menu = "Tools/Project Spark/Automatic Level Generator/118/";
        private const string Output = "Assets/ProjectSpark/AutoGeneratedLevels/Level118";
        private const string RootName = "L118_TSX26_THE_DETERMINISTIC_GRID";
        private const float PhysicalWidth = 0.480f;
        private const float PhysicalDepth = 0.340f;
        private const float PreviewWidth = 10.13f;
        private const float PreviewMaxDepth = 7.4f;
        private static readonly CultureInfo Invariant = CultureInfo.InvariantCulture;

        [MenuItem(Menu + "1. Build FULL Level_118_Layout")]
        public static void BuildFull()
        {
            string source = FindSourceRoot();
            if (string.IsNullOrEmpty(source)) return;
            if (!ValidateSource(source, true)) return;
            if (!SparkL118URPPBRMaterialBuilder.Build(source)) return;
            EnsureDirectory(Output);
            EnsureDirectory(Output + "/ComponentVisualPrefabs");
            AssetDatabase.Refresh();

            List<string[]> modelRows = ReadCsv(source + "/Data/ModelManifest.csv");
            List<string[]> bomRows = ReadCsv(source + "/Data/ComponentBOM.csv");
            List<string[]> placementRows = ReadCsv(source + "/Data/ComponentPlacements.csv");
            List<string[]> routeRows = ReadCsv(source + "/Data/CopperRoutes_320_REQUIRES_SCHEMATIC.csv");
            List<string[]> viaRows = ReadCsv(source + "/Data/ViaTasks_116_REQUIRES_SCHEMATIC.csv");
            Dictionary<string, string[]> models = new Dictionary<string, string[]>(StringComparer.OrdinalIgnoreCase);
            Dictionary<string, string[]> parts = new Dictionary<string, string[]>(StringComparer.OrdinalIgnoreCase);
            for (int i = 0; i < modelRows.Count; i++) models.Add(modelRows[i][1], modelRows[i]);
            for (int i = 0; i < bomRows.Count; i++) parts.Add(bomRows[i][0], bomRows[i]);

            // Avoid silently destroying the user's open and modified Project Spark scenes.
            if (!EditorSceneManager.SaveCurrentModifiedScenesIfUserWantsTo())
            {
                Debug.LogWarning("[L118] Build cancelled so open unsaved scenes are preserved.");
                return;
            }
            Scene scene = EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Single);
            GameObject root = new GameObject(RootName);
            root.AddComponent<SparkL118LayoutMarker>();
            GameObject art = Child(root.transform, "VisualArtRoot_Metres");
            GameObject actualBoard = Child(art.transform, "EmptyPCB_Physical_480x340mm");
            string[] boardRecord;
            if (!models.TryGetValue("L118_PCB_Main", out boardRecord))
            {
                Debug.LogError("[L118] Missing PCB_Main manifest record.");
                UnityEngine.Object.DestroyImmediate(root);
                return;
            }
            GameObject board = ImportModel(source, boardRecord[5], actualBoard.transform, "PCB_Main_RealScale");
            Bounds boardBounds;
            if (board == null || !TryBounds(board, out boardBounds) ||
                Mathf.Abs(boardBounds.size.x - PhysicalWidth) > .002f ||
                Mathf.Abs(boardBounds.size.z - PhysicalDepth) > .002f)
            {
                Debug.LogError("[L118] Board mesh import/scale mismatch. Expected 0.480 x 0.340 m. " +
                               "Do not generate primitive fallback geometry.");
                UnityEngine.Object.DestroyImmediate(root);
                return;
            }
            actualBoard.AddComponent<SparkL118VisualOnly>();
            BoxCollider boardClickArea = actualBoard.AddComponent<BoxCollider>();
            boardClickArea.size = new Vector3(PhysicalWidth, .0016f, PhysicalDepth);
            boardClickArea.center = Vector3.zero;
            GameObject layerArtwork = Child(art.transform, "28_InspectionLayerReferences_DISABLED");
            GameObject otherArtwork = Child(art.transform, "OtherUnverifiedFactoryArtwork_DISABLED");
            for (int i = 0; i < modelRows.Count; i++)
            {
                string[] item = modelRows[i];
                if (item[10] == "TRUE" || item[1] == "L118_PCB_Main") continue;
                Transform owner = item[2] == "layer" ? layerArtwork.transform : otherArtwork.transform;
                GameObject decoration = ImportModel(source, item[5], owner, "NONCONDUCTIVE_" + item[1]);
                if (decoration != null) decoration.AddComponent<SparkL118VisualOnly>();
            }
            layerArtwork.SetActive(false);
            otherArtwork.SetActive(false);

            GameObject authoring = Child(root.transform, "GameplayAuthoringRoot_NONCERTIFIABLE");
            GameObject targets = Child(authoring.transform, "236_UninstalledComponentTargets");
            GameObject routes = Child(authoring.transform, "320_Routes_UNASSIGNED_BLOCKED");
            GameObject vias = Child(authoring.transform, "116_Vias_UNASSIGNED_BLOCKED");
            GameObject inventory = Child(authoring.transform, "InventoryPrefabs_AsAssets_NotYetInstalled");
            inventory.AddComponent<SparkL118VisualOnly>();
            List<SparkL118ComponentEntry> componentData = new List<SparkL118ComponentEntry>(236);
            for (int i = 0; i < placementRows.Count; i++)
            {
                string[] record = placementRows[i];
                string[] bomItem;
                string[] model;
                if (!parts.TryGetValue(record[0], out bomItem) || !models.TryGetValue(record[1], out model))
                {
                    Debug.LogError("[L118] Missing component/BOM/asset join: " + record[0]);
                    UnityEngine.Object.DestroyImmediate(root);
                    return;
                }
                float x = F(record[3]);
                float y = F(record[4]);
                float z = F(record[5]);
                GameObject slot = Child(targets.transform, "SLOT_" + record[0]);
                slot.transform.localPosition = new Vector3(x, y, z);
                slot.AddComponent<SparkL118PlacementSlot>().Configure(record[0], record[1], bomItem[1]);
                BoxCollider trigger = slot.AddComponent<BoxCollider>();
                trigger.isTrigger = true;
                bool substantial = bomItem[1] == "ic" || bomItem[1] == "connector" || bomItem[1] == "shield";
                trigger.size = substantial ? new Vector3(.012f, .004f, .010f) : new Vector3(.005f, .002f, .004f);
                trigger.center = new Vector3(0f, .0007f, 0f);
                componentData.Add(new SparkL118ComponentEntry
                {
                    referenceId = record[0], assetId = record[1], kind = bomItem[1],
                    physicalLocationMetres = new Vector3(x, y, z),
                    footprintVerified = false, installedAtStart = false
                });
                string prefabAsset = Output + "/ComponentVisualPrefabs/L118_" + record[0] + ".prefab";
                GameObject visual = ImportModel(source, model[5], inventory.transform, "L118_" + record[0] + "_SourceVisual");
                if (visual == null)
                {
                    Debug.LogError("[L118] Missing importable component mesh " + model[5]);
                    UnityEngine.Object.DestroyImmediate(root);
                    return;
                }
                // Object models are local to their origin: placement is through the slot only.
                visual.transform.localPosition = Vector3.zero;
                visual.transform.localRotation = Quaternion.identity;
                visual.AddComponent<SparkL118VisualOnly>();
                PrefabUtility.SaveAsPrefabAsset(visual, prefabAsset);
                UnityEngine.Object.DestroyImmediate(visual);
            }
            List<SparkL118RouteEntry> routeData = new List<SparkL118RouteEntry>(320);
            for (int i = 0; i < routeRows.Count; i++)
            {
                string[] r = routeRows[i];
                Child(routes.transform, r[0] + "_" + SafeName(r[1]))
                    .AddComponent<SparkL118BlockedTask>()
                    .Configure(SparkL118TaskType.CopperRoute, r[0], r[1]);
                routeData.Add(new SparkL118RouteEntry
                {
                    id = r[0], domain = r[1], sourcePad = r[2], destinationPad = r[3],
                    netId = r[4], layer = r[5], certifiable = false
                });
            }
            List<SparkL118ViaEntry> viaData = new List<SparkL118ViaEntry>(116);
            for (int i = 0; i < viaRows.Count; i++)
            {
                string[] v = viaRows[i];
                Child(vias.transform, v[0] + "_BLOCKED")
                    .AddComponent<SparkL118BlockedTask>()
                    .Configure(SparkL118TaskType.Via, v[0], "Layer span TBD");
                viaData.Add(new SparkL118ViaEntry
                {
                    id = v[0], netId = v[1], fromLayer = v[2], toLayer = v[3], verified = false
                });
            }
            SparkL118SourceBlueprint blueprint = AssetDatabase.LoadAssetAtPath<SparkL118SourceBlueprint>(Output + "/L118_SourceBlueprint.asset");
            if (blueprint == null)
            {
                blueprint = ScriptableObject.CreateInstance<SparkL118SourceBlueprint>();
                AssetDatabase.CreateAsset(blueprint, Output + "/L118_SourceBlueprint.asset");
            }
            blueprint.SetSourceData(componentData, routeData, viaData);
            EditorUtility.SetDirty(blueprint);

            GameObject adapters = Child(root.transform, "ProjectSparkSystemBindings_REQUIRED_UNBOUND");
            string[] requiredServices = {
                "SparkCircuitSystem authoritative circuit and return topology",
                "SparkTerminal approved pin-level TSX-26 and SFP+ contacts",
                "LevelGamePlayManager six objective verification events",
                "Existing world-space virtual PCB test and repair UI",
                "Shop and component inventory placement lifecycle",
                "Six-port mixed-rate TSN PHY and link qualification",
                "gPTP primary and holdover timing with clock-quality gates",
                "TSN time-aware gate schedules, deterministic priority queues and bounded delay",
                "F1 gPTP oscillator drift / F2 redundant link via / F3 scheduler SRAM authority",
                "W321 independent deterministic-ready safety supervisor",
                "Save/load evidence freshness and topology revision"
            };
            for (int i = 0; i < requiredServices.Length; i++)
                Child(adapters.transform, SafeName(requiredServices[i]))
                    .AddComponent<SparkL118IntegrationAnchor>().Configure(requiredServices[i]);
            GameObject demo = Child(root.transform, "OPTIONAL_TSN_GateSchedule_Teaching_DEMO_NONCERTIFIABLE");
            demo.AddComponent<SparkL118TSNTeachingDemo>();

            GameObject disabledReference = Child(root.transform, "Assembled_ART_REFERENCE_DISABLED_NEVER_GAMEPLAY");
            GameObject reference = ImportModel(source, "289_L118_AssembledReference.obj", disabledReference.transform, "Showcase_FullAssembly_ONLY");
            if (reference != null) reference.AddComponent<SparkL118VisualOnly>();
            disabledReference.AddComponent<SparkL118VisualOnly>();
            disabledReference.SetActive(false);

            PrefabUtility.SaveAsPrefabAsset(root, Output + "/Level_118_Layout.prefab");
            EditorSceneManager.SaveScene(scene, Output + "/Level_118_Layout.unity");
            AssetDatabase.SaveAssets();
            WriteValidationReport(source, modelRows.Count, componentData.Count, routeData.Count, viaData.Count);
            AssetDatabase.Refresh();
            Selection.activeGameObject = root;
            Debug.Log("[L118] Visual layout generated. COMPONENTS 0/236, ROUTES 0/320, VIAS 0/116, " +
                      "W321 OPEN, OBJECTIVES 0/6; NO VERIFIED SCHEMATIC; NOT CERTIFIABLE.");
        }

        [MenuItem(Menu + "2. Place assembled VISUAL preview on SELECTED tabletop")]
        public static void PlacePreview()
        {
            GameObject selected = Selection.activeGameObject;
            if (selected == null)
            {
                Debug.LogError("[L118] Select existing Table_top (or tabletop Renderer) in Hierarchy first.");
                return;
            }
            if (selected.GetComponentInParent<SparkL118LayoutMarker>() != null)
            {
                Debug.LogError("[L118] Select the existing workshop tabletop, not a Level 118 object.");
                return;
            }
            string source = FindSourceRoot();
            if (string.IsNullOrEmpty(source)) return;
            if (GameObject.Find("L118_TSX26_VisualPreview_ONLY") != null)
            {
                Debug.LogWarning("[L118] Visual-only tabletop preview already exists. Not duplicating it.");
                return;
            }
            Renderer tableRenderer = selected.GetComponent<Renderer>();
            if (tableRenderer == null) tableRenderer = selected.GetComponentInChildren<Renderer>();
            if (tableRenderer == null)
            {
                Debug.LogError("[L118] Table_top has no measurable Renderer; cannot place or size the preview.");
                return;
            }
            GameObject imported = AssetDatabase.LoadAssetAtPath<GameObject>(source + "/Models_OBJ/289_L118_AssembledReference.obj");
            if (imported == null)
            {
                Debug.LogError("[L118] Assembled showcase OBJ unavailable.");
                return;
            }
            GameObject preview = new GameObject("L118_TSX26_VisualPreview_ONLY");
            Undo.RegisterCreatedObjectUndo(preview, "Create Level118 Visual Preview");
            preview.AddComponent<SparkL118VisualOnly>();
            GameObject visual = (GameObject)PrefabUtility.InstantiatePrefab(imported);
            visual.transform.SetParent(preview.transform, false);
            visual.name = "VisualShowcase_NotElectrical";
            SparkL118URPPBRMaterialBuilder.Bind(visual);
            float scale = Mathf.Min(PreviewWidth / PhysicalWidth, PreviewMaxDepth / PhysicalDepth);
            preview.transform.position = tableRenderer.bounds.center + Vector3.up *
                                        (tableRenderer.bounds.extents.y + .015f);
            preview.transform.rotation = selected.transform.rotation;
            preview.transform.localScale = Vector3.one * scale;
            Collider[] colliders = preview.GetComponentsInChildren<Collider>(true);
            for (int i = 0; i < colliders.Length; i++) UnityEngine.Object.DestroyImmediate(colliders[i]);
            Selection.activeGameObject = preview;
            Debug.Log("[L118] Placed visual-only assembled board preview. Physical model remains 0.480 x 0.340 m; " +
                      "presentation scale=" + scale.ToString("F3", Invariant) + ". No gameplay state modified.");
        }

        [MenuItem(Menu + "3. Validate Sources and Report Blockers")]
        public static void ValidateMenu()
        {
            string root = FindSourceRoot();
            if (root != null) ValidateSource(root, true);
        }

        public static string FindSourceRoot()
        {
            const string suffix = "/Data/ModelManifest.csv";
            string[] assets = AssetDatabase.GetAllAssetPaths();
            string matched = null;
            for (int i = 0; i < assets.Length; i++)
            {
                if (!assets[i].EndsWith(suffix, StringComparison.OrdinalIgnoreCase)) continue;
                if (assets[i].IndexOf("Level118", StringComparison.OrdinalIgnoreCase) < 0 &&
                    assets[i].IndexOf("TSX26", StringComparison.OrdinalIgnoreCase) < 0) continue;
                string sourceRoot = assets[i].Substring(0, assets[i].Length - "/Data/ModelManifest.csv".Length);
                if (matched != null && !matched.Equals(sourceRoot, StringComparison.OrdinalIgnoreCase))
                {
                    Debug.LogError("[L118] Duplicated Level118_TSX26 source root: " + matched + " and " + sourceRoot);
                    return null;
                }
                matched = sourceRoot;
            }
            if (matched == null) Debug.LogError("[L118] Level118_TSX26 source not installed under Unity Assets.");
            return matched;
        }

        public static bool ValidateSource(string root, bool writeLog)
        {
            try
            {
                List<string[]> models = ReadCsv(root + "/Data/ModelManifest.csv");
                List<string[]> parts = ReadCsv(root + "/Data/ComponentBOM.csv");
                List<string[]> placements = ReadCsv(root + "/Data/ComponentPlacements.csv");
                List<string[]> routes = ReadCsv(root + "/Data/CopperRoutes_320_REQUIRES_SCHEMATIC.csv");
                List<string[]> viaRows = ReadCsv(root + "/Data/ViaTasks_116_REQUIRES_SCHEMATIC.csv");
                if (models.Count != 288 || parts.Count != 236 || placements.Count != 236 ||
                    routes.Count != 320 || viaRows.Count != 116)
                {
                    Debug.LogError("[L118] Wrong row counts: models=" + models.Count +
                        " BOM=" + parts.Count + " placements=" + placements.Count +
                        " routes=" + routes.Count + " vias=" + viaRows.Count);
                    return false;
                }
                HashSet<string> ids = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
                for (int i = 0; i < models.Count; i++)
                {
                    string[] m = models[i];
                    if (m.Length < 12 || !m[5].EndsWith(".obj", StringComparison.OrdinalIgnoreCase) ||
                        !m[6].EndsWith(".glb", StringComparison.OrdinalIgnoreCase) ||
                        m[5].Equals("NOT_INCLUDED", StringComparison.OrdinalIgnoreCase) ||
                        !ids.Add(m[1]) ||
                        !File.Exists(Absolute(root + "/Models_OBJ/" + m[5])) ||
                        !File.Exists(Absolute(root + "/Models_GLB/" + m[6])))
                    {
                        Debug.LogError("[L118] Missing / repeated / invalid model row: " + m[1]);
                        return false;
                    }
                }
                HashSet<string> componentIds = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
                for (int i = 0; i < placements.Count; i++)
                {
                    string[] record = placements[i];
                    if (record.Length < 8 || !componentIds.Add(record[0]) ||
                        !ids.Contains(record[1]) || record[2] != "TSX-26" || record[6] != "FALSE" || record[7] != "FALSE")
                    {
                        Debug.LogError("[L118] Invalid component placement row: " + record[0]);
                        return false;
                    }
                }
                for (int i = 0; i < routes.Count; i++)
                {
                    string[] r = routes[i];
                    if (r.Length < 8 || r[2] != "UNASSIGNED" || r[3] != "UNASSIGNED" ||
                        r[4] != "UNASSIGNED" || r[7] != "FALSE")
                    {
                        Debug.LogError("[L118] Route data unexpectedly changed; require schematic review: " + r[0]);
                        return false;
                    }
                }
                for (int i = 0; i < viaRows.Count; i++)
                {
                    string[] v = viaRows[i];
                    if (v.Length < 7 || v[1] != "UNASSIGNED" || v[2] != "TBD" ||
                        v[3] != "TBD" || v[6] != "FALSE")
                    {
                        Debug.LogError("[L118] Via data unexpectedly changed; require schematic review: " + v[0]);
                        return false;
                    }
                }
                if (!File.Exists(Absolute(root + "/Models_OBJ/289_L118_AssembledReference.obj")))
                {
                    Debug.LogError("[L118] Assembled reference missing.");
                    return false;
                }
                Debug.Log("[L118] Source validation PASS (file/manifest consistency ONLY): " +
                    "288 model pairs; 236 BOM; 320 routes/116 vias UNASSIGNED; W321 pins UNVERIFIED. " +
                    "Unity Play Mode and electrical qualification NOT_RUN.");
                if (writeLog)
                {
                    EnsureDirectory(Output);
                    WriteValidationReport(root, models.Count, parts.Count, routes.Count, viaRows.Count);
                    AssetDatabase.Refresh();
                }
                return true;
            }
            catch (Exception error)
            {
                Debug.LogError("[L118] Source validation failed: " + error);
                return false;
            }
        }

        private static List<string[]> ReadCsv(string path)
        {
            string file = Absolute(path);
            if (!File.Exists(file)) throw new FileNotFoundException(path);
            string[] lines = File.ReadAllLines(file);
            List<string[]> rows = new List<string[]>(lines.Length);
            for (int i = 1; i < lines.Length; i++)
            {
                if (string.IsNullOrWhiteSpace(lines[i])) continue;
                // Properly parse quoted commas in component descriptions.
                rows.Add(ParseCsvLine(lines[i]));
            }
            return rows;
        }

        private static string[] ParseCsvLine(string line)
        {
            List<string> values = new List<string>();
            StringBuilder value = new StringBuilder();
            bool quoted = false;
            for (int i = 0; i < line.Length; i++)
            {
                char c = line[i];
                if (c == '"')
                {
                    if (quoted && i + 1 < line.Length && line[i + 1] == '"')
                    {
                        value.Append('"');
                        i++;
                    }
                    else quoted = !quoted;
                }
                else if (c == ',' && !quoted)
                {
                    values.Add(value.ToString());
                    value.Length = 0;
                }
                else value.Append(c);
            }
            if (quoted) throw new FormatException("Unterminated quoted CSV cell");
            values.Add(value.ToString());
            return values.ToArray();
        }

        private static float F(string value)
        {
            return float.Parse(value, NumberStyles.Float, Invariant);
        }

        private static GameObject Child(Transform parent, string childName)
        {
            GameObject obj = new GameObject(childName);
            obj.transform.SetParent(parent, false);
            return obj;
        }

        private static GameObject ImportModel(string root, string objName, Transform parent, string instanceName)
        {
            GameObject imported = AssetDatabase.LoadAssetAtPath<GameObject>(root + "/Models_OBJ/" + objName);
            if (imported == null)
            {
                Debug.LogError("[L118] OBJ not imported: " + objName);
                return null;
            }
            GameObject instance = (GameObject)PrefabUtility.InstantiatePrefab(imported);
            instance.transform.SetParent(parent, false);
            instance.transform.localPosition = Vector3.zero;
            instance.transform.localRotation = Quaternion.identity;
            instance.name = instanceName;
            SparkL118URPPBRMaterialBuilder.Bind(instance);
            return instance;
        }

        private static bool TryBounds(GameObject go, out Bounds result)
        {
            result = new Bounds(Vector3.zero, Vector3.zero);
            if (go == null) return false;
            Renderer[] renderers = go.GetComponentsInChildren<Renderer>(true);
            if (renderers.Length == 0) return false;
            bool found = false;
            for (int i = 0; i < renderers.Length; i++)
            {
                if (renderers[i] == null) continue;
                if (!found) { result = renderers[i].bounds; found = true; }
                else result.Encapsulate(renderers[i].bounds);
            }
            return found;
        }

        private static string SafeName(string raw)
        {
            char[] chars = raw.ToCharArray();
            for (int i = 0; i < chars.Length; i++)
                if (!char.IsLetterOrDigit(chars[i]) && chars[i] != '_') chars[i] = '_';
            return new string(chars);
        }

        private static string Absolute(string assetPath)
        {
            return Path.Combine(Directory.GetParent(Application.dataPath).FullName,
                assetPath.Replace('/', Path.DirectorySeparatorChar));
        }

        private static void EnsureDirectory(string path)
        {
            Directory.CreateDirectory(Absolute(path));
        }

        private static void WriteValidationReport(string root, int modelCount, int components,
            int routeCount, int viaCount)
        {
            string[] lines = {
                "PROJECT SPARK LEVEL 118 - SOURCE/IMPORT AUDIT (NOT UNITY PLAY MODE CERTIFICATION)",
                "Board: TSX-26 / The Deterministic Grid / 0.480 x 0.340 metres / 28 layers",
                "Source: " + root,
                "Modular model records: " + modelCount + " (expected 288)",
                "Component slots: " + components + " (236 UNINSTALLED)",
                "Copper: " + routeCount + " (UNASSIGNED / NOT CERTIFIABLE)",
                "Vias: " + viaCount + " (TBD layer span / NOT CERTIFIABLE)",
                "W321: OPEN; U31 monitor / U32 supervisor logical roles only; package pins UNASSIGNED",
                "Objectives: 0/6. Existing Project Spark runtime APIs have not been inspected.",
                "Source validation does not prove Unity compile, rendering, TSN scheduling and packet timing integrity, or gameplay.",
                "Requires approved schematic/TSN PHY/clock/scheduler specifications/28-layer stack-up and fresh independent tests.",
                "Every Unity EditMode and PlayMode test: NOT_RUN"
            };
            File.WriteAllLines(Absolute(Output + "/L118_Layout_Validation.txt"), lines);
        }
