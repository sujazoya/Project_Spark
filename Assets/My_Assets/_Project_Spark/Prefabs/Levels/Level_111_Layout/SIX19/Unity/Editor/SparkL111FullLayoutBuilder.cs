    {
        private const string Menu = "Tools/Project Spark/Automatic Level Generator/111/";
        private const string Output = "Assets/ProjectSpark/AutoGeneratedLevels/Level111";
        private const string RootName = "L111_SIX19_SIGNAL_CRUCIBLE";
        private const float PhysicalWidth = 0.330f;
        private const float PhysicalDepth = 0.240f;
        private const float PreviewWidth = 10.13f;
        private const float PreviewMaxDepth = 7.4f;
        private static readonly CultureInfo Format = CultureInfo.InvariantCulture;

        [MenuItem(Menu + "1. Build FULL Level_111_Layout")]
        public static void BuildFull()
        {
            string source = FindSourceRoot();
            if (string.IsNullOrEmpty(source)) return;
            if (!ValidateSource(source, true)) return;
            if (!SparkL111URPMaterialBuilder.Build(source)) return;
            EnsureDirectory(Output);
            EnsureDirectory(Output + "/ComponentVisualPrefabs");
            AssetDatabase.Refresh();

            List<string[]> rows = ReadCsv(source + "/Data/L111_ModelManifest.csv");
            int objColumn = GetManifestColumn(source, "obj");
            if (objColumn < 0) return;
            List<string[]> bom = ReadCsv(source + "/Data/L111_ComponentBOM.csv");
            List<string[]> placement = ReadCsv(source + "/Data/L111_ComponentPlacements.csv");
            List<string[]> routes = ReadCsv(source + "/Data/L111_CopperRoutes_184_SCHEMATIC_REQUIRED.csv");
            List<string[]> vias = ReadCsv(source + "/Data/L111_ViaTasks_60_SCHEMATIC_REQUIRED.csv");

            Dictionary<string, string[]> models = new Dictionary<string, string[]>(StringComparer.OrdinalIgnoreCase);
            for (int i = 0; i < rows.Count; ++i) models[rows[i][1]] = rows[i];
            Dictionary<string, string[]> components = new Dictionary<string, string[]>(StringComparer.OrdinalIgnoreCase);
            for (int i = 0; i < bom.Count; ++i) components[bom[i][0]] = bom[i];

            // Guard existing unsaved Project Spark editor scene changes before opening an isolated scene.
            if (!EditorSceneManager.SaveCurrentModifiedScenesIfUserWantsTo())
            {
                Debug.LogWarning("[L111] Build cancelled to preserve unsaved scene changes.");
                return;
            }
            // New isolated scene; no existing Project Spark scene or previously generated level is changed.
            Scene scene = EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Single);
            GameObject root = new GameObject(RootName);
            root.AddComponent<SparkL111LayoutMarker>();
            GameObject art = Child(root.transform, "ArtRoot");
            GameObject playableBoard = Child(art.transform, "EmptyPCBPhysicalMetres");
            string boardAssetId = "PCB_Main";
            string[] boardManifest;
            if (!models.TryGetValue(boardAssetId, out boardManifest))
            {
                Debug.LogError("[L111] PCB_Main missing from model manifest.");
                UnityEngine.Object.DestroyImmediate(root);
                return;
            }
            GameObject board = InstantiateModel(source, boardManifest[objColumn], playableBoard.transform, "PCB_Main_Physical_330x240mm");
            if (!board)
            {
                UnityEngine.Object.DestroyImmediate(root);
                return;
            }
            Bounds bounds;
            if (!TryBounds(board, out bounds) ||
                Mathf.Abs(bounds.size.x - PhysicalWidth) > 0.0025f ||
                Mathf.Abs(bounds.size.z - PhysicalDepth) > 0.0025f)
            {
                Debug.LogError("[L111] PCB import geometry mismatch. Measured " + bounds.size +
                    ", expected X=0.330, Z=0.240 metres. Check OBJ import scale; build aborted.");
                UnityEngine.Object.DestroyImmediate(root);
                return;
            }
            GameObject layers = Child(art.transform, "14LayerInspectionArtwork_DISABLED");
            GameObject structural = Child(art.transform, "OtherFactoryOnlyArtwork_DISABLED");
            for (int i = 0; i < rows.Count; ++i)
            {
                if (rows[i][11].Equals("True", StringComparison.OrdinalIgnoreCase)) continue;
                if (rows[i][1] == "PCB_Main") continue;
                Transform parent = rows[i][3] == "layer" ? layers.transform : structural.transform;
                GameObject obj = InstantiateModel(source, rows[i][objColumn], parent, "VISUAL_ONLY_" + rows[i][1]);
                if (obj) obj.AddComponent<SparkL111VisualOnly>();
            }
            layers.SetActive(false);
            structural.SetActive(false);

            GameObject gameplay = Child(root.transform, "GameplayAuthoringRoot");
            GameObject slots = Child(gameplay.transform, "138_UninstalledComponentTargets");
            GameObject routesRoot = Child(gameplay.transform, "184_RouteRecords_SCHEMATIC_REQUIRED");
            GameObject viasRoot = Child(gameplay.transform, "60_ViaRecords_SCHEMATIC_REQUIRED");
            GameObject inventory = Child(gameplay.transform, "InventoryPrefabDefinitions_REFERENCE_ONLY");
            inventory.AddComponent<SparkL111VisualOnly>();
            // Inventory prefabs are stored as assets; installing them is reserved to existing shop/placement authority.
            for (int i = 0; i < placement.Count; ++i)
            {
                string reference = placement[i][0];
                string[] bomItem;
                string[] asset;
                if (!components.TryGetValue(reference, out bomItem) ||
                    !models.TryGetValue("L111_" + reference, out asset))
                {
                    Debug.LogError("[L111] Missing join for component " + reference);
                    UnityEngine.Object.DestroyImmediate(root);
                    return;
                }
                float x = F(placement[i][2]);
                float y = F(placement[i][3]);
                float z = F(placement[i][4]);
                GameObject slot = Child(slots.transform, "SLOT_" + reference);
                slot.transform.localPosition = new Vector3(x, y, z);
                SparkL111PlacementSlot record = slot.AddComponent<SparkL111PlacementSlot>();
                record.Configure(reference, bomItem[1], asset[1]);
                BoxCollider hit = slot.AddComponent<BoxCollider>();
                hit.isTrigger = true;
                bool large = reference.StartsWith("U", StringComparison.OrdinalIgnoreCase) ||
                             reference.StartsWith("J", StringComparison.OrdinalIgnoreCase);
                hit.size = large ? new Vector3(0.013f, 0.003f, 0.012f) :
                                   new Vector3(0.0075f, 0.002f, 0.006f);
                hit.center = new Vector3(0f, 0.0008f, 0f);

                string prefabPath = Output + "/ComponentVisualPrefabs/L111_" + reference + ".prefab";
                GameObject temporary = InstantiateModel(source, asset[objColumn], inventory.transform, "L111_" + reference + "_VisualOnly");
                if (!temporary) { UnityEngine.Object.DestroyImmediate(root); return; }
                temporary.AddComponent<SparkL111VisualOnly>();
                PrefabUtility.SaveAsPrefabAsset(temporary, prefabPath);
                UnityEngine.Object.DestroyImmediate(temporary);
            }
            for (int i = 0; i < routes.Count; ++i)
            {
                GameObject obj = Child(routesRoot.transform, routes[i][0] + "_" + SafeName(routes[i][1]));
                obj.AddComponent<SparkL111BlockedTask>().Configure(SparkL111TaskType.CopperRoute, routes[i][0], routes[i][1]);
            }
            for (int i = 0; i < vias.Count; ++i)
            {
                GameObject obj = Child(viasRoot.transform, vias[i][0] + "_BLOCKED");
                obj.AddComponent<SparkL111BlockedTask>().Configure(SparkL111TaskType.Via, vias[i][0], "14 layer unknown span");
            }
            GameObject integration = Child(root.transform, "ProjectSparkIntegrationContracts_UNBOUND");
            string[] services = {
                "SparkCircuitSystem / SparkElectricalNetworkGraph", "SparkTerminal / approved footprint pins",
                "LevelGamePlayManager / objective authority", "WorldSpacePCBVirtualStudio / tool raycast routing",
                "Existing shop and component placement", "W185 independent safety supervisor",
                "SerDes telemetry / calibrated measurement", "Save and load with evidence epochs"
            };
            foreach (string service in services)
                Child(integration.transform, SafeName(service)).AddComponent<SparkL111IntegrationAnchor>().Configure(service);
            GameObject demo = Child(root.transform, "OPTIONAL_EducationalSignalDemo_NONCERTIFIABLE");
            demo.AddComponent<SparkL111SignalIntegritySandbox>();
            GameObject refRoot = Child(root.transform, "AssembledShowcaseReference_DISABLED_NEVER_GAMEPLAY");
            string showcasePath = source + "/Models_OBJ/177_L111_AssembledReference.obj";
            GameObject assembled = InstantiateAssetAtPath(showcasePath, refRoot.transform, "VisualShowcase_ONLY");
            if (assembled) assembled.AddComponent<SparkL111VisualOnly>();
            refRoot.AddComponent<SparkL111VisualOnly>();
            refRoot.SetActive(false);

            string prefabOutput = Output + "/Level_111_Layout.prefab";
            PrefabUtility.SaveAsPrefabAsset(root, prefabOutput);
            EditorSceneManager.SaveScene(scene, Output + "/Level_111_Layout.unity");
            AssetDatabase.SaveAssets();
            WriteAudit(Output + "/L111_Layout_Validation.txt", rows.Count, placement.Count, routes.Count, vias.Count);
            Selection.activeGameObject = root;
            Debug.Log("[L111] Visual layout authored. 138/138 UNINSTALLED, 184/184 ROUTES BLOCKED, " +
                "60/60 VIAS BLOCKED, W185 DISCONNECTED, 0/6 objectives. NOT ELECTRICALLY CERTIFIABLE.");
        }

        [MenuItem(Menu + "2. Place assembled VISUAL preview on SELECTED tabletop")]
        public static void PlacePreviewOnTable()
        {
            GameObject table = Selection.activeGameObject;
            if (!table)
            {
                Debug.LogError("[L111] Select existing tabletop or Table_top transform first.");
                return;
            }
            if (table.GetComponentInParent<SparkL111LayoutMarker>() != null)
            {
                Debug.LogError("[L111] Please select a tabletop, not a Level 111 sub-object.");
                return;
            }
            string source = FindSourceRoot();
            if (string.IsNullOrEmpty(source)) return;
            string previewAssetPath = source + "/Models_OBJ/177_L111_AssembledReference.obj";
            GameObject imported = AssetDatabase.LoadAssetAtPath<GameObject>(previewAssetPath);
            if (!imported) { Debug.LogError("[L111] Assembled OBJ not imported. " + previewAssetPath); return; }
            GameObject root = new GameObject("L111_SIX19_VisualPreview_ONLY");
            Undo.RegisterCreatedObjectUndo(root, "Place Level 111 visual preview");
            root.AddComponent<SparkL111VisualOnly>();
            Bounds tableBounds;
            bool boundedTable = TryBounds(table, out tableBounds);
            Vector3 topPoint = boundedTable ? new Vector3(tableBounds.center.x, tableBounds.max.y, tableBounds.center.z) : table.transform.position;
            root.transform.position = topPoint + Vector3.up * 0.010f;
            root.transform.rotation = table.transform.rotation;
            GameObject visual = (GameObject)PrefabUtility.InstantiatePrefab(imported);
            if (!visual) { UnityEngine.Object.DestroyImmediate(root); return; }
            visual.transform.SetParent(root.transform, false);
            visual.transform.localPosition = Vector3.zero;
            float scale = Mathf.Min(PreviewWidth / PhysicalWidth, PreviewMaxDepth / PhysicalDepth);
            visual.transform.localScale = Vector3.one * scale;
            SparkL111URPMaterialBuilder.Bind(visual);
            visual.AddComponent<SparkL111VisualOnly>();
            DisableColliders(visual);
            Selection.activeGameObject = root;
            Debug.Log("[L111] Preview size " + (scale * PhysicalWidth).ToString("0.###", Format) +
                " x " + (scale * PhysicalDepth).ToString("0.###", Format) +
                " table units. VISUAL ONLY - physical PCB stays 0.330 x 0.240m.");
        }

        [MenuItem(Menu + "3. Validate Sources and Report Blockers")]
        public static void ValidateMenu()
        {
            string root = FindSourceRoot();
            if (!string.IsNullOrEmpty(root)) ValidateSource(root, true);
        }

        public static string FindSourceRoot()
        {
            string found = null;
            foreach (string guid in AssetDatabase.FindAssets("L111_ModelManifest"))
            {
                string p = AssetDatabase.GUIDToAssetPath(guid).Replace('\\', '/');
                if (!p.EndsWith("/Data/L111_ModelManifest.csv", StringComparison.OrdinalIgnoreCase)) continue;
                string root = Path.GetDirectoryName(Path.GetDirectoryName(p)).Replace('\\', '/');
                if (found != null && !string.Equals(root, found, StringComparison.OrdinalIgnoreCase))
                {
                    Debug.LogError("[L111] Multiple Level111 source kits found. Remove duplicate copies to protect source GUIDs.");
                    return null;
                }
                found = root;
            }
            if (found == null) Debug.LogError("[L111] Data/L111_ModelManifest.csv missing from imported Level111 source kit.");
            return found;
        }

        private static bool ValidateSource(string source, bool log)
        {
            string[] files = { "L111_ModelManifest.csv", "L111_ComponentBOM.csv", "L111_ComponentPlacements.csv",
                "L111_CopperRoutes_184_SCHEMATIC_REQUIRED.csv", "L111_ViaTasks_60_SCHEMATIC_REQUIRED.csv" };
            int[] expected = { 176, 138, 138, 184, 60 };
            for (int i = 0; i < files.Length; ++i)
            {
                string file = source + "/Data/" + files[i];
                if (!File.Exists(ToAbsolute(file))) { Debug.LogError("[L111] Missing " + file); return false; }
                List<string[]> rows = ReadCsv(file);
                if (rows.Count != expected[i])
                {
                    Debug.LogError("[L111] " + files[i] + ": expected " + expected[i] + " records, found " + rows.Count);
                    return false;
                }
            }
            List<string[]> models = ReadCsv(source + "/Data/L111_ModelManifest.csv");
            int objColumn = GetManifestColumn(source, "obj");
            if (objColumn < 0) return false;
            for (int i = 0; i < models.Count; ++i)
            {
                if (models[i].Length <= objColumn)
                {
                    Debug.LogError("[L111] Invalid manifest row " + (i + 2) + ": missing obj column.");
                    return false;
                }
                string filename = models[i][objColumn].Trim();
                if (string.IsNullOrEmpty(filename) ||
                    string.Equals(filename, "NOT_INCLUDED", StringComparison.OrdinalIgnoreCase) ||
                    !filename.EndsWith(".obj", StringComparison.OrdinalIgnoreCase) ||
                    !string.Equals(Path.GetFileName(filename), filename, StringComparison.Ordinal))
                {
                    Debug.LogError("[L111] Invalid OBJ filename at manifest row " + (i + 2) +
                        ": '" + filename + "'. The builder must read the 'obj' header, not the 'fbx' header.");
                    return false;
                }
                string obj = source + "/Models_OBJ/" + filename;
                if (!File.Exists(ToAbsolute(obj)))
                {
                    Debug.LogError("[L111] Missing OBJ " + obj +
                        ". Reinstall the complete Level 111 SIX19 kit using the included installer.");
                    return false;
                }
            }
            if (!File.Exists(ToAbsolute(source + "/Models_OBJ/177_L111_AssembledReference.obj")))
            {
                Debug.LogError("[L111] Assembled art source missing."); return false;
            }
            if (log)
            {
                Debug.Log("[L111] OBJ manifest column 'obj' = " + objColumn +
                    "; verified all " + models.Count + " model OBJ paths and assembled reference OBJ.");
                Debug.LogWarning("[L111] ART SOURCE VALIDATED OFFLINE COUNTS. ELECTRICAL SCHEMATIC REQUIRED: 184 routes, " +
                    "60 vias, W185 pin endpoints. No certification, no solver integration, no Play Mode claim.");
            }
            return true;
        }

        // Use the CSV header, never a hard-coded column number: FBX=NOT_INCLUDED is not an OBJ.
        private static int GetManifestColumn(string source, string columnName)
        {
            string manifest = source + "/Data/L111_ModelManifest.csv";
            using (StreamReader reader = new StreamReader(ToAbsolute(manifest)))
            {
                string header = reader.ReadLine();
                if (string.IsNullOrEmpty(header))
                {
                    Debug.LogError("[L111] Missing or empty manifest header: " + manifest);
                    return -1;
                }
                string[] columns = header.TrimStart('\uFEFF').Split(',');
                for (int i = 0; i < columns.Length; ++i)
                {
                    if (string.Equals(columns[i].Trim(), columnName, StringComparison.OrdinalIgnoreCase))
                        return i;
                }
            }
            Debug.LogError("[L111] Manifest has no '" + columnName + "' column: " + manifest);
            return -1;
        }

        private static GameObject InstantiateModel(string source, string objName, Transform parent, string name)
        {
            return InstantiateAssetAtPath(source + "/Models_OBJ/" + objName, parent, name);
        }

        private static GameObject InstantiateAssetAtPath(string path, Transform parent, string childName)
        {
            GameObject asset = AssetDatabase.LoadAssetAtPath<GameObject>(path);
            if (!asset) { Debug.LogError("[L111] Failed to load OBJ model asset " + path); return null; }
            GameObject result = PrefabUtility.InstantiatePrefab(asset) as GameObject;
            if (!result) { Debug.LogError("[L111] Failed to instantiate model " + path); return null; }
            result.transform.SetParent(parent, false);
            result.name = childName;
            SparkL111URPMaterialBuilder.Bind(result);
            DisableColliders(result);
            return result;
        }

        private static GameObject Child(Transform parent, string name)
        {
            GameObject go = new GameObject(name);
            go.transform.SetParent(parent, false);
            return go;
        }

        private static void DisableColliders(GameObject root)
        {
            Collider[] all = root.GetComponentsInChildren<Collider>(true);
            for (int i = 0; i < all.Length; ++i) all[i].enabled = false;
        }

        private static bool TryBounds(GameObject root, out Bounds bounds)
        {
            Renderer[] renders = root.GetComponentsInChildren<Renderer>(true);
            bool seen = false;
            bounds = new Bounds(root.transform.position, Vector3.zero);
            for (int i = 0; i < renders.Length; ++i)
            {
                if (!seen) { bounds = renders[i].bounds; seen = true; }
                else bounds.Encapsulate(renders[i].bounds);
            }
            return seen && bounds.size.sqrMagnitude > 0.000000001f;
        }

        // These source CSVs are deliberately simple with no quoted delimiters.
        private static List<string[]> ReadCsv(string assetPath)
        {
            string[] lines = File.ReadAllLines(ToAbsolute(assetPath));
            List<string[]> result = new List<string[]>(lines.Length);
            for (int i = 1; i < lines.Length; ++i)
            {
                if (string.IsNullOrWhiteSpace(lines[i])) continue;
                result.Add(ParseCsvFields(lines[i]));
            }
            return result;
        }

        // Parse single-line CSV records including commas within quotes and doubled quotes.
        private static string[] ParseCsvFields(string line)
        {
            List<string> fields = new List<string>(16);
            System.Text.StringBuilder field = new System.Text.StringBuilder(line.Length);
            bool insideQuotes = false;
            for (int i = 0; i < line.Length; ++i)
            {
                char c = line[i];
                if (c == '"')
                {
                    if (insideQuotes && i + 1 < line.Length && line[i + 1] == '"')
                    {
                        field.Append('"');
                        ++i;
                    }
                    else
                    {
                        insideQuotes = !insideQuotes;
                    }
                }
                else if (c == ',' && !insideQuotes)
                {
                    fields.Add(field.ToString());
                    field.Length = 0;
                }
                else
                {
                    field.Append(c);
                }
            }
            if (insideQuotes)
                throw new FormatException("Unclosed quoted field.");
            fields.Add(field.ToString());
            return fields.ToArray();
        }

        private static float F(string n) { return float.Parse(n, NumberStyles.Float, Format); }
        private static string SafeName(string value) { return value.Replace('/', '_').Replace(' ', '_'); }
        private static void EnsureDirectory(string assetFolder)
        {
            Directory.CreateDirectory(ToAbsolute(assetFolder));
        }
        private static string ToAbsolute(string assetPath)
        {
            string projectRoot = Directory.GetParent(Application.dataPath).FullName;
            return Path.Combine(projectRoot, assetPath.Replace('/', Path.DirectorySeparatorChar));
        }
        private static void WriteAudit(string assetFile, int models, int components, int routes, int vias)
        {
            string body = "PROJECT SPARK / LEVEL 111 / SIX-19 / THE SIGNAL CRUCIBLE\n" +
                "ART SOURCE = " + models + " model entries\n" +
                "PLACEMENT TARGETS = " + components + " (ALL UNINSTALLED)\n" +
                "ROUTE TASKS = " + routes + " (ALL UNASSIGNED / NOT CERTIFIABLE)\n" +
                "VIA TASKS = " + vias + " (ALL UNASSIGNED / NOT CERTIFIABLE)\n" +
                "LAYER COUNT = 14 visual reference layers\n" +
                "W185 = DISCONNECTED; PHYSICAL SOURCE / DEST PINS UNVERIFIED\n" +
                "OBJECTIVES = 0/6; NO AUTHORITATIVE AWARDS\n" +
                "GAMEPLAY API / BOARD NETLIST / FABRICATED DATA = NOT ASSUMED\n" +
                "RENDER QUALITY / PLAY MODE / UNITY COMPILER = NOT TESTED\n";
            File.WriteAllText(ToAbsolute(assetFile), body);
            AssetDatabase.Refresh();
        }
