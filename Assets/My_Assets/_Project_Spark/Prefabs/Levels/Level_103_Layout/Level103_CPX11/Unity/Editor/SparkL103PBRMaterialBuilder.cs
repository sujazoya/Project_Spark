#if UNITY_EDITOR
using System;
using System.Collections.Generic;
using System.IO;
using UnityEditor;
using UnityEngine;

namespace ProjectSpark.Level103.Editor
{
    /// <summary>Creates idempotent URP Lit PBR materials from the preserved 23-family source.
    /// Original FBX/GLB material imports are never overwritten or reconfigured.</summary>
    public static class SparkL103PBRMaterialBuilder
    {
        private const string Output = "Assets/ProjectSpark/AutoGeneratedLevels/Level103/URP_PBR_Materials";
        private static readonly Dictionary<string, Material> Cached =
            new Dictionary<string, Material>(StringComparer.OrdinalIgnoreCase);

        [MenuItem("Tools/Project Spark/Automatic Level Generator/103/4. Rebuild URP PBR Materials")]
        public static void RebuildMaterials()
        {
            string root = SparkL103FullLayoutBuilder.FindSourceRoot();
            if (string.IsNullOrEmpty(root))
            {
                Debug.LogError("[L103] Cannot find one unique Level103_CPX11 source root.");
                return;
            }
            if (BuildForRoot(root)) Debug.Log("[L103] 23 native URP Lit families prepared. Run full-layout build to rebind visuals.");
        }

        public static bool BuildForRoot(string root)
        {
            Cached.Clear();
            Shader shader = Shader.Find("Universal Render Pipeline/Lit");
            if (shader == null)
            {
                Debug.LogError("[L103] URP Lit shader not found. Install/activate Unity URP before building Level 103.");
                return false;
            }
            string textures = root + "/Textures";
            string absolute = AssetPathToAbsolute(textures);
            if (!Directory.Exists(absolute)) { Debug.LogError("[L103] Missing source textures: " + textures); return false; }
            string[] albedos = Directory.GetFiles(absolute, "*_BaseColor.png", SearchOption.TopDirectoryOnly);
            if (albedos.Length != 23)
            {
                Debug.LogError("[L103] Expected exactly 23 PBR BaseColor maps, found " + albedos.Length);
                return false;
            }
            Directory.CreateDirectory(AssetPathToAbsolute(Output));
            AssetDatabase.Refresh();
            Array.Sort(albedos, StringComparer.Ordinal);
            foreach (string file in albedos)
            {
                string family = Path.GetFileName(file).Replace("_BaseColor.png", "");
                string colorPath = textures + "/" + family + "_BaseColor.png";
                string metalPath = root + "/URP_Packed/" + family + "_URP_MetallicSmoothness.png";
                string normalPath = textures + "/" + family + "_Normal.png";
                string aoPath = textures + "/" + family + "_AO.png";
                if (!File.Exists(AssetPathToAbsolute(metalPath)) ||
                    !File.Exists(AssetPathToAbsolute(normalPath)) ||
                    !File.Exists(AssetPathToAbsolute(aoPath)))
                {
                    Debug.LogError("[L103] Missing PBR maps for " + family);
                    return false;
                }
                ConfigureTexture(colorPath, false, true);
                ConfigureTexture(metalPath, false, false);
                ConfigureTexture(normalPath, true, false);
                ConfigureTexture(aoPath, false, false);
                Texture2D albedo = AssetDatabase.LoadAssetAtPath<Texture2D>(colorPath);
                Texture2D metal = AssetDatabase.LoadAssetAtPath<Texture2D>(metalPath);
                Texture2D normal = AssetDatabase.LoadAssetAtPath<Texture2D>(normalPath);
                Texture2D ao = AssetDatabase.LoadAssetAtPath<Texture2D>(aoPath);
                if (albedo == null || metal == null || normal == null || ao == null)
                {
                    Debug.LogError("[L103] Texture import not finished for " + family);
                    return false;
                }
                string matPath = Output + "/L103_" + family + ".mat";
                Material material = AssetDatabase.LoadAssetAtPath<Material>(matPath);
                if (material == null)
                {
                    material = new Material(shader) { name = "L103_" + family };
                    AssetDatabase.CreateAsset(material, matPath);
                }
                else if (material.shader != shader) material.shader = shader;
                material.SetTexture("_BaseMap", albedo);
                material.SetColor("_BaseColor", Color.white);
                material.SetTexture("_MetallicGlossMap", metal);
                material.SetFloat("_Metallic", 1.0f);
                material.SetFloat("_Smoothness", 1.0f);
                if (material.HasProperty("_SmoothnessTextureChannel")) material.SetFloat("_SmoothnessTextureChannel", 0f);
                material.EnableKeyword("_METALLICSPECGLOSSMAP");
                material.SetTexture("_BumpMap", normal);
                material.SetFloat("_BumpScale", 1.0f);
                material.EnableKeyword("_NORMALMAP");
                material.SetTexture("_OcclusionMap", ao);
                material.SetFloat("_OcclusionStrength", 1.0f);
                material.SetFloat("_Surface", 0f);
                material.enableInstancing = true;
                EditorUtility.SetDirty(material);
                Cached.Add(family, material);
            }
            AssetDatabase.SaveAssets();
            return Cached.Count == 23;
        }

        private static void ConfigureTexture(string path, bool normal, bool srgb)
        {
            TextureImporter importer = AssetImporter.GetAtPath(path) as TextureImporter;
            if (importer == null) return;
            TextureImporterType type = normal ? TextureImporterType.NormalMap : TextureImporterType.Default;
            if (importer.textureType == type && importer.sRGBTexture == srgb) return;
            importer.textureType = type;
            importer.sRGBTexture = srgb;
            importer.SaveAndReimport();
        }

        public static void BindAllMaterials(GameObject importedInstance)
        {
            if (importedInstance == null) return;
            EnsureCachedMaterials();
            Renderer[] renderers = importedInstance.GetComponentsInChildren<Renderer>(true);
            for (int k = 0; k < renderers.Length; k++)
            {
                Renderer renderer = renderers[k];
                Material[] list = renderer.sharedMaterials;
                bool changed = false;
                for (int i = 0; i < list.Length; i++)
                {
                    string family = GetMaterialIdentity(list[i], renderer.transform);
                    Material native;
                    if (family != null && Cached.TryGetValue(family, out native))
                    {
                        list[i] = native;
                        changed = true;
                    }
                }
                if (changed) renderer.sharedMaterials = list;
            }
        }

        private static void EnsureCachedMaterials()
        {
            if (Cached.Count != 0) return;
            string[] ids = AssetDatabase.FindAssets("t:Material", new[] { Output });
            foreach (string guid in ids)
            {
                string path = AssetDatabase.GUIDToAssetPath(guid);
                if (!path.EndsWith(".mat", StringComparison.OrdinalIgnoreCase)) continue;
                string name = Path.GetFileNameWithoutExtension(path);
                if (!name.StartsWith("L103_", StringComparison.OrdinalIgnoreCase)) continue;
                string family = name.Substring(5);
                Material mat = AssetDatabase.LoadAssetAtPath<Material>(path);
                if (mat != null && !Cached.ContainsKey(family)) Cached.Add(family, mat);
            }
        }

        private static string GetMaterialIdentity(Material assigned, Transform node)
        {
            string tag = "__PSMAT__";
            for (Transform current = node; current != null; current = current.parent)
            {
                string nodeName = current.name;
                int at = nodeName.IndexOf(tag, StringComparison.OrdinalIgnoreCase);
                if (at >= 0)
                {
                    string tagged = nodeName.Substring(at + tag.Length);
                    if (Cached.ContainsKey(tagged)) return tagged;
                    string matching = null;
                    foreach (string family in Cached.Keys)
                    {
                        if ((tagged.StartsWith(family + "_", StringComparison.OrdinalIgnoreCase) ||
                             tagged.StartsWith(family + " (", StringComparison.OrdinalIgnoreCase)) &&
                             (matching == null || family.Length > matching.Length))
                            matching = family;
                    }
                    if (matching != null) return matching;
                }
            }
            if (assigned == null) return null;
            string name = assigned.name;
            if (name.StartsWith("L103_", StringComparison.OrdinalIgnoreCase)) name = name.Substring(5);
            if (Cached.ContainsKey(name)) return name;
            // Some versions of the OBJ importer append a suffix after the MTL family name.
            string fallback = null;
            foreach (string key in Cached.Keys)
            {
                if ((name.StartsWith(key + " (", StringComparison.OrdinalIgnoreCase) ||
                     name.StartsWith(key + "_", StringComparison.OrdinalIgnoreCase)) &&
                     (fallback == null || key.Length > fallback.Length)) fallback = key;
            }
            return fallback;
        }

        private static string AssetPathToAbsolute(string asset)
        {
            string project = Directory.GetParent(Application.dataPath).FullName;
            return Path.Combine(project, asset.Replace('/', Path.DirectorySeparatorChar));
        }
    }
}
