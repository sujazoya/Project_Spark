        [MenuItem(Menu + "1. Build FULL Level_103_Layout")]
        public static void BuildFull()
        {
            string root = FindSourceRoot();
            if (string.IsNullOrEmpty(root))
            {
                Debug.LogError("[L103] Source missing/ambiguous: Level103_CPX11/Data/ModelManifest.csv. Use complete install; remove duplicate roots.");
                return;
            }
            List<Dictionary<string, string>> models = ReadCsv(root + "/Data/ModelManifest.csv");
            List<Dictionary<string, string>> bom = ReadCsv(root + "/Data/ComponentBOM.csv");
            List<Dictionary<string, string>> placement = ReadCsv(root + "/Data/ComponentPlacements.csv");
            List<Dictionary<string, string>> routes = ReadCsv(root + "/Data/CopperRoutes_116_REQUIRES_SCHEMATIC.csv");
            List<Dictionary<string, string>> vias = ReadCsv(root + "/Data/ViaTasks_30_REQUIRES_SCHEMATIC.csv");
            if (!ValidateData(root, models, bom, placement, routes, vias, true)) return;
            GameObject boardSource = ResolveModel(root, BoardModel);
            GameObject referenceSource = ResolveModel(root, ReferenceModel);
            if (boardSource == null || referenceSource == null)
            {
                Debug.LogError("[L103] Empty CPX-11 board or assembled source is not a renderable imported model.");
                return;
            }
            if (AssetDatabase.LoadAssetAtPath<GameObject>(LayoutPrefab) != null &&
                !EditorUtility.DisplayDialog("Level 103 rebuild", "Rebuild generated Level 103 scene/prefab/visual inventory? This will overwrite only Level 103 generated art assets. Back up user modifications first.", "Rebuild", "Cancel")) return;
            if (!SparkL103PBRMaterialBuilder.BuildForRoot(root)) return;
            Directory.CreateDirectory(ToAbsolute(Generated));
            Directory.CreateDirectory(ToAbsolute(Generated + "/ComponentVisualPrefabs"));
            AssetDatabase.Refresh();
            SparkL103SourceBlueprint blueprint = CreateOrUpdateBlueprint(models, bom, placement, routes, vias);
            Scene tempScene = EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Additive);
            bool succeeded = false;
            try
            {
                GameObject main = NewRootInScene("L103_ThePowerCore_CPX11", tempScene);
                GameObject visuals = NewChild("Visuals", main.transform);
                GameObject baseArt = NewChild("EmptyPCB_FactoryOnly", visuals.transform);
                GameObject baseInstance = SpawnArt(boardSource, "CPX11_EmptyPCB_SourceGeometry", baseArt.transform, tempScene);
                if (baseInstance == null) throw new InvalidOperationException("Unable to instantiate empty board.");
                Bounds bounds;
                if (!TryGetBounds(baseInstance, out bounds) ||
                    Mathf.Abs(bounds.size.x - BoardWidthM) > .004f || Mathf.Abs(bounds.size.z - BoardDepthM) > .004f)
                    throw new InvalidOperationException("Board Unity geometry scale mismatch. Expected 0.240 x 0.180 metres; actual " + bounds.size + ". Do not double-scale centimetre FBXs.");

                GameObject cpu = ResolveModel(root, "102_L103_CPU_Socket_And_Load.fbx");
                if (cpu == null) throw new InvalidOperationException("CPU socket/load board detail missing.");
                SpawnArt(cpu, "CPU_Socket_ArtOnly_NotIn88BOM", baseArt.transform, tempScene);
                NewChild("InstalledComponentVisuals_EMPTY", visuals.transform);
                NewChild("NewCopperTraces_EMPTY", visuals.transform);
                NewChild("InstalledVias_EMPTY", visuals.transform);
                GameObject layerArt = NewChild("LayerInspection_REFERENCE_DISABLED", visuals.transform);
                GameObject otherArt = NewChild("BoardRepairsAndDiagnosticArt_REFERENCE_DISABLED", visuals.transform);
                for (int i = 89; i < 112; i++)
                {
                    Dictionary<string, string> item = models[i];
                    string fbx = Get(item, "fbx");
                    if (fbx == "102_L103_CPU_Socket_And_Load.fbx") continue;
                    GameObject geometry = ResolveModel(root, fbx);
                    if (geometry == null) throw new InvalidOperationException("Required structural asset missing: " + fbx);
                    bool isLayer = i >= 89 && i <= 100;
                    GameObject child = SpawnArt(geometry, "ART_ONLY_" + Path.GetFileNameWithoutExtension(fbx),
                        (isLayer ? layerArt : otherArt).transform, tempScene);
                    if (child != null) child.SetActive(false);
                }
                layerArt.SetActive(false);
                otherArt.SetActive(false);

                GameObject showcase = NewChild("AssembledShowcase_REFERENCE_ONLY_DISABLED", visuals.transform);
                SpawnArt(referenceSource, "COMPLETE_REFERENCE_NEVER_PLAYABLE", showcase.transform, tempScene);
                showcase.SetActive(false);

                GameObject authoring = NewChild("SourcePlanning_NOT_GAMEPLAY_AUTHORITY", main.transform);
                GameObject footprints = NewChild("FootprintTargets_88_ALL_UNINSTALLED", authoring.transform);
                GameObject routesGroup = NewChild("CopperTasks_116_BLOCKED_UNVERIFIED_NETLIST", authoring.transform);
                GameObject viasGroup = NewChild("ViaTasks_30_BLOCKED_UNVERIFIED_NETLIST", authoring.transform);
                Dictionary<string, Dictionary<string, string>> modelByRef = ByRef(models);
                Dictionary<string, Dictionary<string, string>> bomByRef = ByRef(bom);
                for (int i = 0; i < placement.Count; i++)
                {
                    Dictionary<string, string> item = placement[i];
                    string id = Get(item, "ref");
                    string fbx = Get(modelByRef[id], "fbx");
                    GameObject model = ResolveModel(root, fbx);
                    GameObject inventoryPrefab = EnsureInventoryArtPrefab(model, id, tempScene);
                    GameObject slot = NewChild("Slot_" + id + "_UNINSTALLED", footprints.transform);
                    Vector3 sourcePose = new Vector3(ReadFloat(Get(item,"x_m")),
                        ReadFloat(Get(item,"y_m")), ReadFloat(Get(item,"z_m")));
                    slot.transform.localPosition = sourcePose;
                    slot.transform.localRotation = Quaternion.Euler(0f, ReadFloat(Get(item,"yaw_deg")), 0f);
                    SparkL103FootprintArtTarget marker = slot.AddComponent<SparkL103FootprintArtTarget>();
                    marker.referenceDesignator = id;
                    marker.modelFbx = fbx;
                    marker.originalPhysicalPositionMeters = sourcePose;
                    marker.inventoryVisualPrefab = inventoryPrefab;
                    marker.startsInstalled = false;
                    marker.hasApprovedPinMapping = false;
                }
                for (int i = 0; i < routes.Count; i++)
                {
                    Dictionary<string, string> r = routes[i];
                    GameObject task = NewChild("Route_" + Get(r,"id") + "_NOT_CERTIFIABLE", routesGroup.transform);
                    SparkL103UnverifiedPlanningTask entry = task.AddComponent<SparkL103UnverifiedPlanningTask>();
                    entry.sourceId = Get(r,"id"); entry.category = "Copper route"; entry.subsystem = Get(r,"group");
                    entry.certifiable = false;
                }
                for (int i = 0; i < vias.Count; i++)
                {
                    Dictionary<string, string> v = vias[i];
                    GameObject task = NewChild("Via_" + Get(v,"id") + "_NOT_CERTIFIABLE", viasGroup.transform);
                    SparkL103UnverifiedPlanningTask entry = task.AddComponent<SparkL103UnverifiedPlanningTask>();
                    entry.sourceId = Get(v,"id"); entry.category = "Via"; entry.subsystem = Get(v,"group");
                    entry.certifiable = false;
                }
                GameObject gameplay = NewChild("GameplayIntegration_REQUIRED_REAL_PROJECT_APIS", main.transform);
                NewChild("SparkTerminal_AndPinMap_BLOCKED", gameplay.transform);
                NewChild("SparkCircuitSystem_VRM_NOT_CONNECTED", gameplay.transform);
                NewChild("ExistingLevelGamePlayManager_NOT_BOUND", gameplay.transform);
                NewChild("VirtualPCBRepairUI_ExistingWorldSpaceCanvas_NOT_DUPLICATED", gameplay.transform);
                GameObject safety = NewChild("W117_TRUSTED_VCORE_GOOD_CONCEPTUAL_PORTS_ONLY", gameplay.transform);
                NewChild("L103_VcoreSupervisor_U10.TRUSTED_VCORE_GOOD_OUT", safety.transform);
                NewChild("L103_CPUSafetySupervisor_U11.TRUSTED_VCORE_GOOD_IN", safety.transform);
                GameObject faults = NewChild("FaultPlan_NOT_INJECTED", gameplay.transform);
                NewChild("F1_Phase2_CurrentSenseDrift", faults.transform);
                NewChild("F2_Phase3_InductorOpenVia", faults.transform);
                NewChild("F3_Phase4_MOSFETThermalLoss", faults.transform);
                GameObject objectives = NewChild("ObjectiveTargets_0_of_6_UNCERTIFIED", gameplay.transform);
                string[] titles = { "01_Assemble88", "02_Route116_Via30", "03_FourPhaseVRM", "04_CPULoadThermal",
                    "05_RepairThreeRealFaults", "06_W117IndependentSafetyRecovery" };
                for (int i = 0; i < titles.Length; i++) NewChild(titles[i] + "_NO_EVIDENCE", objectives.transform);

                AssetDatabase.SaveAssets();
                PrefabUtility.SaveAsPrefabAsset(main, LayoutPrefab);
                if (!EditorSceneManager.SaveScene(tempScene, LayoutScene))
                    throw new IOException("Unity did not save Level_103_Layout.unity");
                WriteReport(root, bounds, models.Count, placement.Count, routes.Count, vias.Count);
                AssetDatabase.Refresh();
                succeeded = true;
            }
            catch (Exception ex)
            {
                Debug.LogError("[L103] Full-layout generation FAILED: " + ex);
            }
            finally
            {
                EditorSceneManager.CloseScene(tempScene, true);
            }
            if (succeeded)
                Debug.Log("[L103] Level_103_Layout.prefab and scene saved. 88 UNINSTALLED slots, 116 UNVERIFIED routes, 30 UNVERIFIED vias; W117 disconnected, 0/6 objectives. Geometry/PBR only; live VRM gameplay NOT implemented. " + ReportPath);
        }

        [MenuItem(Menu + "2. Place Level 103 on SELECTED tabletop")]
        public static void PlacePreviewOnTable()
        {
            Transform table = Selection.activeTransform;
            if (table == null) { Debug.LogError("[L103] Select Table_top Transform first."); return; }
            if (AssetDatabase.LoadAssetAtPath<GameObject>(LayoutPrefab) == null)
            { Debug.LogError("[L103] Build the full layout prefab first."); return; }
            string root = FindSourceRoot();
            GameObject source = string.IsNullOrEmpty(root) ? null : ResolveModel(root, ReferenceModel);
            if (source == null) { Debug.LogError("[L103] Completed reference art not imported."); return; }
            GameObject existing = FindRootInOpenScenes(PreviewName);
            if (existing != null)
            {
                if (!EditorUtility.DisplayDialog("Replace Level 103 preview?", "An existing Level 103 tabletop art preview will be removed. This does not modify the saved gameplay level.", "Replace", "Cancel")) return;
                Undo.DestroyObjectImmediate(existing);
            }
            GameObject preview = new GameObject(PreviewName);
            Undo.RegisterCreatedObjectUndo(preview, "Create L103 tabletop ART preview");
            GameObject board = PrefabUtility.InstantiatePrefab(source) as GameObject;
            if (board == null) { Undo.DestroyObjectImmediate(preview); Debug.LogError("[L103] Could not instantiate completed reference."); return; }
            board.name = "CompletedCPX11_VISUAL_ONLY_NO_GAMEPLAY";
            board.transform.SetParent(preview.transform, false);
            board.transform.localPosition = Vector3.zero;
            board.transform.localRotation = Quaternion.identity;
            board.transform.localScale = Vector3.one;
            SparkL103PBRMaterialBuilder.BindAllMaterials(board);
            StripColliders(board);
            float uniformScale = Mathf.Min(TableTargetWidth / BoardWidthM, TableTargetDepth / BoardDepthM);
            preview.transform.localScale = Vector3.one * uniformScale;
            preview.transform.SetPositionAndRotation(table.position, Quaternion.Euler(0f, table.eulerAngles.y, 0f));
            SparkL103PreviewArtOnly marker = preview.AddComponent<SparkL103PreviewArtOnly>();
            marker.displayScale = uniformScale;
            float surfaceY = table.position.y;
            Collider directCollider = table.GetComponent<Collider>();
            Renderer directRenderer = table.GetComponent<Renderer>();
            if (directCollider != null) surfaceY = directCollider.bounds.max.y;
            else if (directRenderer != null) surfaceY = directRenderer.bounds.max.y;
            Bounds bounds;
            if (TryGetBounds(board, out bounds))
                preview.transform.position += Vector3.up * (surfaceY + 0.005f - bounds.min.y);
            Selection.activeGameObject = preview;
            Debug.Log("[L103] Created completed-board VISUAL-ONLY preview. Physical PCB 0.240x0.180m; display about 10.013 x 7.51 Unity units; uniform scale " + uniformScale.ToString("F3") + ". No electrical/gameplay authority in preview.");
        }

