        private static List<Dictionary<string,string>> ReadCsv(string assetPath)
        {
            var rows = new List<Dictionary<string,string>>();
            string full = ToAbsolute(assetPath);
            if (!File.Exists(full)) { Debug.LogError("[L103] Missing source table " + assetPath); return rows; }
            string[] lines = File.ReadAllLines(full);
            if (lines.Length < 2) return rows;
            List<string> header = ParseLine(lines[0].TrimStart('\ufeff'));
            for (int i = 1; i < lines.Length; i++)
            {
                if (string.IsNullOrWhiteSpace(lines[i])) continue;
                List<string> columns = ParseLine(lines[i]);
                if (columns.Count != header.Count)
                {
                    Debug.LogError("[L103] Malformed CSV " + assetPath + " at line " + (i+1));
                    return new List<Dictionary<string,string>>();
                }
                var row = new Dictionary<string,string>(StringComparer.Ordinal);
                for (int k = 0; k < header.Count; k++) row[header[k]] = columns[k];
                rows.Add(row);
            }
            return rows;
        }
        private static List<string> ParseLine(string line)
        {
            var fields = new List<string>();
            var value = new StringBuilder(); bool quoted = false;
            for (int i = 0; i < line.Length; i++)
            {
                char c = line[i];
                if (c == '"')
                {
                    if (quoted && i + 1 < line.Length && line[i+1] == '"') { value.Append('"'); i++; }
                    else quoted = !quoted;
                }
                else if (c == ',' && !quoted) { fields.Add(value.ToString().Trim()); value.Length = 0; }
                else value.Append(c);
            }
            fields.Add(value.ToString().Trim());
            return fields;
        }
