        public static void ValidateSourceInUnity()
        {
            string root = FindSourceRoot();
            if (root == null) { Debug.LogError("[L103] Source missing/ambiguous."); return; }
            var m = ReadCsv(root + "/Data/ModelManifest.csv");
            var b = ReadCsv(root + "/Data/ComponentBOM.csv");
            var p = ReadCsv(root + "/Data/ComponentPlacements.csv");
            var r = ReadCsv(root + "/Data/CopperRoutes_116_REQUIRES_SCHEMATIC.csv");
            var v = ReadCsv(root + "/Data/ViaTasks_30_REQUIRES_SCHEMATIC.csv");
            bool valid = ValidateData(root, m, b, p, r, v, true);
            Debug.Log("[L103] Source validation " + (valid ? "OK" : "FAILED") + ": 112 modular models, 88 source parts, 116 unverified routes, 30 unverified vias. ELECTRICAL STATUS=BLOCKED_UNVERIFIED_NETLIST; Unity Play Mode, power and objectives still untested.");
        }

        public static string FindSourceRoot()
        {
            string found = null;
            foreach (string guid in AssetDatabase.FindAssets("ModelManifest"))
            {
                string path = AssetDatabase.GUIDToAssetPath(guid).Replace('\\','/');
                string suffix = "/Data/ModelManifest.csv";
                if (!path.EndsWith(suffix, StringComparison.OrdinalIgnoreCase)) continue;
                string candidate = path.Substring(0, path.Length - suffix.Length);
                if (candidate.IndexOf("Level103", StringComparison.OrdinalIgnoreCase) < 0 &&
                    candidate.IndexOf("L103", StringComparison.OrdinalIgnoreCase) < 0) continue;
                if (found != null && !found.Equals(candidate, StringComparison.OrdinalIgnoreCase)) return null;
                found = candidate;
            }
            return found;
        }

        private static bool ValidateData(string root, List<Dictionary<string,string>> models,
            List<Dictionary<string,string>> bom, List<Dictionary<string,string>> positions,
            List<Dictionary<string,string>> routes, List<Dictionary<string,string>> vias, bool verifyImportedMeshes)
        {
            if (models.Count != ModelsExpected || bom.Count != PartsExpected || positions.Count != PartsExpected ||
                routes.Count != RoutesExpected || vias.Count != ViasExpected)
            {
                Debug.LogError("[L103] Manifest counts mismatch. models=" + models.Count + " BOM=" + bom.Count +
                    " placement=" + positions.Count + " routes=" + routes.Count + " vias=" + vias.Count);
                return false;
            }
            HashSet<string> names = new HashSet<string>(StringComparer.Ordinal);
            for (int i = 0; i < PartsExpected; i++)
            {
                string name = Get(models[i], "ref");
                if (name.Length == 0 || !names.Add(name) || Get(positions[i], "ref") != name ||
                    !Get(positions[i], "initial_state").Equals("Uninstalled", StringComparison.OrdinalIgnoreCase))
                { Debug.LogError("[L103] Duplicate, reordered or pre-installed BOM/placement entry " + i); return false; }
            }
            HashSet<string> bomIds = new HashSet<string>(StringComparer.Ordinal);
            foreach (var row in bom) if (!bomIds.Add(Get(row,"ref"))) { Debug.LogError("[L103] Duplicate BOM reference " + Get(row,"ref")); return false; }
            if (!bomIds.SetEquals(names) || !names.Contains("W117"))
            { Debug.LogError("[L103] BOM mismatch or missing W117."); return false; }
            for (int i = 0; i < routes.Count; i++)
            {
                var r = routes[i];
                if (Get(r,"id") != "W" + (i+1).ToString("000",CultureInfo.InvariantCulture) ||
                    Get(r,"net_id") != "UNASSIGNED" || Get(r,"validation_status") != "NOT_CERTIFIABLE" ||
                    Get(r,"source_pin") != "REQUIRES_PIN_SCHEMATIC" || Get(r,"destination_pin") != "REQUIRES_PIN_SCHEMATIC")
                { Debug.LogError("[L103] Route source contract changed: " + Get(r,"id")); return false; }
            }
            for (int i = 0; i < vias.Count; i++)
            {
                var v = vias[i];
                if (Get(v,"id") != "V" + (i+1).ToString("000",CultureInfo.InvariantCulture) ||
                    Get(v,"net_id") != "UNASSIGNED" || Get(v,"validation_status") != "NOT_CERTIFIABLE")
                { Debug.LogError("[L103] Via source contract changed: " + Get(v,"id")); return false; }
            }
            if (!verifyImportedMeshes) return true;
            for (int i = 0; i < models.Count; i++)
            {
                string fbx = Get(models[i],"fbx");
                string glb = Get(models[i],"glb");
                if (!File.Exists(ToAbsolute(root + "/Models_FBX/" + fbx)) ||
                    !File.Exists(ToAbsolute(root + "/Models_GLB/" + glb)) || ResolveModel(root, fbx) == null)
                { Debug.LogError("[L103] Missing or unrenderable art in model manifest: " + fbx); return false; }
            }
            if (ResolveModel(root, ReferenceModel) == null)
            { Debug.LogError("[L103] Assembled reference OBJ missing/unrenderable."); return false; }
            return true;
        }

        private static SparkL103SourceBlueprint CreateOrUpdateBlueprint(List<Dictionary<string,string>> models,
            List<Dictionary<string,string>> bom, List<Dictionary<string,string>> placements,
            List<Dictionary<string,string>> routes, List<Dictionary<string,string>> vias)
        {
            SparkL103SourceBlueprint asset = AssetDatabase.LoadAssetAtPath<SparkL103SourceBlueprint>(BlueprintPath);
            if (asset == null)
            {
                asset = ScriptableObject.CreateInstance<SparkL103SourceBlueprint>();
                AssetDatabase.CreateAsset(asset, BlueprintPath);
            }
            asset.electricalStatus = SparkL103SourceBlueprint.UnverifiedStatus;
            asset.certifiedObjectives = 0;
            asset.components.Clear(); asset.routes.Clear(); asset.vias.Clear();
            Dictionary<string,Dictionary<string,string>> indexedModels = ByRef(models);
            Dictionary<string,Dictionary<string,string>> indexedBOM = ByRef(bom);
            foreach (var p in placements)
            {
                string id = Get(p,"ref");
                asset.components.Add(new SparkL103ComponentRecord
                {
                    referenceDesignator = id, kind = Get(indexedBOM[id],"kind"), description = Get(indexedBOM[id],"description"),
                    sourceFbx = Get(indexedModels[id],"fbx"),
                    physicalPositionMeters = new Vector3(ReadFloat(Get(p,"x_m")),ReadFloat(Get(p,"y_m")),ReadFloat(Get(p,"z_m"))),
                    yawDegrees = ReadFloat(Get(p,"yaw_deg")), startsInstalled = false
                });
            }
            foreach (var r in routes)
                asset.routes.Add(new SparkL103CopperTaskRecord { id=Get(r,"id"),subsystem=Get(r,"group"),
                    netId=Get(r,"net_id"),sourcePin=Get(r,"source_pin"),destinationPin=Get(r,"destination_pin"),
                    layerSpan=Get(r,"layer_span"), certifiable=false });
            foreach (var v in vias)
                asset.vias.Add(new SparkL103ViaTaskRecord { id=Get(v,"id"),subsystem=Get(v,"group"),
                    netId=Get(v,"net_id"),sourcePin=Get(v,"source_pin"),destinationPin=Get(v,"destination_pin"),
                    layerSpan=Get(v,"layer_span"), certifiable=false });
            EditorUtility.SetDirty(asset);
            return asset;
        }

        private static GameObject ResolveModel(string root, string fbxName)
        {
            string stem = Path.GetFileNameWithoutExtension(fbxName);
            // L103's original FBX vertices are centimetres. Prefer correctly oriented GLB-derived
            // metre OBJ; do not accidentally accept a visible but 100x-too-big FBX.
            GameObject fallback = AssetDatabase.LoadAssetAtPath<GameObject>(root + "/Models_OBJ_Fallback/" + stem + ".obj");
            return HasMesh(fallback) ? fallback : null;
        }
        private static bool HasMesh(GameObject source)
        {
            if (source == null) return false;
            MeshFilter[] filters = source.GetComponentsInChildren<MeshFilter>(true);
            for (int i=0;i<filters.Length;i++)
                if (filters[i].sharedMesh != null && filters[i].sharedMesh.vertexCount > 2) return true;
            return false;
        }
        private static GameObject SpawnArt(GameObject source, string name, Transform parent, Scene scene)
        {
            GameObject child = PrefabUtility.InstantiatePrefab(source, scene) as GameObject;
            if (child == null) return null;
            child.name = name;
            child.transform.SetParent(parent, false);
            child.transform.localPosition = Vector3.zero;
            child.transform.localRotation = Quaternion.identity;
            child.transform.localScale = Vector3.one;
            SparkL103PBRMaterialBuilder.BindAllMaterials(child);
            StripColliders(child);
            return child;
        }
        private static GameObject EnsureInventoryArtPrefab(GameObject source, string refdes, Scene scene)
        {
            if (source == null) throw new InvalidOperationException("Missing source 3D model for " + refdes);
            GameObject container = NewRootInScene("L103_" + refdes + "_VisualOnly", scene);
            try
            {
                GameObject model = SpawnArt(source, "SourceMesh_Metres", container.transform, scene);
                if (model == null) throw new InvalidOperationException("Source model cannot instantiate: " + refdes);
                string path = Generated + "/ComponentVisualPrefabs/L103_" + refdes + "_Visual.prefab";
                GameObject saved = PrefabUtility.SaveAsPrefabAsset(container, path);
                if (saved == null) throw new IOException("Visual prefab asset did not save: " + path);
                return saved;
            }
            finally { UnityEngine.Object.DestroyImmediate(container); }
        }
        private static void StripColliders(GameObject go)
        {
            Collider[] colliders = go.GetComponentsInChildren<Collider>(true);
            for (int i = 0; i < colliders.Length; i++) UnityEngine.Object.DestroyImmediate(colliders[i]);
        }
        private static bool TryGetBounds(GameObject root, out Bounds value)
        {
            value = new Bounds(root.transform.position, Vector3.zero);
            bool found = false;
            Renderer[] renderers = root.GetComponentsInChildren<Renderer>(true);
            for (int i = 0; i < renderers.Length; i++)
            {
                if (!renderers[i].gameObject.activeInHierarchy) continue;
                if (!found) { value=renderers[i].bounds; found=true; }
                else value.Encapsulate(renderers[i].bounds);
            }
            return found;
        }
        private static GameObject NewRootInScene(string name, Scene scene)
        {
            GameObject result = new GameObject(name);
            SceneManager.MoveGameObjectToScene(result, scene);
            return result;
        }
        private static GameObject NewChild(string name, Transform parent)
        {
            GameObject child = new GameObject(name);
            child.transform.SetParent(parent, false);
            return child;
        }
        private static GameObject FindRootInOpenScenes(string name)
        {
            for (int i = 0; i < SceneManager.sceneCount; i++)
            {
                Scene scene = SceneManager.GetSceneAt(i);
                if (!scene.isLoaded) continue;
                foreach (GameObject root in scene.GetRootGameObjects())
                    if (root.name == name) return root;
            }
            return null;
        }
        private static Dictionary<string,Dictionary<string,string>> ByRef(List<Dictionary<string,string>> source)
        {
            var found = new Dictionary<string,Dictionary<string,string>>(StringComparer.Ordinal);
            foreach (var entry in source) found.Add(Get(entry,"ref"), entry);
            return found;
        }
