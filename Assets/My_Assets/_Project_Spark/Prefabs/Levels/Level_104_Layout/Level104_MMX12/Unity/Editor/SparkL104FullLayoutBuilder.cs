    /// <summary>
    /// Isolated, idempotent Level 104 VISUAL layout authoring.
    /// It deliberately does not infer physical terminals or authorize gameplay.
    /// Requires the source kit and GLB-derived OBJ mesh fallbacks.
    /// </summary>
    public static class SparkL104FullLayoutBuilder
    {
        private const string Output =
            "Assets/ProjectSpark/AutoGeneratedLevels/Level104";
        private const string PrefabPath = Output + "/Level_104_Layout.prefab";
        private const string ScenePath = Output + "/Level_104_Layout.unity";
        private const string BlueprintPath = Output + "/L104_SourceBlueprint.asset";
        private const string RootName = "Level_104_Layout";
        private const string PreviewName = "L104_MMX12_TABLETOP_VISUAL_PREVIEW";
        private const float PcbWidthMeters = 0.260f;
        private const float PcbDepthMeters = 0.185f;
        private const float TablePreviewWidth = 10.13f;

        [MenuItem("Tools/Project Spark/Levels/Create Level 104")]
        public static void BuildLevel104Convenience()
        {
            BuildFullLayout();
        }

        [MenuItem("Tools/Project Spark/Automatic Level Generator/104/1. Build FULL Level_104_Layout")]
        public static void BuildFullLayout()
        {
            string sourceRoot = FindSourceRoot();
            if (string.IsNullOrEmpty(sourceRoot))
            {
                Debug.LogError("[L104] Source kit not found. Install Level104_MMX12 first.");
                return;
            }

            string[][] manifest = LoadCsv(sourceRoot + "/Data/ModelManifest.csv");
            string[][] routes = LoadCsv(sourceRoot + "/Data/CopperRoutes_124_REQUIRES_SCHEMATIC.csv");
            string[][] vias = LoadCsv(sourceRoot + "/Data/ViaTasks_34_REQUIRES_SCHEMATIC.csv");
            string[][] placements = LoadCsv(sourceRoot + "/Data/ComponentPlacements.csv");

            if (manifest == null || routes == null || vias == null || placements == null ||
                manifest.Length != 120 || routes.Length != 124 ||
                vias.Length != 34 || placements.Length != 94)
            {
                Debug.LogError("[L104] Source counts incorrect. Expected " +
                    "120 models, 94 placements, 124 routes, 34 vias. Nothing built.");
                return;
            }

            int installable = 0;
            HashSet<string> uniqueAssets = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            HashSet<string> uniquePlacements = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            for (int i = 0; i < manifest.Length; i++)
            {
                if (manifest[i].Length < 9 || !uniqueAssets.Add(manifest[i][1]))
                {
                    Debug.LogError("[L104] Invalid/duplicate model asset ID at row " + i);
                    return;
                }
                if (String.Equals(manifest[i][8], "True", StringComparison.OrdinalIgnoreCase))
                    installable++;
                string objPath = GetFallbackPath(sourceRoot, manifest[i][3]);
                if (!File.Exists(ToAbsolute(objPath)))
                {
                    Debug.LogError("[L104] Missing fallback OBJ: " + objPath);
                    return;
                }
            }
            for (int i = 0; i < placements.Length; i++)
            {
                if (placements[i].Length < 6 || !uniquePlacements.Add(placements[i][0]) ||
                    !uniqueAssets.Contains("L104_" + placements[i][0]))
                {
                    Debug.LogError("[L104] Invalid/duplicate placement: row " + i);
                    return;
                }
            }
            if (installable != 94)
            {
                Debug.LogError("[L104] Exactly 94 installable assets required; found " + installable);
                return;
            }
            if (!CheckUnverifiedTasks(routes, true) || !CheckUnverifiedTasks(vias, false))
            {
                Debug.LogError("[L104] Unexpected approved routing/via source status. " +
                    "Review source before rebuilding. Nothing built.");
                return;
            }
            if (!SparkL104URPPBRMaterialBuilder.BuildForRoot(sourceRoot)) return;

            Directory.CreateDirectory(ToAbsolute(Output));
            Directory.CreateDirectory(ToAbsolute(Output + "/ComponentVisualPrefabs"));
            AssetDatabase.Refresh();

            GameObject root = new GameObject(RootName);
            try
            {
                SparkL104LayoutState state = root.AddComponent<SparkL104LayoutState>();
                state.schematicApproved = false;
                state.electricalIntegrationVerified = false;

                Transform visuals = Child(root.transform, "Visuals");
                Transform pcbRoot = Child(visuals, "PCB_Base");
                GameObject board = InstantiateModel(
                    GetFallbackPath(sourceRoot, "095_L104_PCB_Substrate_260x185mm.fbx"),
                    pcbRoot, "PCB_Substrate_PhysicalScale");
                if (board == null || !ValidateBoardBounds(board))
                {
                    Debug.LogError("[L104] Board import scale or orientation is invalid. " +
                        "Required physical dimensions: X=0.260m, Z=0.185m. No prefab saved.");
                    return;
                }

                Transform auxiliaryArt = Child(visuals, "LayerAndInspectionArt_DISABLED");
                for (int i = 94; i < manifest.Length; i++)
                {
                    string modelPath = GetFallbackPath(sourceRoot, manifest[i][3]);
                    GameObject detail = InstantiateModel(modelPath, auxiliaryArt, manifest[i][1]);
                    if (detail == null) return;
                    detail.AddComponent<SparkL104VisualReference>();
                    detail.SetActive(false);
                }

                Transform assembledArt = Child(visuals, "AssembledReference_DISABLED");
                GameObject showcase = InstantiateModel(
                    sourceRoot + "/Models_OBJ/121_L104_AssembledReference.obj",
                    assembledArt, "REFERENCE_NOT_GAMEPLAY");
                if (showcase == null) return;
                showcase.AddComponent<SparkL104VisualReference>();
                showcase.SetActive(false);
                Child(visuals, "InstalledComponentVisuals_EMPTY");
                Child(visuals, "PlayerCopperVisuals_EMPTY");
                Child(visuals, "PlayerViaVisuals_EMPTY");

                Transform targets = Child(root.transform, "ComponentPlacementTargets_94_UNINSTALLED");
                Transform tasks = Child(root.transform, "SourceTasks_NOT_CERTIFIABLE");
                Transform routeRoot = Child(tasks, "CopperRoutes_124_BLOCKED");
                Transform viaRoot = Child(tasks, "Vias_34_BLOCKED");
                Transform safety = Child(root.transform, "Safety_W125_PIN_MAPPING_REQUIRED");
                Child(root.transform, "ElectricalAuthority_ADAPTER_REQUIRED");
                Child(root.transform, "ExistingVirtualPCBStudio_ADAPTER_REQUIRED");
                Child(root.transform, "Diagnostics_NO_OBJECTIVES_CERTIFIED");

                Dictionary<string, string[]> manifestLookup =
                    new Dictionary<string, string[]>(StringComparer.OrdinalIgnoreCase);
                for (int i = 0; i < manifest.Length; i++)
                    manifestLookup[manifest[i][1]] = manifest[i];

                for (int i = 0; i < placements.Length; i++)
                {
                    string componentRef = placements[i][0];
                    string assetId = "L104_" + componentRef;
                    string[] modelInfo = manifestLookup[assetId];
                    Vector3 position = new Vector3(
                        ParseMetres(placements[i][1]), ParseMetres(placements[i][2]),
                        ParseMetres(placements[i][3]));
                    GameObject target = new GameObject("SLOT_" + componentRef + "_UNINSTALLED");
                    target.transform.SetParent(targets, false);
                    target.transform.localPosition = position;
                    SparkL104ComponentVisualSlot marker =
                        target.AddComponent<SparkL104ComponentVisualSlot>();
                    marker.componentReference = componentRef;
                    marker.sourceAssetId = assetId;
                    marker.intendedPhysicalPosition = position;
                    marker.visualPrefabPath = Output + "/ComponentVisualPrefabs/" +
                        assetId + "_Visual.prefab";

                    if (!MakeVisualPrefab(
                            GetFallbackPath(sourceRoot, modelInfo[3]),
                            assetId, marker.visualPrefabPath))
                        return;
                }

                for (int i = 0; i < routes.Length; i++)
                {
                    GameObject task = new GameObject(routes[i][0] + "_BLOCKED");
                    task.transform.SetParent(routeRoot, false);
                    SparkL104BlockedTaskMarker marker =
                        task.AddComponent<SparkL104BlockedTaskMarker>();
                    marker.taskId = routes[i][0];
                    marker.taskGroup = routes[i][1];
                    marker.sourcePad = routes[i][2];
                    marker.destinationPad = routes[i][3];
                    marker.netId = routes[i][4];
                }
                for (int i = 0; i < vias.Length; i++)
                {
                    GameObject task = new GameObject(vias[i][0] + "_BLOCKED");
                    task.transform.SetParent(viaRoot, false);
                    SparkL104BlockedTaskMarker marker =
                        task.AddComponent<SparkL104BlockedTaskMarker>();
                    marker.taskId = vias[i][0];
                    marker.taskGroup = "Via";
                    marker.netId = vias[i][3];
                    marker.layerSpan = vias[i][1] + " -> " + vias[i][2];
                }

                GameObject safetyMarker = new GameObject("W125_OPEN_U11_U12_UNRESOLVED");
                safetyMarker.transform.SetParent(safety, false);
                SparkL104BlockedTaskMarker w125 =
                    safetyMarker.AddComponent<SparkL104BlockedTaskMarker>();
                w125.taskId = "W125";
                w125.taskGroup = "Trusted memory-ready feedback";
                w125.sourcePad = "L104_MemoryTrainingMonitor_U11.TRUSTED_MEMORY_READY_OUT";
                w125.destinationPad = "L104_MemorySafetySupervisor_U12.TRUSTED_MEMORY_READY_IN";
                w125.netId = "SCHEMATIC_VALIDATION_REQUIRED";

                UpdateBlueprint(manifest, routes, vias);
                PrefabUtility.SaveAsPrefabAsset(root, PrefabPath);
                AssetDatabase.SaveAssets();
                CreatePrefabScene();
                WriteValidationReport(sourceRoot);
                AssetDatabase.Refresh();
                Debug.Log("[L104] Created Level_104_Layout prefab and scene. " +
                    "94 uninstalled targets, 124 blocked routes, 34 blocked vias, " +
                    "0/6 objectives. W125 mapping unresolved; no gameplay certified.");
                Selection.activeObject = AssetDatabase.LoadAssetAtPath<GameObject>(PrefabPath);
            }
            finally
            {
                UnityEngine.Object.DestroyImmediate(root);
            }
        }

        [MenuItem("Tools/Project Spark/Automatic Level Generator/104/2. Place Level 104 on SELECTED tabletop")]
        public static void PlaceTabletopPreview()
        {
            Transform tabletop = Selection.activeTransform;
            if (tabletop == null)
            {
                Debug.LogError("[L104] Select the existing Table_top Transform first.");
                return;
            }
            string root = FindSourceRoot();
            if (string.IsNullOrEmpty(root)) return;
            string modelPath = root + "/Models_OBJ/121_L104_AssembledReference.obj";
            GameObject prefab = AssetDatabase.LoadAssetAtPath<GameObject>(modelPath);
            if (prefab == null)
            {
                Debug.LogError("[L104] Missing assembled preview OBJ: " + modelPath);
                return;
            }

            GameObject[] objects = SceneManager.GetActiveScene().GetRootGameObjects();
            for (int i = 0; i < objects.Length; i++)
            {
                if (objects[i].name == PreviewName)
                    Undo.DestroyObjectImmediate(objects[i]);
            }

            GameObject preview = new GameObject(PreviewName);
            Undo.RegisterCreatedObjectUndo(preview, "Create L104 tabletop art preview");
            preview.transform.position = tabletop.position + tabletop.up * 0.025f;
            preview.transform.rotation = tabletop.rotation;
            preview.transform.localScale = Vector3.one * (TablePreviewWidth / PcbWidthMeters);
            GameObject assembled = (GameObject)PrefabUtility.InstantiatePrefab(prefab);
            if (assembled == null)
            {
                Undo.DestroyObjectImmediate(preview);
                Debug.LogError("[L104] Could not instantiate assembled reference.");
                return;
            }
            assembled.transform.SetParent(preview.transform, false);
            assembled.transform.localPosition = Vector3.zero;
            assembled.transform.localRotation = Quaternion.identity;
            assembled.transform.localScale = Vector3.one;
            assembled.name = "SHOWCASE_ONLY_NOT_GAMEPLAY";
            assembled.AddComponent<SparkL104VisualReference>();
            SparkL104URPPBRMaterialBuilder.BindAllMaterials(assembled);
            Collider[] colliders = assembled.GetComponentsInChildren<Collider>(true);
            for (int i = 0; i < colliders.Length; i++) colliders[i].enabled = false;
            Selection.activeGameObject = preview;
            Debug.Log("[L104] Visual-only preview placed: approximately 10.13 x 7.21 " +
                "Unity units, proportional to 260 x 185 mm. Never use for electrical calculations.");
        }

        [MenuItem("Tools/Project Spark/Automatic Level Generator/104/3. Validate Source and 3D Models")]
        public static void ValidateImportedSource()
        {
            string root = FindSourceRoot();
            if (string.IsNullOrEmpty(root))
            {
                Debug.LogError("[L104] Level 104 source folder not found.");
                return;
            }
            string[][] models = LoadCsv(root + "/Data/ModelManifest.csv");
            string[][] routes = LoadCsv(root + "/Data/CopperRoutes_124_REQUIRES_SCHEMATIC.csv");
            string[][] vias = LoadCsv(root + "/Data/ViaTasks_34_REQUIRES_SCHEMATIC.csv");
            int found = 0;
            if (models != null)
            {
                for (int i = 0; i < models.Length; i++)
                {
                    if (models[i].Length > 3 &&
                        AssetDatabase.LoadAssetAtPath<GameObject>(
                            GetFallbackPath(root, models[i][3])) != null) found++;
                }
            }
            Debug.Log("[L104] Modular OBJ imported: " + found + "/120; " +
                "routes: " + (routes == null ? 0 : routes.Length) + "/124; vias: " +
                (vias == null ? 0 : vias.Length) + "/34. " +
                "All route/via pins remain unapproved; W125 U11/U12 does not match BOM. " +
                "This is ART validation, NOT Unity Play Mode or gameplay certification.");
        }

        public static string FindSourceRoot()
        {
            string[] ids = AssetDatabase.FindAssets("ModelManifest");
            for (int i = 0; i < ids.Length; i++)
            {
                string asset = AssetDatabase.GUIDToAssetPath(ids[i]).Replace('\\', '/');
                if (!asset.EndsWith("/Level104_MMX12/Data/ModelManifest.csv",
                    StringComparison.OrdinalIgnoreCase)) continue;
                string root = asset.Substring(0, asset.Length - "/Data/ModelManifest.csv".Length);
                if (File.Exists(ToAbsolute(root + "/Data/ComponentBOM.csv")))
                    return root;
            }
            return null;
        }

        private static bool ValidateBoardBounds(GameObject board)
        {
            Renderer[] renderers = board.GetComponentsInChildren<Renderer>(true);
            if (renderers.Length == 0) return false;
            Bounds combined = renderers[0].bounds;
            for (int i = 1; i < renderers.Length; i++)
                combined.Encapsulate(renderers[i].bounds);
            Vector3 size = combined.size;
            Debug.Log("[L104] Imported fallback PCB bounding size: " + size);
            return Mathf.Abs(size.x - PcbWidthMeters) <= 0.012f &&
                   Mathf.Abs(size.z - PcbDepthMeters) <= 0.012f;
        }

        private static bool CheckUnverifiedTasks(string[][] records, bool isRoute)
        {
            for (int i = 0; i < records.Length; i++)
            {
                string[] r = records[i];
                if (isRoute)
                {
                    if (r.Length < 6 || r[2] != "UNASSIGNED" ||
                        r[3] != "UNASSIGNED" || r[4] != "UNASSIGNED" ||
                        !String.Equals(r[5], "False", StringComparison.OrdinalIgnoreCase))
                        return false;
                }
                else if (r.Length < 5 || r[1] != "TBD" || r[2] != "TBD" ||
                         r[3] != "UNASSIGNED" ||
                         !String.Equals(r[4], "False", StringComparison.OrdinalIgnoreCase))
                    return false;
            }
            return true;
        }

        private static bool MakeVisualPrefab(string sourceModel, string id, string outputPath)
        {
            GameObject holder = new GameObject(id + "_Visual");
            try
            {
                GameObject instance = InstantiateModel(sourceModel, holder.transform,
                    id + "_Geometry");
                if (instance == null) return false;
                holder.AddComponent<SparkL104VisualReference>();
                PrefabUtility.SaveAsPrefabAsset(holder, outputPath);
                return true;
            }
            finally { UnityEngine.Object.DestroyImmediate(holder); }
        }

        private static GameObject InstantiateModel(string path, Transform parent, string objectName)
        {
            GameObject model = AssetDatabase.LoadAssetAtPath<GameObject>(path);
            if (model == null)
            {
                Debug.LogError("[L104] Cannot import 3D model: " + path);
                return null;
            }
            GameObject created = PrefabUtility.InstantiatePrefab(model) as GameObject;
            if (created == null)
            {
                Debug.LogError("[L104] Failed to instantiate: " + path);
                return null;
            }
            created.transform.SetParent(parent, false);
            created.transform.localPosition = Vector3.zero;
            created.transform.localRotation = Quaternion.identity;
            created.transform.localScale = Vector3.one;
            created.name = objectName;
            SparkL104URPPBRMaterialBuilder.BindAllMaterials(created);
            return created;
        }

        private static void UpdateBlueprint(string[][] manifest, string[][] routes, string[][] vias)
        {
            SparkL104SourceBlueprint blueprint =
                AssetDatabase.LoadAssetAtPath<SparkL104SourceBlueprint>(BlueprintPath);
            if (blueprint == null)
            {
                blueprint = ScriptableObject.CreateInstance<SparkL104SourceBlueprint>();
                AssetDatabase.CreateAsset(blueprint, BlueprintPath);
            }

            blueprint.models = new SparkL104ModelRecord[manifest.Length];
            for (int i = 0; i < manifest.Length; i++)
            {
                string[] r = manifest[i];
                blueprint.models[i] = new SparkL104ModelRecord
                {
                    assetId = r[1], kind = r[2], sourceFbx = r[3], sourceGlb = r[4],
                    physicalLocalPosition = new Vector3(
                        ParseMetres(r[5]), ParseMetres(r[6]), ParseMetres(r[7])),
                    installable = String.Equals(r[8], "True", StringComparison.OrdinalIgnoreCase)
                };
            }
            blueprint.copperRoutes = new SparkL104TaskRecord[routes.Length];
            for (int i = 0; i < routes.Length; i++)
            {
                string[] r = routes[i];
                blueprint.copperRoutes[i] = new SparkL104TaskRecord
                {
                    id = r[0], category = r[1], sourcePad = r[2],
                    destinationPad = r[3], netId = r[4], certifiable = false
                };
            }
            blueprint.vias = new SparkL104TaskRecord[vias.Length];
            for (int i = 0; i < vias.Length; i++)
            {
                string[] r = vias[i];
                blueprint.vias[i] = new SparkL104TaskRecord
                {
                    id = r[0], category = "Via", layerSpan = r[1] + " -> " + r[2],
                    netId = r[3], certifiable = false
                };
            }
            blueprint.approvedPinLevelNetlist = false;
            blueprint.w125EndpointMappingApproved = false;
            EditorUtility.SetDirty(blueprint);
        }

        private static void CreatePrefabScene()
        {
            GameObject prefab = AssetDatabase.LoadAssetAtPath<GameObject>(PrefabPath);
            if (prefab == null) return;
            Scene scene = EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Additive);
            try
            {
                GameObject instance = PrefabUtility.InstantiatePrefab(prefab) as GameObject;
                if (instance == null) return;
                SceneManager.MoveGameObjectToScene(instance, scene);
                EditorSceneManager.SaveScene(scene, ScenePath);
            }
            finally
            {
                EditorSceneManager.CloseScene(scene, true);
            }
        }

        private static void WriteValidationReport(string sourceRoot)
        {
            string message =
                "PROJECT SPARK - LEVEL 104 MMX-12 - OFFLINE/EDITOR ART REPORT\n" +
                "Source kit: " + sourceRoot + "\n" +
                "Physical PCB: X=0.260 m, Z=0.185 m; Y up, 8 layers\n" +
                "Source 3D: 120 modular GLB/FBX pairs, 1 assembled reference\n" +
                "Fall-back meshes: 121 OBJ models (Y-up, metres, generated UVs)\n" +
                "Installed components: 0 / 94 (slots only, no gameplay)\n" +
                "Copper routes: 0 / 124 (UNASSIGNED, NOT CERTIFIABLE)\n" +
                "Vias: 0 / 34 (TBD, NOT CERTIFIABLE)\n" +
                "W125: OPEN. U11/U12 named by safety JSON but absent in BOM.\n" +
                "Objectives: 0 / 6. No gameplay manager rewards are created.\n" +
                "VRM, DDR4 training, memory tests, repair/solver adapters: NOT IMPLEMENTED.\n" +
                "Unity compilation / Play Mode / performance: NOT TESTED BY PACKAGE CREATOR.\n" +
                "Never use assembled reference or visual-only tabletop preview as gameplay authority.\n";
            File.WriteAllText(ToAbsolute(Output + "/L104_Layout_Validation.txt"), message);
        }

        private static Transform Child(Transform parent, string name)
        {
            GameObject child = new GameObject(name);
            child.transform.SetParent(parent, false);
            return child.transform;
        }

        private static string GetFallbackPath(string root, string sourceFbx)
        {
            return root + "/Models_OBJ/" + Path.GetFileNameWithoutExtension(sourceFbx) + ".obj";
        }

        private static float ParseMetres(string value)
        {
            return float.Parse(value, NumberStyles.Float, CultureInfo.InvariantCulture);
        }

        private static string[][] LoadCsv(string assetPath)
        {
            string fullPath = ToAbsolute(assetPath);
            if (!File.Exists(fullPath)) return null;
            string[] lines = File.ReadAllLines(fullPath);
            if (lines.Length <= 1) return new string[0][];
            List<string[]> rows = new List<string[]>();
            for (int i = 1; i < lines.Length; i++)
            {
                if (string.IsNullOrWhiteSpace(lines[i])) continue;
                rows.Add(lines[i].TrimEnd('\r').Split(','));
            }
            return rows.ToArray();
        }

        private static string ToAbsolute(string assetPath)
        {
            string project = Directory.GetParent(Application.dataPath).FullName;
            return Path.Combine(project, assetPath.Replace('/', Path.DirectorySeparatorChar));
        }
