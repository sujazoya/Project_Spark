                new Vector3(.200f,.0014f,.150f),new Vector3(.200f,.0014f,.105f),
                new Vector3(.200f,.0014f,.060f),new Vector3(.200f,.0014f,.015f),
                new Vector3(.015f,.0014f,-.130f),new Vector3(-.085f,.0014f,.142f),
                new Vector3(-.045f,.0014f,-.151f)
