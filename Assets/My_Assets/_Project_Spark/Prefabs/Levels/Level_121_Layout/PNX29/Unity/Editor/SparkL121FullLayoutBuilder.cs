            if (imported == null)
            {
                Debug.LogError("[L121] Assembled showcase OBJ unavailable.");
                return;
            }
            GameObject preview = new GameObject("L121_PNX29_VisualPreview_ONLY");
            Undo.RegisterCreatedObjectUndo(preview, "Create Level121 Visual Preview");
            preview.AddComponent<SparkL121VisualOnly>();
            GameObject visual = (GameObject)PrefabUtility.InstantiatePrefab(imported);
            visual.transform.SetParent(preview.transform, false);
            visual.name = "VisualShowcase_NotElectrical";
            SparkL121URPPBRMaterialBuilder.Bind(visual);
