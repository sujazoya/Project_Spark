            GameObject targets = Child(authoring.transform, "280_UninstalledComponentTargets");
            GameObject routes = Child(authoring.transform, "368_Routes_UNASSIGNED_BLOCKED");
            GameObject vias = Child(authoring.transform, "140_Vias_UNASSIGNED_BLOCKED");
