            GameObject zones = Child(authoring.transform, "PerceptionAcquisitionZones_UNBOUND");
            string[] zoneNames = {
                "Camera_A_StereoLeft_UNBOUND", "Camera_B_StereoRight_UNBOUND",
                "Camera_C_DepthA_UNBOUND", "Camera_D_DepthB_UNBOUND",
                "LiDAR_ToF_UNBOUND", "IMU_Timing_UNBOUND", "Independent_Safety_UNBOUND"
            };
