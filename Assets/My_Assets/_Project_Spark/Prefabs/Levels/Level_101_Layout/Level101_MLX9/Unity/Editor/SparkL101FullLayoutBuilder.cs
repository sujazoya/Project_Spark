        [MenuItem(Menu + "1. Build FULL Level_101_Layout")]
        public static void BuildFull()
        {
            string root = FindSourceRoot();
            if (string.IsNullOrEmpty(root))
            {
                Debug.LogError("[L101] Source missing or duplicated: Level101_MLX9/Data/Asset_Manifest_96.csv. Use complete install; remove duplicate roots.");
                return;
            }
            List<Dictionary<string, string>> models = ReadCsv(root + "/Data/Asset_Manifest_96.csv");
            List<Dictionary<string, string>> bom = ReadCsv(root + "/Data/Component_BOM_76.csv");
            List<Dictionary<string, string>> placement = ReadCsv(root + "/Data/Component_BOM_76.csv");
            List<Dictionary<string, string>> routes = ReadCsv(root + "/Data/Copper_Routes_100_UNVERIFIED.csv");
            List<Dictionary<string, string>> vias = ReadCsv(root + "/Data/Vias_24_UNVERIFIED.csv");
            if (!ValidateData(root, models, bom, placement, routes, vias, true)) return;
            GameObject boardSource = ResolveModel(root, BoardModel);
            GameObject referenceSource = ResolveModel(root, ReferenceModel);
            if (boardSource == null || referenceSource == null)
            {
                Debug.LogError("[L101] Empty MLX-9 board or assembled source is not a renderable imported model.");
                return;
            }
            if (AssetDatabase.LoadAssetAtPath<GameObject>(LayoutPrefab) != null &&
                !EditorUtility.DisplayDialog("Level 101 rebuild", "Rebuild generated Level 101 scene/prefab/visual inventory? This will overwrite only Level 101 generated art assets. Back up user modifications first.", "Rebuild", "Cancel")) return;
            if (!SparkL101URPPBRMaterialBuilder.BuildForRoot(root)) return;
            Directory.CreateDirectory(ToAbsolute(Generated));
            Directory.CreateDirectory(ToAbsolute(Generated + "/ComponentVisualPrefabs"));
            AssetDatabase.Refresh();
            SparkL101SourceBlueprint blueprint = CreateOrUpdateBlueprint(models, bom, placement, routes, vias);
            Scene tempScene = EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Additive);
            bool succeeded = false;
            try
            {
                GameObject main = NewRootInScene("L101_TheHiddenLayers_MLX9", tempScene);
                GameObject visuals = NewChild("Visuals", main.transform);
                GameObject baseArt = NewChild("EmptyPCB_FactoryOnly", visuals.transform);
                GameObject baseInstance = SpawnArt(boardSource, "MLX9_EmptyPCB_SourceGeometry", baseArt.transform, tempScene);
                if (baseInstance == null) throw new InvalidOperationException("Unable to instantiate empty board.");
                Bounds bounds;
                if (!TryGetBounds(baseInstance, out bounds) ||
                    Mathf.Abs(bounds.size.x - BoardWidthM) > .004f || Mathf.Abs(bounds.size.z - BoardDepthM) > .004f)
                    throw new InvalidOperationException("Board Unity geometry scale mismatch. Expected 0.230 x 0.160 metres; actual " + bounds.size + ". Do not double-scale centimetre FBXs.");

                // Original board only: never preinstall electronic components or solder.
                NewChild("InstalledComponentVisuals_EMPTY", visuals.transform);
                NewChild("NewCopperTraces_EMPTY", visuals.transform);
                NewChild("InstalledVias_EMPTY", visuals.transform);
                GameObject factory = NewChild("FactoryFootprintsAndSilkscreen_ART_ONLY", visuals.transform);
                GameObject layers = NewChild("LayerInspection_REFERENCE_DISABLED", visuals.transform);
                GameObject diagnostics = NewChild("OtherStructuralAndFaultArt_REFERENCE_DISABLED", visuals.transform);
                for (int i = 77; i < ModelsExpected; i++)
                {
                    Dictionary<string, string> item = models[i];
                    string fbx = Get(item, "fbx");
                    GameObject sourceGeometry = ResolveModel(root, fbx);
                    if (sourceGeometry == null)
                        throw new InvalidOperationException("Missing secondary art: " + fbx);
                    bool factoryVisual = fbx == "084_L101_SMD_Footprint_Pads.fbx" ||
                                         fbx == "093_L101_Silkscreen_Reference.fbx";
                    bool isLayer = Get(item, "name").Contains("Layer") ||
                                   Get(item, "name").Contains("Plane") ||
                                   Get(item, "name").Contains("Copper");
                    Transform holder = factoryVisual ? factory.transform :
                                       isLayer ? layers.transform : diagnostics.transform;
                    GameObject detail = SpawnArt(sourceGeometry,
                        "SOURCE_ART_ONLY_" + Path.GetFileNameWithoutExtension(fbx), holder, tempScene);
                    if (detail == null) throw new InvalidOperationException("Unable to instantiate " + fbx);
                    if (!factoryVisual) detail.SetActive(false);
                }
                layers.SetActive(false);
                diagnostics.SetActive(false);
                // The assembled showcase is intentionally NOT created under this live layout.
                // It is only instantiated by the separate tabletop visual-preview menu.

                GameObject authoring = NewChild("SourcePlanning_NOT_GAMEPLAY_AUTHORITY", main.transform);
                GameObject footprints = NewChild("FootprintTargets_76_ALL_UNINSTALLED", authoring.transform);
                GameObject routesGroup = NewChild("CopperTasks_100_BLOCKED_UNVERIFIED_NETLIST", authoring.transform);
                GameObject viasGroup = NewChild("ViaTasks_24_BLOCKED_UNVERIFIED_NETLIST", authoring.transform);
                Dictionary<string, Dictionary<string, string>> modelByRef = ByRef(models);
                for (int i = 0; i < placement.Count; i++)
                {
                    Dictionary<string, string> item = placement[i];
                    string id = Get(item, "ref");
                    Dictionary<string, string> modelRow = modelByRef[id];
                    string fbx = Get(modelRow, "fbx");
                    GameObject model = ResolveModel(root, fbx);
                    GameObject inventoryPrefab = EnsureInventoryArtPrefab(model, id, tempScene);
                    GameObject slot = NewChild("Slot_" + id + "_UNINSTALLED", footprints.transform);
                    Vector3 sourcePose = new Vector3(ReadFloat(Get(item,"x_m")),
                        ReadFloat(Get(modelRow,"y_m")), ReadFloat(Get(item,"z_m")));
                    slot.transform.localPosition = sourcePose;
                    SparkL101FootprintArtTarget marker = slot.AddComponent<SparkL101FootprintArtTarget>();
                    marker.referenceDesignator = id;
                    marker.modelFbx = fbx;
                    marker.originalPhysicalPositionMeters = sourcePose;
                    marker.inventoryVisualPrefab = inventoryPrefab;
                    marker.startsInstalled = false;
                    marker.hasApprovedPinMapping = false;
                }

                for (int i = 0; i < routes.Count; i++)
                {
                    Dictionary<string, string> r = routes[i];
                    GameObject task = NewChild("Route_" + Get(r,"route_id") + "_NOT_CERTIFIABLE", routesGroup.transform);
                    SparkL101UnverifiedPlanningTask entry = task.AddComponent<SparkL101UnverifiedPlanningTask>();
                    entry.sourceId = Get(r,"route_id"); entry.category = "Copper route"; entry.subsystem = Get(r,"group");
                    entry.certifiable = false;
                }
                for (int i = 0; i < vias.Count; i++)
                {
                    Dictionary<string, string> v = vias[i];
                    GameObject task = NewChild("Via_" + Get(v,"via_id") + "_NOT_CERTIFIABLE", viasGroup.transform);
                    SparkL101UnverifiedPlanningTask entry = task.AddComponent<SparkL101UnverifiedPlanningTask>();
                    entry.sourceId = Get(v,"via_id"); entry.category = "Via"; entry.subsystem = "Six-layer via";
                    entry.certifiable = false;
                }
                GameObject gameplay = NewChild("ElectricalAndGameplayIntegration_REQUIRED", main.transform);
                NewChild("SparkTerminal_AndPinMap_BLOCKED", gameplay.transform);
                NewChild("SixLayerPCBGraph_NOT_CONNECTED", gameplay.transform);
                NewChild("ExistingLevelGamePlayManager_NOT_BOUND", gameplay.transform);
                NewChild("ExistingWorldSpaceVirtualRepairUI_NOT_DUPLICATED", gameplay.transform);
                GameObject safety = NewChild("W101_CONCEPTUAL_ENDPOINTS_CONFLICT_UNRESOLVED", gameplay.transform);
                NewChild("SOURCE_SAYS_U10_LinkMonitor_BUT_BOM_U10_IS_LDO", safety.transform);
                NewChild("SOURCE_SAYS_U11_Safety_BUT_BOM_U11_IS_INTERFACE", safety.transform);
                NewChild("BOM_U7_LINK_MON_AND_U8_SAFETY_REQUIRE_REVIEW", safety.transform);
                NewChild("NO_LIVE_TERMINALS_OR_APPROVED_PIN_NUMBERS", safety.transform);
                GameObject faults = NewChild("FaultSources_NOT_INJECTED", gameplay.transform);
                NewChild("F1_InternalViaOpen", faults.transform);
                NewChild("F2_GroundReturnDiscontinuity", faults.transform);
                NewChild("F3_DifferentialPairSkew", faults.transform);
                GameObject objectives = NewChild("Objectives_0_of_6_NO_CERTIFICATION", gameplay.transform);
                string[] titles = { "01_Install76", "02_BuildRoutes100_Vias24", "03_BootMemoryPower",
                    "04_DifferentialLinkIntegrity", "05_RepairThreeFaults", "06_W101SafetyRecovery" };
                for (int i = 0; i < titles.Length; i++) NewChild(titles[i] + "_NO_EVIDENCE", objectives.transform);

                AssetDatabase.SaveAssets();
                PrefabUtility.SaveAsPrefabAsset(main, LayoutPrefab);
                if (!EditorSceneManager.SaveScene(tempScene, LayoutScene))
                    throw new IOException("Unity did not save Level_101_Layout.unity");
                WriteReport(root, bounds, models.Count, placement.Count, routes.Count, vias.Count);
                AssetDatabase.Refresh();
                succeeded = true;
            }
            catch (Exception ex)
            {
                Debug.LogError("[L101] Full-layout generation FAILED: " + ex);
            }
            finally
            {
                EditorSceneManager.CloseScene(tempScene, true);
            }
            if (succeeded)
                Debug.Log("[L101] Level_101_Layout.prefab and scene saved. 76 UNINSTALLED slots, 100 UNVERIFIED routes, 24 UNVERIFIED vias; W101 disconnected, 0/6 objectives. Geometry/PBR only; live multi-layer electrical gameplay NOT implemented. " + ReportPath);
        }

        [MenuItem(Menu + "2. Place Level 101 on SELECTED tabletop")]
        public static void PlacePreviewOnTable()
        {
            Transform table = Selection.activeTransform;
            if (table == null) { Debug.LogError("[L101] Select Table_top Transform first."); return; }
            if (AssetDatabase.LoadAssetAtPath<GameObject>(LayoutPrefab) == null)
            { Debug.LogError("[L101] Build the full layout prefab first."); return; }
            string root = FindSourceRoot();
            GameObject source = string.IsNullOrEmpty(root) ? null : ResolveModel(root, ReferenceModel);
            if (source == null) { Debug.LogError("[L101] Completed reference art not imported."); return; }
            GameObject existing = FindRootInOpenScenes(PreviewName);
            if (existing != null)
            {
                if (!EditorUtility.DisplayDialog("Replace Level 101 preview?", "An existing Level 101 tabletop art preview will be removed. This does not modify the saved gameplay level.", "Replace", "Cancel")) return;
                Undo.DestroyObjectImmediate(existing);
            }
            GameObject preview = new GameObject(PreviewName);
            Undo.RegisterCreatedObjectUndo(preview, "Create L101 tabletop ART preview");
            GameObject board = PrefabUtility.InstantiatePrefab(source) as GameObject;
            if (board == null) { Undo.DestroyObjectImmediate(preview); Debug.LogError("[L101] Could not instantiate completed reference."); return; }
            board.name = "CompletedMLX9_VISUAL_ONLY_NO_GAMEPLAY";
            board.transform.SetParent(preview.transform, false);
            board.transform.localPosition = Vector3.zero;
            board.transform.localRotation = Quaternion.identity;
            board.transform.localScale = Vector3.one;
            SparkL101URPPBRMaterialBuilder.BindAllMaterials(board);
            StripColliders(board);
            float uniformScale = Mathf.Min(TableTargetWidth / BoardWidthM, TableTargetDepth / BoardDepthM);
            preview.transform.localScale = Vector3.one * uniformScale;
            preview.transform.SetPositionAndRotation(table.position, Quaternion.Euler(0f, table.eulerAngles.y, 0f));
            SparkL101PreviewArtOnly marker = preview.AddComponent<SparkL101PreviewArtOnly>();
            marker.displayScale = uniformScale;
            float surfaceY = table.position.y;
            Collider directCollider = table.GetComponent<Collider>();
            Renderer directRenderer = table.GetComponent<Renderer>();
            if (directCollider != null) surfaceY = directCollider.bounds.max.y;
            else if (directRenderer != null) surfaceY = directRenderer.bounds.max.y;
            Bounds bounds;
            if (TryGetBounds(board, out bounds))
                preview.transform.position += Vector3.up * (surfaceY + 0.005f - bounds.min.y);
            Selection.activeGameObject = preview;
            Debug.Log("[L101] Created completed-board VISUAL-ONLY preview. Physical PCB 0.230x0.160m; display about 10.13 x 7.05 Unity units; uniform scale " + uniformScale.ToString("F3") + ". No electrical/gameplay authority in preview.");
        }

        [MenuItem(Menu + "3. Validate Source and 3D Models")]
        public static void ValidateSourceInUnity()
        {
            string root = FindSourceRoot();
            if (root == null) { Debug.LogError("[L101] Source missing/ambiguous."); return; }
            var m = ReadCsv(root + "/Data/Asset_Manifest_96.csv");
            var b = ReadCsv(root + "/Data/Component_BOM_76.csv");
            var p = ReadCsv(root + "/Data/Component_BOM_76.csv");
            var r = ReadCsv(root + "/Data/Copper_Routes_100_UNVERIFIED.csv");
            var v = ReadCsv(root + "/Data/Vias_24_UNVERIFIED.csv");
            bool valid = ValidateData(root, m, b, p, r, v, true);
            Debug.Log("[L101] Source validation " + (valid ? "OK" : "FAILED") + ": 96 modular models, 76 source parts, 100 unverified routes, 24 unverified vias. ELECTRICAL STATUS=BLOCKED_UNVERIFIED_NETLIST; Unity Play Mode, power and objectives still untested.");
        }

        public static string FindSourceRoot()
        {
            string found = null;
            foreach (string guid in AssetDatabase.FindAssets("Asset_Manifest_96"))
            {
                string path = AssetDatabase.GUIDToAssetPath(guid).Replace('\\','/');
                string suffix = "/Data/Asset_Manifest_96.csv";
                if (!path.EndsWith(suffix, StringComparison.OrdinalIgnoreCase)) continue;
                string candidate = path.Substring(0, path.Length - suffix.Length);
                if (candidate.IndexOf("Level101", StringComparison.OrdinalIgnoreCase) < 0 &&
                    candidate.IndexOf("L101", StringComparison.OrdinalIgnoreCase) < 0) continue;
                if (found != null && !found.Equals(candidate, StringComparison.OrdinalIgnoreCase)) return null;
                found = candidate;
            }
            return found;
        }

        private static bool ValidateData(string root, List<Dictionary<string,string>> models,
            List<Dictionary<string,string>> bom, List<Dictionary<string,string>> positions,
            List<Dictionary<string,string>> routes, List<Dictionary<string,string>> vias, bool verifyImportedMeshes)
        {
            if (models.Count != ModelsExpected || bom.Count != PartsExpected || positions.Count != PartsExpected ||
                routes.Count != RoutesExpected || vias.Count != ViasExpected)
            {
                Debug.LogError("[L101] Counts do not match source: models=" + models.Count +
                    " BOM=" + bom.Count + " placements=" + positions.Count +
                    " routes=" + routes.Count + " vias=" + vias.Count);
                return false;
            }
            HashSet<string> installed = new HashSet<string>(StringComparer.Ordinal);
            for (int i = 0; i < PartsExpected; i++)
            {
                Dictionary<string,string> source = models[i];
                Dictionary<string,string> part = positions[i];
                string id = Get(source,"ref");
                if (id.Length == 0 || !installed.Add(id) || Get(part,"ref") != id ||
                    Get(source,"installable") != "true" || Get(part,"install_state") != "MISSING")
                { Debug.LogError("[L101] Invalid BOM/asset identity or starting state at row " + i); return false; }
                if (Mathf.Abs(ReadFloat(Get(source,"x_m")) - ReadFloat(Get(part,"x_m"))) > .00001f ||
                    Mathf.Abs(ReadFloat(Get(source,"z_m")) - ReadFloat(Get(part,"z_m"))) > .00001f)
                { Debug.LogError("[L101] BOM and visual placement conflict for " + id); return false; }
            }
            var bomRefs = new HashSet<string>(StringComparer.Ordinal);
            foreach (var part in bom) if (!bomRefs.Add(Get(part,"ref"))) return false;
            if (!bomRefs.SetEquals(installed) || !installed.Contains("W101"))
            { Debug.LogError("[L101] 76-part BOM or W101 identity mismatch"); return false; }
            for (int i = PartsExpected; i < models.Count; i++)
                if (Get(models[i],"installable") != "false")
                { Debug.LogError("[L101] Board art incorrectly marked installable at " + i); return false; }
            for (int i=0;i<routes.Count;i++)
            {
                var row = routes[i];
                if (Get(row,"route_id") != "W"+(i+1).ToString("000",CultureInfo.InvariantCulture) ||
                    Get(row,"source_pad") != "UNASSIGNED" || Get(row,"destination_pad") != "UNASSIGNED" ||
                    Get(row,"net_id") != "UNASSIGNED" || Get(row,"requires_schematic") != "YES" ||
                    Get(row,"status") != "MISSING")
                { Debug.LogError("[L101] Missing or unexpectedly altered route: " + Get(row,"route_id")); return false; }
            }
            for (int i=0;i<vias.Count;i++)
            {
                var row = vias[i];
                if (Get(row,"via_id") != "V"+(i+1).ToString("00",CultureInfo.InvariantCulture) ||
                    Get(row,"net_id") != "UNASSIGNED" || Get(row,"from_layer") != "UNASSIGNED" ||
                    Get(row,"to_layer") != "UNASSIGNED" || Get(row,"requires_schematic") != "YES" ||
                    Get(row,"status") != "MISSING")
                { Debug.LogError("[L101] Missing or unexpectedly altered via: " + Get(row,"via_id")); return false; }
            }
            if (!File.Exists(ToAbsolute(root + "/Data/Critical_W101.json")))
            { Debug.LogError("[L101] W101 source contract missing"); return false; }
            if (!verifyImportedMeshes) return true;
            foreach (var row in models)
            {
                string fbx = Get(row,"fbx");
                string glb = Get(row,"glb");
                if (!File.Exists(ToAbsolute(root+"/Models_FBX/"+fbx)) ||
                    !File.Exists(ToAbsolute(root+"/Models_GLB/"+glb)) || ResolveModel(root,fbx)==null)
                { Debug.LogError("[L101] Missing source or Unity-renderable fallback: " + fbx);return false; }
            }
            if (ResolveModel(root, ReferenceModel)==null)
            { Debug.LogError("[L101] Assembled reference fallback missing/unrenderable");return false; }
            return true;
        }

        private static SparkL101SourceBlueprint CreateOrUpdateBlueprint(List<Dictionary<string,string>> models,
            List<Dictionary<string,string>> bom, List<Dictionary<string,string>> placements,
            List<Dictionary<string,string>> routes, List<Dictionary<string,string>> vias)
        {
            SparkL101SourceBlueprint blueprint = AssetDatabase.LoadAssetAtPath<SparkL101SourceBlueprint>(BlueprintPath);
            if (blueprint == null)
            {
                blueprint = ScriptableObject.CreateInstance<SparkL101SourceBlueprint>();
                AssetDatabase.CreateAsset(blueprint,BlueprintPath);
            }
            blueprint.electricalStatus = SparkL101SourceBlueprint.UnverifiedStatus;
            blueprint.certifiedObjectives = 0;
            blueprint.components.Clear(); blueprint.routes.Clear(); blueprint.vias.Clear();
            var indexedModels=ByRef(models);
            foreach (var part in placements)
            {
                string id=Get(part,"ref"); var model=indexedModels[id];
                blueprint.components.Add(new SparkL101ComponentRecord
                {
                    referenceDesignator=id,kind=Get(part,"kind"),variant=Get(part,"variant"),
                    sourceFbx=Get(model,"fbx"),
                    physicalPositionMeters=new Vector3(ReadFloat(Get(part,"x_m")),
                        ReadFloat(Get(model,"y_m")),ReadFloat(Get(part,"z_m"))),
                    startsInstalled=false, hasApprovedElectricalFootprint=false
                });
            }
            foreach (var row in routes)
                blueprint.routes.Add(new SparkL101CopperTaskRecord
                {
                    id=Get(row,"route_id"), subsystem=Get(row,"group"),
                    sourcePad=Get(row,"source_pad"), destinationPad=Get(row,"destination_pad"),
                    netId=Get(row,"net_id"), certifiable=false, startsComplete=false
                });
            foreach (var row in vias)
                blueprint.vias.Add(new SparkL101ViaTaskRecord
                {
                    id=Get(row,"via_id"), netId=Get(row,"net_id"),
                    fromLayer=Get(row,"from_layer"),toLayer=Get(row,"to_layer"),
                    physicalPositionMeters=new Vector3(ReadFloat(Get(row,"x_m")),0,
                        ReadFloat(Get(row,"z_m"))), certifiable=false, startsInstalled=false
                });
            EditorUtility.SetDirty(blueprint);
            return blueprint;
        }

        private static GameObject ResolveModel(string root, string fbxName)
        {
            string stem = Path.GetFileNameWithoutExtension(fbxName);
            // L101's original FBX vertices are centimetres. Prefer correctly oriented GLB-derived
            // metre OBJ; do not accidentally accept a visible but 100x-too-big FBX.
            GameObject fallback = AssetDatabase.LoadAssetAtPath<GameObject>(root + "/Models_OBJ_Fallback/" + stem + ".obj");
            return HasMesh(fallback) ? fallback : null;
        }
        private static bool HasMesh(GameObject source)
        {
            if (source == null) return false;
            MeshFilter[] filters = source.GetComponentsInChildren<MeshFilter>(true);
            for (int i=0;i<filters.Length;i++)
                if (filters[i].sharedMesh != null && filters[i].sharedMesh.vertexCount > 2) return true;
            return false;
        }
        private static GameObject SpawnArt(GameObject source, string name, Transform parent, Scene scene)
        {
            GameObject child = PrefabUtility.InstantiatePrefab(source, scene) as GameObject;
            if (child == null) return null;
            child.name = name;
            child.transform.SetParent(parent, false);
            child.transform.localPosition = Vector3.zero;
            child.transform.localRotation = Quaternion.identity;
            child.transform.localScale = Vector3.one;
            SparkL101URPPBRMaterialBuilder.BindAllMaterials(child);
            StripColliders(child);
            return child;
        }
        private static GameObject EnsureInventoryArtPrefab(GameObject source, string refdes, Scene scene)
        {
            if (source == null) throw new InvalidOperationException("Missing source 3D model for " + refdes);
            GameObject container = NewRootInScene("L101_" + refdes + "_VisualOnly", scene);
            try
            {
                GameObject model = SpawnArt(source, "SourceMesh_Metres", container.transform, scene);
                if (model == null) throw new InvalidOperationException("Source model cannot instantiate: " + refdes);
                string path = Generated + "/ComponentVisualPrefabs/L101_" + refdes + "_Visual.prefab";
                GameObject saved = PrefabUtility.SaveAsPrefabAsset(container, path);
                if (saved == null) throw new IOException("Visual prefab asset did not save: " + path);
                return saved;
            }
            finally { UnityEngine.Object.DestroyImmediate(container); }
        }
        private static void StripColliders(GameObject go)
        {
            Collider[] colliders = go.GetComponentsInChildren<Collider>(true);
            for (int i = 0; i < colliders.Length; i++) UnityEngine.Object.DestroyImmediate(colliders[i]);
        }
        private static bool TryGetBounds(GameObject root, out Bounds value)
        {
            value = new Bounds(root.transform.position, Vector3.zero);
            bool found = false;
            Renderer[] renderers = root.GetComponentsInChildren<Renderer>(true);
            for (int i = 0; i < renderers.Length; i++)
            {
                if (!renderers[i].gameObject.activeInHierarchy) continue;
                if (!found) { value=renderers[i].bounds; found=true; }
                else value.Encapsulate(renderers[i].bounds);
            }
            return found;
        }
        private static GameObject NewRootInScene(string name, Scene scene)
        {
            GameObject result = new GameObject(name);
            SceneManager.MoveGameObjectToScene(result, scene);
            return result;
        }
        private static GameObject NewChild(string name, Transform parent)
        {
            GameObject child = new GameObject(name);
            child.transform.SetParent(parent, false);
            return child;
        }
        private static GameObject FindRootInOpenScenes(string name)
        {
            for (int i = 0; i < SceneManager.sceneCount; i++)
            {
                Scene scene = SceneManager.GetSceneAt(i);
                if (!scene.isLoaded) continue;
                foreach (GameObject root in scene.GetRootGameObjects())
                    if (root.name == name) return root;
            }
            return null;
        }
        private static Dictionary<string,Dictionary<string,string>> ByRef(List<Dictionary<string,string>> source)
        {
            var found = new Dictionary<string,Dictionary<string,string>>(StringComparer.Ordinal);
            foreach (var entry in source) { string key=Get(entry,"ref"); if (key.Length>0) found.Add(key,entry); }
            return found;
        }
        private static void WriteReport(string source, Bounds boardBounds, int models, int parts, int routes, int vias)
        {
