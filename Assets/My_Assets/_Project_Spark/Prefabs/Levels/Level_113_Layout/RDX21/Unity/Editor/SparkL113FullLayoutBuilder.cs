        public static string FindSourceRoot()
        {
            string found = null;
            foreach (string guid in AssetDatabase.FindAssets("L113_ModelManifest"))
            {
                string p = AssetDatabase.GUIDToAssetPath(guid).Replace('\\', '/');
                if (!p.EndsWith("/Data/L113_ModelManifest.csv", StringComparison.OrdinalIgnoreCase)) continue;
                string root = Path.GetDirectoryName(Path.GetDirectoryName(p)).Replace('\\', '/');
                if (found != null && !string.Equals(root, found, StringComparison.OrdinalIgnoreCase))
                {
                    Debug.LogError("[L113] Multiple Level113 source kits found. Remove duplicate copies to protect source GUIDs.");
                    return null;
                }
                found = root;
            }
            if (found == null) Debug.LogError("[L113] Data/L113_ModelManifest.csv missing from imported Level113 source kit.");
            return found;
        }

        private static bool ValidateSource(string source, bool log)
        {
            string[] files = { "L113_ModelManifest.csv", "L113_ComponentBOM.csv", "L113_ComponentPlacements.csv",
                "L113_CopperRoutes_232_SCHEMATIC_REQUIRED.csv", "L113_ViaTasks_76_SCHEMATIC_REQUIRED.csv" };
            int[] expected = { 206, 166, 166, 232, 76 };
            for (int i = 0; i < files.Length; ++i)
            {
                string file = source + "/Data/" + files[i];
                if (!File.Exists(ToAbsolute(file))) { Debug.LogError("[L113] Missing " + file); return false; }
                List<string[]> rows = ReadCsv(file);
                if (rows.Count != expected[i])
                {
                    Debug.LogError("[L113] " + files[i] + ": expected " + expected[i] + " records, found " + rows.Count);
                    return false;
                }
            }
            List<string[]> models = ReadCsv(source + "/Data/L113_ModelManifest.csv");
            for (int i = 0; i < models.Count; ++i)
            {
                string obj = source + "/Models_OBJ/" + models[i][6];
                if (!File.Exists(ToAbsolute(obj))) { Debug.LogError("[L113] Missing OBJ " + obj); return false; }
            }
            if (!File.Exists(ToAbsolute(source + "/Models_OBJ/207_L113_AssembledReference.obj")))
            {
                Debug.LogError("[L113] Assembled art source missing."); return false;
            }
            if (log)
                Debug.LogWarning("[L113] ART SOURCE VALIDATED OFFLINE COUNTS. ELECTRICAL SCHEMATIC REQUIRED: 232 routes, " +
                    "76 vias, W233 pin endpoints. No certification, no solver integration, no Play Mode claim.");
            return true;
        }

        private static GameObject InstantiateModel(string source, string objName, Transform parent, string name)
        {
            return InstantiateAssetAtPath(source + "/Models_OBJ/" + objName, parent, name);
        }

        private static GameObject InstantiateAssetAtPath(string path, Transform parent, string childName)
        {
            GameObject asset = AssetDatabase.LoadAssetAtPath<GameObject>(path);
            if (!asset) { Debug.LogError("[L113] Failed to load OBJ model asset " + path); return null; }
            GameObject result = PrefabUtility.InstantiatePrefab(asset) as GameObject;
            if (!result) { Debug.LogError("[L113] Failed to instantiate model " + path); return null; }
            result.transform.SetParent(parent, false);
            result.name = childName;
            SparkL113URPMaterialBuilder.Bind(result);
            DisableColliders(result);
            return result;
        }

        private static GameObject Child(Transform parent, string name)
        {
            GameObject go = new GameObject(name);
            go.transform.SetParent(parent, false);
            return go;
        }

        private static void DisableColliders(GameObject root)
        {
            Collider[] all = root.GetComponentsInChildren<Collider>(true);
            for (int i = 0; i < all.Length; ++i) all[i].enabled = false;
        }

        private static bool TryBounds(GameObject root, out Bounds bounds)
        {
            Renderer[] renders = root.GetComponentsInChildren<Renderer>(true);
            bool seen = false;
            bounds = new Bounds(root.transform.position, Vector3.zero);
            for (int i = 0; i < renders.Length; ++i)
            {
                if (!seen) { bounds = renders[i].bounds; seen = true; }
                else bounds.Encapsulate(renders[i].bounds);
            }
            return seen && bounds.size.sqrMagnitude > 0.000000001f;
        }

        // Source CSV rows may contain quoted commas (notably J1-J8 in the model manifest).
                // Parse a CSV row without splitting commas inside quoted descriptions.
        // Handles doubled quote escapes and empty trailing fields.
        private static string[] ParseCsvFields(string line)
        {
            List<string> fields = new List<string>(16);
            System.Text.StringBuilder field = new System.Text.StringBuilder(line.Length);
            bool inQuotes = false;
            for (int i = 0; i < line.Length; ++i)
            {
                char c = line[i];
                if (c == '"')
                {
                    if (inQuotes && i + 1 < line.Length && line[i + 1] == '"')
                    {
                        field.Append('"');
                        ++i;
                    }
                    else
                    {
                        inQuotes = !inQuotes;
                    }
                }
                else if (c == ',' && !inQuotes)
                {
                    fields.Add(field.ToString());
                    field.Length = 0;
                }
                else
                {
                    field.Append(c);
                }
            }
            if (inQuotes)
                throw new FormatException("Unclosed quoted CSV field.");
            fields.Add(field.ToString());
            return fields.ToArray();
        }
        internal static List<string[]> ReadCsv(string assetPath)
        {
            string[] lines = File.ReadAllLines(ToAbsolute(assetPath));
            List<string[]> result = new List<string[]>(lines.Length);
            for (int i = 1; i < lines.Length; ++i)
            {
                if (string.IsNullOrWhiteSpace(lines[i])) continue;
                result.Add(ParseCsvFields(lines[i]));
            }
            return result;
        }

        private static float F(string n) { return float.Parse(n, NumberStyles.Float, Format); }
        private static string SafeName(string value) { return value.Replace('/', '_').Replace(' ', '_'); }
        private static void EnsureDirectory(string assetFolder)
        {
            Directory.CreateDirectory(ToAbsolute(assetFolder));
        }
        private static string ToAbsolute(string assetPath)
        {
            string projectRoot = Directory.GetParent(Application.dataPath).FullName;
            return Path.Combine(projectRoot, assetPath.Replace('/', Path.DirectorySeparatorChar));
        }
