        private const string Menu = "Tools/Project Spark/Automatic Level Generator/113/";
        private const string Output = "Assets/ProjectSpark/AutoGeneratedLevels/Level113";
        private const string RootName = "L113_RDX21_REDUNDANCY_CITADEL";
        private const float PhysicalWidth = 0.380f;
        private const float PhysicalDepth = 0.270f;
        private const float PreviewWidth = 10.13f;
        private const float PreviewMaxDepth = 7.4f;
        private static readonly CultureInfo Format = CultureInfo.InvariantCulture;

        [MenuItem(Menu + "1. Build isolated RDX-21 visual reference")]
        public static void BuildFull()
        {
            string source = FindSourceRoot();
            if (string.IsNullOrEmpty(source)) return;
            if (!ValidateSource(source, true)) return;
            if (!SparkL113URPMaterialBuilder.Build(source)) return;
            EnsureDirectory(Output);
            EnsureDirectory(Output + "/ComponentVisualPrefabs");
            AssetDatabase.Refresh();

            List<string[]> rows = ReadCsv(source + "/Data/L113_ModelManifest.csv");
            List<string[]> bom = ReadCsv(source + "/Data/L113_ComponentBOM.csv");
            List<string[]> placement = ReadCsv(source + "/Data/L113_ComponentPlacements.csv");
            List<string[]> routes = ReadCsv(source + "/Data/L113_CopperRoutes_232_SCHEMATIC_REQUIRED.csv");
            List<string[]> vias = ReadCsv(source + "/Data/L113_ViaTasks_76_SCHEMATIC_REQUIRED.csv");

            Dictionary<string, string[]> models = new Dictionary<string, string[]>(StringComparer.OrdinalIgnoreCase);
            for (int i = 0; i < rows.Count; ++i) models[rows[i][1]] = rows[i];
            Dictionary<string, string[]> components = new Dictionary<string, string[]>(StringComparer.OrdinalIgnoreCase);
            for (int i = 0; i < bom.Count; ++i) components[bom[i][0]] = bom[i];

            // Guard existing unsaved Project Spark editor scene changes before opening an isolated scene.
            if (!EditorSceneManager.SaveCurrentModifiedScenesIfUserWantsTo())
            {
                Debug.LogWarning("[L113] Build cancelled to preserve unsaved scene changes.");
                return;
            }
            // New isolated scene; no existing Project Spark scene or previously generated level is changed.
            Scene scene = EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Single);
            GameObject root = new GameObject(RootName);
            root.AddComponent<SparkL113LayoutMarker>();
            GameObject art = Child(root.transform, "ArtRoot");
            GameObject playableBoard = Child(art.transform, "EmptyPCBPhysicalMetres");
            string boardAssetId = "PCB_Main";
            string[] boardManifest;
            if (!models.TryGetValue(boardAssetId, out boardManifest))
            {
                Debug.LogError("[L113] PCB_Main missing from model manifest.");
                UnityEngine.Object.DestroyImmediate(root);
                return;
            }
            GameObject board = InstantiateModel(source, boardManifest[6], playableBoard.transform, "PCB_Main_Physical_380x270mm");
            if (!board)
            {
                UnityEngine.Object.DestroyImmediate(root);
                return;
            }
            Bounds bounds;
            if (!TryBounds(board, out bounds) ||
                Mathf.Abs(bounds.size.x - PhysicalWidth) > 0.0025f ||
                Mathf.Abs(bounds.size.z - PhysicalDepth) > 0.0025f)
            {
                Debug.LogError("[L113] PCB import geometry mismatch. Measured " + bounds.size +
                    ", expected X=0.380, Z=0.270 metres. Check OBJ import scale; build aborted.");
                UnityEngine.Object.DestroyImmediate(root);
                return;
            }
            GameObject layers = Child(art.transform, "18LayerInspectionArtwork_DISABLED");
            GameObject structural = Child(art.transform, "OtherFactoryOnlyArtwork_DISABLED");
            for (int i = 0; i < rows.Count; ++i)
            {
                if (rows[i][11].Equals("True", StringComparison.OrdinalIgnoreCase)) continue;
                if (rows[i][1] == "PCB_Main") continue;
                Transform parent = rows[i][3] == "layer" ? layers.transform : structural.transform;
                GameObject obj = InstantiateModel(source, rows[i][6], parent, "VISUAL_ONLY_" + rows[i][1]);
                if (obj) obj.AddComponent<SparkL113VisualOnly>();
            }
            layers.SetActive(false);
            structural.SetActive(false);

            GameObject gameplay = Child(root.transform, "GameplayAuthoringRoot");
            GameObject slots = Child(gameplay.transform, "166_UninstalledComponentTargets");
            GameObject routesRoot = Child(gameplay.transform, "232_RouteRecords_SCHEMATIC_REQUIRED");
            GameObject viasRoot = Child(gameplay.transform, "76_ViaRecords_SCHEMATIC_REQUIRED");
            GameObject inventory = Child(gameplay.transform, "InventoryPrefabDefinitions_REFERENCE_ONLY");
            inventory.AddComponent<SparkL113VisualOnly>();
            // Inventory prefabs are stored as assets; installing them is reserved to existing shop/placement authority.
            for (int i = 0; i < placement.Count; ++i)
            {
                string reference = placement[i][0];
                string[] bomItem;
                string[] asset;
                if (!components.TryGetValue(reference, out bomItem) ||
                    !models.TryGetValue("L113_" + reference, out asset))
                {
                    Debug.LogError("[L113] Missing join for component " + reference);
                    UnityEngine.Object.DestroyImmediate(root);
                    return;
                }
                float x = F(placement[i][2]);
                float y = F(placement[i][3]);
                float z = F(placement[i][4]);
                GameObject slot = Child(slots.transform, "SLOT_" + reference);
                slot.transform.localPosition = new Vector3(x, y, z);
                SparkL113PlacementSlot record = slot.AddComponent<SparkL113PlacementSlot>();
                record.Configure(reference, bomItem[1], asset[1]);
                BoxCollider hit = slot.AddComponent<BoxCollider>();
                hit.isTrigger = true;
                bool large = reference.StartsWith("U", StringComparison.OrdinalIgnoreCase) ||
                             reference.StartsWith("J", StringComparison.OrdinalIgnoreCase);
                hit.size = large ? new Vector3(0.013f, 0.003f, 0.012f) :
                                   new Vector3(0.0075f, 0.002f, 0.006f);
                hit.center = new Vector3(0f, 0.0008f, 0f);

                string prefabPath = Output + "/ComponentVisualPrefabs/L113_" + reference + ".prefab";
                GameObject temporary = InstantiateModel(source, asset[6], inventory.transform, "L113_" + reference + "_VisualOnly");
                if (!temporary) { UnityEngine.Object.DestroyImmediate(root); return; }
                temporary.AddComponent<SparkL113VisualOnly>();
                temporary.transform.localPosition = Vector3.zero;
                temporary.transform.localRotation = Quaternion.identity;
                PrefabUtility.SaveAsPrefabAsset(temporary, prefabPath);
                UnityEngine.Object.DestroyImmediate(temporary);
            }
            for (int i = 0; i < routes.Count; ++i)
            {
                GameObject obj = Child(routesRoot.transform, routes[i][0] + "_" + SafeName(routes[i][1]));
                obj.AddComponent<SparkL113BlockedTask>().Configure(SparkL113TaskType.CopperRoute, routes[i][0], routes[i][1]);
            }
            for (int i = 0; i < vias.Count; ++i)
            {
                GameObject obj = Child(viasRoot.transform, vias[i][0] + "_BLOCKED");
                obj.AddComponent<SparkL113BlockedTask>().Configure(SparkL113TaskType.Via, vias[i][0], "18 layer unknown span");
            }
            GameObject integration = Child(root.transform, "ProjectSparkIntegrationContracts_UNBOUND");
            string[] services = {
                "SparkCircuitSystem / SparkElectricalNetworkGraph", "SparkTerminal / approved footprint pins",
                "LevelGamePlayManager / objective authority", "WorldSpacePCBVirtualStudio / tool raycast routing",
                "Existing shop and component placement", "W233 independent failover authorization monitor",
                "Redundant power domains / ECC / failover and independent safety", "Save and load with evidence epochs"
            };
            foreach (string service in services)
                Child(integration.transform, SafeName(service)).AddComponent<SparkL113IntegrationAnchor>().Configure(service);
            GameObject demo = Child(root.transform, "OPTIONAL_EducationalResilienceDemo_NONCERTIFIABLE");
            demo.AddComponent<SparkL113ResilienceSandbox>();
            GameObject refRoot = Child(root.transform, "AssembledShowcaseReference_DISABLED_NEVER_GAMEPLAY");
            string showcasePath = source + "/Models_OBJ/207_L113_AssembledReference.obj";
            GameObject assembled = InstantiateAssetAtPath(showcasePath, refRoot.transform, "VisualShowcase_ONLY");
            if (assembled) assembled.AddComponent<SparkL113VisualOnly>();
            refRoot.AddComponent<SparkL113VisualOnly>();
            refRoot.SetActive(false);

            string prefabOutput = Output + "/Level_113_Layout.prefab";
            PrefabUtility.SaveAsPrefabAsset(root, prefabOutput);
            EditorSceneManager.SaveScene(scene, Output + "/Level_113_Layout.unity");
            AssetDatabase.SaveAssets();
            WriteAudit(Output + "/L113_Layout_Validation.txt", rows.Count, placement.Count, routes.Count, vias.Count);
            Selection.activeGameObject = root;
            Debug.Log("[L113] Visual layout authored. 166/166 UNINSTALLED, 232/232 ROUTES BLOCKED, " +
                "76/76 VIAS BLOCKED, W233 DISCONNECTED, 0/6 objectives. NOT ELECTRICALLY CERTIFIABLE.");
        }

        [MenuItem(Menu + "2. Place assembled VISUAL preview on SELECTED tabletop")]
        public static void PlacePreviewOnTable()
        {
            GameObject table = Selection.activeGameObject;
            if (!table)
            {
                Debug.LogError("[L113] Select existing tabletop or Table_top transform first.");
                return;
            }
            if (table.GetComponentInParent<SparkL113LayoutMarker>() != null)
            {
                Debug.LogError("[L113] Please select a tabletop, not a Level 113 sub-object.");
                return;
            }
            string source = FindSourceRoot();
            if (string.IsNullOrEmpty(source)) return;
            string previewAssetPath = source + "/Models_OBJ/207_L113_AssembledReference.obj";
            GameObject imported = AssetDatabase.LoadAssetAtPath<GameObject>(previewAssetPath);
            if (!imported) { Debug.LogError("[L113] Assembled OBJ not imported. " + previewAssetPath); return; }
            GameObject root = new GameObject("L113_RDX21_VisualPreview_ONLY");
            Undo.RegisterCreatedObjectUndo(root, "Place Level 113 visual preview");
            root.AddComponent<SparkL113VisualOnly>();
            Bounds tableBounds;
            bool boundedTable = TryBounds(table, out tableBounds);
            Vector3 topPoint = boundedTable ? new Vector3(tableBounds.center.x, tableBounds.max.y, tableBounds.center.z) : table.transform.position;
            root.transform.position = topPoint + Vector3.up * 0.010f;
            root.transform.rotation = table.transform.rotation;
            GameObject visual = (GameObject)PrefabUtility.InstantiatePrefab(imported);
            if (!visual) { UnityEngine.Object.DestroyImmediate(root); return; }
            visual.transform.SetParent(root.transform, false);
            visual.transform.localPosition = Vector3.zero;
            float scale = Mathf.Min(PreviewWidth / PhysicalWidth, PreviewMaxDepth / PhysicalDepth);
            visual.transform.localScale = Vector3.one * scale;
            SparkL113URPMaterialBuilder.Bind(visual);
            visual.AddComponent<SparkL113VisualOnly>();
            DisableColliders(visual);
            Selection.activeGameObject = root;
            Debug.Log("[L113] Preview size " + (scale * PhysicalWidth).ToString("0.###", Format) +
                " x " + (scale * PhysicalDepth).ToString("0.###", Format) +
                " table units. VISUAL ONLY - physical PCB stays 0.380 x 0.270m.");
        }

