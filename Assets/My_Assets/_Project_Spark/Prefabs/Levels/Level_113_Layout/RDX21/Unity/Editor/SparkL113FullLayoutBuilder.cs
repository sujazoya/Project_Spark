        {
            string body = "PROJECT SPARK / LEVEL 113 / RDX-21 / THE REDUNDANCY CITADEL\n" +
                "ART SOURCE = " + models + " model entries\n" +
                "PLACEMENT TARGETS = " + components + " (ALL UNINSTALLED)\n" +
                "ROUTE TASKS = " + routes + " (ALL UNASSIGNED / NOT CERTIFIABLE)\n" +
                "VIA TASKS = " + vias + " (ALL UNASSIGNED / NOT CERTIFIABLE)\n" +
                "LAYER COUNT = 18 visual reference layers\n" +
                "W233 = DISCONNECTED; PHYSICAL SOURCE / DEST PINS UNVERIFIED\n" +
                "OBJECTIVES = 0/6; NO AUTHORITATIVE AWARDS\n" +
                "GAMEPLAY API / BOARD NETLIST / FABRICATED DATA = NOT ASSUMED\n" +
                "RENDER QUALITY / PLAY MODE / UNITY COMPILER = NOT TESTED\n";
            File.WriteAllText(ToAbsolute(assetFile), body);
            AssetDatabase.Refresh();
        }
