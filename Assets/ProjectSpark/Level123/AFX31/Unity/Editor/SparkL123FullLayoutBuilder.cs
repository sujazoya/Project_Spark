            string[] zoneNames = {
                "FlightComputer_A_UNBOUND", "FlightComputer_B_UNBOUND",
                "FlightSafetySupervisor_UNBOUND", "IMU_TripleVoter_UNBOUND",
                "BarometerAltitude_UNBOUND", "MotorStage5_GateDrive_UNBOUND",
                "EightMotorMixing_UNBOUND", "W401_FLIGHT_READY_OPEN"
