            GameObject targets = Child(authoring.transform, "312_UninstalledComponentTargets");
            GameObject routes = Child(authoring.transform, "400_Routes_UNASSIGNED_BLOCKED");
            GameObject vias = Child(authoring.transform, "156_Vias_UNASSIGNED_BLOCKED");
