#if UNITY_EDITOR
using System;
using System.Collections.Generic;
using System.IO;
using UnityEditor;
using UnityEngine;

namespace ProjectSpark.Level113.Editor
{
    public static class SparkL113URPMaterialBuilder
    {
        public const string Output = "Assets/ProjectSpark/AutoGeneratedLevels/Level113/URP_PBR_Materials";
        private static readonly Dictionary<string, Material> Cache =
            new Dictionary<string, Material>(StringComparer.OrdinalIgnoreCase);

        [MenuItem("Tools/Project Spark/Automatic Level Generator/113/4. Rebuild URP Materials")]
        public static void Rebuild()
        {
            string root = SparkL113FullLayoutBuilder.FindSourceRoot();
            if (string.IsNullOrEmpty(root)) return;
            if (Build(root)) Debug.Log("[L113] 24 URP PBR families imported; generated assets are editable.");
        }

        public static bool Build(string sourceRoot)
        {
            Shader shader = Shader.Find("Universal Render Pipeline/Lit");
            if (shader == null)
            {
                Debug.LogError("[L113] URP Lit shader unavailable. Activate URP; no false material success.");
                return false;
            }
            Cache.Clear();
            string textures = sourceRoot + "/Textures";
            string folder = Absolute(textures);
            if (!Directory.Exists(folder)) { Debug.LogError("[L113] Missing texture folder: " + textures); return false; }
            string[] maps = Directory.GetFiles(folder, "*_BaseColor.png", SearchOption.TopDirectoryOnly);
            if (maps.Length != 24)
            {
                Debug.LogError("[L113] Expected 24 BaseColor textures; found " + maps.Length);
                return false;
            }
            Array.Sort(maps, StringComparer.Ordinal);
            Directory.CreateDirectory(Absolute(Output));
            AssetDatabase.Refresh();
            for (int i = 0; i < maps.Length; ++i)
            {
                string fileName = Path.GetFileName(maps[i]);
                string family = fileName.Substring(0, fileName.Length - "_BaseColor.png".Length);
                string diffusePath = textures + "/" + family + "_BaseColor.png";
                string normalPath = textures + "/" + family + "_Normal.png";
                string maskPath = sourceRoot + "/URP_Packed/" + family + "_URP_MetallicSmoothness.png";
                string aoPath = textures + "/" + family + "_AO.png";
                if (!File.Exists(Absolute(normalPath)) || !File.Exists(Absolute(maskPath)) || !File.Exists(Absolute(aoPath)))
                {
                    Debug.LogError("[L113] Missing complete PBR maps for " + family);
                    return false;
                }
                Configure(diffusePath, false, true);
                Configure(maskPath, false, false);
                Configure(normalPath, true, false);
                Configure(aoPath, false, false);
                Texture2D diffuse = AssetDatabase.LoadAssetAtPath<Texture2D>(diffusePath);
                Texture2D normal = AssetDatabase.LoadAssetAtPath<Texture2D>(normalPath);
                Texture2D mask = AssetDatabase.LoadAssetAtPath<Texture2D>(maskPath);
                Texture2D ao = AssetDatabase.LoadAssetAtPath<Texture2D>(aoPath);
                if (!diffuse || !normal || !mask || !ao)
                {
                    Debug.LogError("[L113] Texture import failed for " + family);
                    return false;
                }
                string materialPath = Output + "/L113_" + family + ".mat";
                Material mat = AssetDatabase.LoadAssetAtPath<Material>(materialPath);
                if (mat == null)
                {
                    mat = new Material(shader);
                    mat.name = "L113_" + family;
                    AssetDatabase.CreateAsset(mat, materialPath);
                }
                else if (mat.shader != shader) mat.shader = shader;
                mat.SetTexture("_BaseMap", diffuse);
                mat.SetColor("_BaseColor", Color.white);
                mat.SetTexture("_MetallicGlossMap", mask);
                mat.SetFloat("_Metallic", 1f);
                mat.SetFloat("_Smoothness", 1f);
                mat.EnableKeyword("_METALLICSPECGLOSSMAP");
                mat.SetTexture("_BumpMap", normal);
                mat.EnableKeyword("_NORMALMAP");
                mat.SetTexture("_OcclusionMap", ao);
                mat.SetFloat("_OcclusionStrength", 1f);
                mat.enableInstancing = true;
                EditorUtility.SetDirty(mat);
                Cache[family] = mat;
            }
            AssetDatabase.SaveAssets();
            return Cache.Count == 24;
        }

        private static void Configure(string path, bool normalMap, bool sRGB)
        {
            TextureImporter importer = AssetImporter.GetAtPath(path) as TextureImporter;
            if (importer == null) return;
            TextureImporterType textureType = normalMap ? TextureImporterType.NormalMap : TextureImporterType.Default;
            if (importer.textureType == textureType && importer.sRGBTexture == sRGB) return;
            importer.textureType = textureType;
            importer.sRGBTexture = sRGB;
            importer.SaveAndReimport();
        }

        public static void Bind(GameObject visual)
        {
            if (!visual) return;
            if (Cache.Count == 0) LoadCache();
            Renderer[] renderers = visual.GetComponentsInChildren<Renderer>(true);
            for (int r = 0; r < renderers.Length; ++r)
            {
                Material[] oldMaterials = renderers[r].sharedMaterials;
                bool modified = false;
                for (int i = 0; i < oldMaterials.Length; ++i)
                {
                    string family = Identify(oldMaterials[i], renderers[r].transform);
                    Material replacement;
                    if (family != null && Cache.TryGetValue(family, out replacement))
                    {
                        oldMaterials[i] = replacement;
                        modified = true;
                    }
                }
                if (modified) renderers[r].sharedMaterials = oldMaterials;
            }
        }

        private static void LoadCache()
        {
            string[] ids = AssetDatabase.FindAssets("t:Material", new[] { Output });
            foreach (string guid in ids)
            {
                string path = AssetDatabase.GUIDToAssetPath(guid);
                string filename = Path.GetFileNameWithoutExtension(path);
                if (!filename.StartsWith("L113_", StringComparison.OrdinalIgnoreCase)) continue;
                Material mat = AssetDatabase.LoadAssetAtPath<Material>(path);
                if (mat != null) Cache[filename.Substring(5)] = mat;
            }
        }

        private static string Identify(Material assigned, Transform transform)
        {
            const string tag = "__PSMAT__";
            for (Transform ancestor = transform; ancestor != null; ancestor = ancestor.parent)
            {
                string nodeName = ancestor.name;
                int position = nodeName.IndexOf(tag, StringComparison.OrdinalIgnoreCase);
                if (position < 0) continue;
                string suffix = nodeName.Substring(position + tag.Length);
                string hit = Resolve(suffix);
                if (hit != null) return hit;
            }
            if (!assigned) return null;
            string assignedName = assigned.name;
            if (assignedName.StartsWith("L113_", StringComparison.OrdinalIgnoreCase))
                assignedName = assignedName.Substring(5);
            return Resolve(assignedName);
        }

        private static string Resolve(string value)
        {
            if (Cache.ContainsKey(value)) return value;
            string best = null;
            foreach (string key in Cache.Keys)
            {
                if ((value.StartsWith(key + "_", StringComparison.OrdinalIgnoreCase) ||
                     value.StartsWith(key + " (", StringComparison.OrdinalIgnoreCase)) &&
                    (best == null || key.Length > best.Length)) best = key;
            }
            return best;
        }

        private static string Absolute(string assetPath)
        {
            string project = Directory.GetParent(Application.dataPath).FullName;
            return Path.Combine(project, assetPath.Replace('/', Path.DirectorySeparatorChar));
        }
    }
}
